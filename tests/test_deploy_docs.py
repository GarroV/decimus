"""Процедура раскатки не должна собирать образ без версии (#229).

`BUILD_SHA` приходит в сборку из окружения (`docker-compose.yml`), и собранный
без него образ поднимается **успешно**, отвечая `сборка: неизвестна`. То есть
единственный признак, по которому раскатанное отличается от собранного мимо
процедуры, пропадает молча — ровно это и случилось на раскатке 07.09.2026:
собрано по доке, а версии в образе нет.

Поэтому дока и `Makefile` проверяются как код: сборка без версии рядом — тот же
дефект, что и вызов функции без обязательного аргумента, только его не ловит
ни один компилятор. Проверяется ТЕКСТ процедуры, а не её исход: исход тут
всегда «успешно», в этом и беда.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ДОКА = Path("docs/08-deploy.md")
MAKEFILE = Path("Makefile")

#: Сборка образа в любом виде: `docker compose build`, `docker-compose build`.
_СБОРКА = re.compile(r"docker[ -]compose\s+build")

#: Сборка, приделанная к подъёму. Она молча ПРОПУСКАЕТ пересборку — проверено
#: на площадке 06.09.2026: после неё в образе не оказалось файлов, появившихся
#: в новом коде. Работает только явная пара `build` + `up`.
_ПОДЪЁМ_СО_СБОРКОЙ = re.compile(r"docker[ -]compose\s+up[^\n]*--build")


def _блоки(текст: str) -> list[str]:
    """Куски документа между заголовками — то, что читатель выполняет подряд."""
    return re.split(r"\n(?=#{2,4} )", текст)


@pytest.mark.parametrize("файл", [ДОКА, MAKEFILE])
def test_рядом_со_сборкой_образа_всегда_стоит_версия(файл: Path) -> None:
    """Раскатывающий по доке не обязан помнить про переменную — она в процедуре."""
    for блок in _блоки(файл.read_text(encoding="utf-8")):
        if not _СБОРКА.search(блок):
            continue
        assert "BUILD_SHA" in блок, (
            f"в {файл} есть сборка образа без BUILD_SHA рядом — "
            f"собранный по ней образ ответит «сборка: неизвестна»:\n"
            f"{блок[:400]}"
        )


@pytest.mark.parametrize("файл", [ДОКА, MAKEFILE])
def test_подъём_со_сборкой_в_процедуре_не_предлагается(файл: Path) -> None:
    """`up -d --build` пересборку пропускает — и молчит об этом."""
    for строка in файл.read_text(encoding="utf-8").splitlines():
        # Только команды, а не разбор в прозе: сама дока объясняет, ПОЧЕМУ
        # `up --build` не работает, и упоминает его в тексте намеренно.
        if not строка.lstrip().startswith(("docker compose", "docker-compose", "$")):
            continue
        assert not _ПОДЪЁМ_СО_СБОРКОЙ.search(строка), (
            f"в {файл} процедура предлагает `up --build`, а он пересборку пропускает "
            f"(проверено на площадке 06.09.2026): {строка.strip()!r}"
        )


def test_у_сборки_образа_есть_цель_в_makefile() -> None:
    """Процедура должна звать цель, а не пересказывать команды по памяти.

    Пересказанная команда живёт в трёх местах (дока установки, дока обновления,
    голова раскатывающего) и расходится молча. Цель — одно место, и именно она
    подставляет версию.
    """
    текст = MAKEFILE.read_text(encoding="utf-8")

    assert re.search(r"^image:", текст, re.MULTILINE), "в Makefile нет цели сборки образа"
    цель = текст[текст.index("\nimage:") :].split("\n\n")[0]
    assert "BUILD_SHA" in цель and "rev-parse" in цель, (
        "цель сборки не подставляет версию сама — тогда она не решает задачу #229"
    )
