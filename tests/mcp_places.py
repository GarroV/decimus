"""Где ещё записан каждый инструмент MCP — одна карта мест (#271).

Новый инструмент дважды краснел на приёмке в месте, о котором автор не знал:
список мест нигде не был записан. Теперь сверки каталога с тестами идут через
`сверить`, и её отказ сам называет все места, а не одно.
"""

from __future__ import annotations

from collections.abc import Iterable

#: Куда вносится новый инструмент, кроме самого каталога `src/mcp/catalogue.py`.
МЕСТА = (
    "tests/test_mcp_no_paths.py: ГОДНЫЕ и НЕГОДНЫЕ (аргументы для перебора)",
    "tests/test_mcp_catalogue.py: группа ИМЕНА_ИНСТРУМЕНТОВ_* и счёт в "
    "test_каталог_содержит_ровно_…",
    "tests/test_mcp_server.py: модуль обработчика в test_…_модул… (если не src.mcp.tools)",
    "docs/inventory.md: `make map`",
)


def сверить(место: str, записано: Iterable[str], каталог: Iterable[str]) -> None:
    """Набор имён в `место` совпадает с каталогом; иначе отказ с картой мест."""
    в_месте, в_каталоге = set(записано), set(каталог)
    нет = sorted(в_каталоге - в_месте)
    лишние = sorted(в_месте - в_каталоге)
    if not (нет or лишние):
        return
    карта = "\n  ".join(МЕСТА)
    raise AssertionError(
        f"{место} разошёлся с каталогом MCP: не внесены {нет}, лишние {лишние}.\n"
        f"Инструмент вносится во все места сразу:\n  {карта}"
    )
