"""Волна 1 (#340): ни один экран не читает и не пишет по тенанту стенда.

Статическая сверка: маршрут с `conf.tenant` зеленеет на любом тесте, где стенд и
человек из одного пространства, — а это все тесты, написанные до волны. Чтение
идёт по охвату вошедшего (`auth.current_reach`), запись — в его пространство
(`auth.current_tenant`).
"""

from __future__ import annotations

from pathlib import Path

#: Единственное законное место — счётчик попыток до входа (задача 4): до входа
#: пространство человека неизвестно, а счётчик — защита от перебора, не граница.
РАЗРЕШЕНО = {("auth.py", "рубеж = conf.tenant")}

КОРЕНЬ = Path(__file__).resolve().parent.parent / "src" / "web"


def test_данные_берутся_по_пространству_вошедшего() -> None:
    файлы = sorted(КОРЕНЬ.rglob("*.py"))
    assert len(файлы) > 10, f"сверка не нашла модулей веба в {КОРЕНЬ}"
    нарушения = []
    for путь in файлы:
        for номер, строка in enumerate(путь.read_text(encoding="utf-8").splitlines(), 1):
            if "conf.tenant" in строка and (путь.name, строка.strip()) not in РАЗРЕШЕНО:
                нарушения.append(f"{путь.name}:{номер}: {строка.strip()}")
    assert нарушения == [], "тенант стенда вместо тенанта вошедшего:\n" + "\n".join(нарушения)


def test_мост_охвата_по_тенанту_снят() -> None:
    """`own_reach` был мостом задачи 5; в вебе чтение — только охват вошедшего."""
    мосты = [
        путь.name
        for путь in sorted(КОРЕНЬ.rglob("*.py"))
        if "own_reach" in путь.read_text(encoding="utf-8")
    ]
    assert мосты == [], f"чтение по тенанту, а не по охвату вошедшего: {мосты}"
