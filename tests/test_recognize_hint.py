"""#1267, D646 п. 3: мгновенная подсказка — 2–3 пункта по карте слов, без модели.

Ядро: подсказка показывается аудитору как «предварительно», и он вправе нажать
её, не дожидаясь модели. Ошибка здесь молчалива: в записи окажется пункт, до
которого аудитор не дочитал. Поэтому проверяется порядок (нужный пункт стоит
наверху, название зоны слова-пункта не поднимает), чистота (служебные пункты и
сводные строки не показываются, правило 8) и тишина (нет совпадения — пусто).
"""

from __future__ import annotations

from pathlib import Path

import pytest
from conftest import live_data_env, requires_data  # noqa: F401 -- фикстура

from src.recognize.config import NO_CHAT
from src.recognize.hint import HINT_MAX, rank

#: Заголовок и шапка таблицы, которой тест дописывает свои строки в карту.
ШАПКА = "\n## Проверка подсказки\n\n| Что на кадре | Пункты |\n|---|---|\n"


def _карта_со_строками(data_copy: Path, monkeypatch: pytest.MonkeyPatch, *строки: str) -> None:
    карта = data_copy / "photo-cues.md"
    карта.write_text(
        карта.read_text(encoding="utf-8") + ШАПКА + "".join(f"| {s} |\n" for s in строки),
        encoding="utf-8",
    )
    monkeypatch.setenv("AUDIT_DATA_DIR", str(data_copy))


def _коды(note: str, zone: str | None = None) -> list[str]:
    return [h.code for h in rank(note, zone, chat_id=NO_CHAT)]


def test_пол_в_названной_зоне_поднимает_пункт_про_пол(domain_env: Path) -> None:
    """Образец владельца: «грязный пол в тепловом участке» — это пол, а не участок."""
    коды = _коды("грязный пол на тепловом участке")

    assert коды and коды[0] == "CLN01", коды


def test_название_зоны_не_поднимает_пункты_про_неё_саму(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Строка с названием зоны («… на тепловом участке») не стоит выше строки про пол.

    На боевой карте так и есть: строка про термометр с названием цеха делит с
    фразой аудитора два слова, а «Пол» — одно, и без вычитания зоны термометр
    оказывался первым.
    """
    _карта_со_строками(data_copy, monkeypatch, "Термометр на стене теплового участка | PRD07")

    коды = _коды("грязный пол на тепловом участке")

    assert коды[0] == "CLN01", коды


def test_слова_без_совпадения_дают_пустоту(domain_env: Path) -> None:
    assert _коды("ничего особенного не видно") == []
    assert _коды("") == []
    assert _коды("   ") == []


def test_не_больше_предела(domain_env: Path) -> None:
    коды = _коды("тара без ярлыка пол печь шкаф весы розетка нож мука аптечка")

    assert 0 < len(коды) <= HINT_MAX


def test_слова_колонки_выбирают_грязь_или_поломку(domain_env: Path) -> None:
    """«Печь | CLN05 | TEH05»: грязь и поломка — разные вопросы, слова их разводят."""
    грязь = _коды("печь в нагаре", "hot_kitchen")
    поломка = _коды("печь сломана", "hot_kitchen")

    assert грязь[0] == "CLN05" and "TEH05" not in грязь[:1]
    assert поломка[0] == "TEH05"


def test_служебные_пункты_не_показываются(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Правило 8: сводная строка процесса и пункты ручного решения — не подсказка."""
    _карта_со_строками(
        data_copy,
        monkeypatch,
        "Сводка заготовок процесса | PRD16",
        "Журнал смены не заполнен | MGM22",
    )

    assert _коды("сводка заготовок процесса") == []
    assert _коды("журнал смены не заполнен") == []


def test_пункты_названной_зоны_идут_раньше(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Одна строка — два пункта с разными зонами: пункт зоны экрана стоит первым."""
    _карта_со_строками(data_copy, monkeypatch, "Половое покрытие | CLN01, CLN12")

    кухня = _коды("половое покрытие", "hot_kitchen")
    зал = _коды("половое покрытие", "dining")

    assert кухня[0] == "CLN01"
    assert зал[0] == "CLN12"


def test_у_подсказки_один_пункт_один_раз(domain_env: Path) -> None:
    коды = _коды("пол участка грязный пол", "hot_kitchen")

    assert len(коды) == len(set(коды))


# ── боевая карта: образец владельца из #1267 ────────────────────────────


@requires_data
def test_боевая_карта_грязный_пол_в_горячем_цехе(live_data_env: Path) -> None:  # noqa: F811
    """«Даже банальная вещь — грязный пол в горячем цехе» (D646): CLN03 в подсказке первым.

    Зона не названа на экране — название зоны только в словах. Без вычитания
    зоны первым вставала строка про термометр с названием цеха.
    """
    коды = _коды("грязный пол в горячем цехе")

    assert коды[:1] == ["CLN03"], коды
    assert "MGM02" not in коды[:1], "зона в словах подняла пункт про термометр"
