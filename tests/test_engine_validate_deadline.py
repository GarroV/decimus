"""Нарушение без срока устранения обязано валить `manage.py validate`.

Колонка `days` — не украшение таблицы: из неё в отчёт партнёру попадает дата,
к которой нарушение должно быть устранено. Пустую клетку движок читает нулём
(`src/domain/checklist.py::_days`), а ноль в отчёте означает «устранить
немедленно». То есть забытый срок не выглядит забытым: партнёр получает
документ, где рядовое нарушение требует немедленного исправления, и спорить с
этим ему нечем — цифра стоит в официальной бумаге.

`validate` этого не ловил. Проверка срока выглядела так:
`int(float(r.get("days") or 0))` — пустая клетка подставлялась нулём ещё до
проверки, и ловился только срок, записанный словами. Отсюда правило: сроком
считается проставленный срок, а не отсутствие клетки.

Почему отказ, а не подстановка умолчания: умолчание — это решение о цене
ответа, и принимает его владелец методики, а не программа, молча выбравшая
десять дней вместо трёх. Пункт без срока нужно дозаполнить, а не угадать.

Границы, которые тест держит специально:
- **D0 без срока — норма.** D0 не нарушение, устранять нечего; в боевой
  методике таких строк три, и запрет на пустую клетку сломал бы её.
- **Штатное заведение не ломается:** `manage.py add` без `--days` сам пишет 10,
  пустая клетка возникает только при ручной правке файла.
"""

from __future__ import annotations

import csv
from collections.abc import Callable
from pathlib import Path

import pytest
from conftest import ROOT, Run, run_engine

MANAGE = ROOT / "engine" / "manage.py"


@pytest.fixture
def manage(data_copy: Path, workdir: Path) -> Callable[..., Run]:
    """`manage.py` на копии методики. Боевой `data/` не трогается."""

    def call(*args: str) -> Run:
        return run_engine(MANAGE, *args, cwd=workdir, env_extra={"CHECKLIST_DIR": str(data_copy)})

    return call


def _стереть_срок(путь: Path, код: str) -> None:
    """Убрать срок у названного пункта. Только модулем `csv`.

    Правка построчным `split(",")` уже давала ложно зелёный прогон: в строках
    чек-листа запятые есть внутри кавычек, и значение уезжало в соседнюю
    колонку, а чтение этого не замечало.
    """
    with путь.open(encoding="utf-8", newline="") as f:
        читатель = csv.DictReader(f)
        поля = читатель.fieldnames or []
        строки = list(читатель)
    нашёлся = False
    for строка in строки:
        if строка["id"] == код:
            строка["days"] = ""
            нашёлся = True
    assert нашёлся, f"пункт {код} в копии методики не найден"
    with путь.open("w", encoding="utf-8", newline="") as f:
        писатель = csv.DictWriter(f, fieldnames=поля)
        писатель.writeheader()
        писатель.writerows(строки)


def _любой_пункт(путь: Path, *, нарушение: bool) -> str:
    """Код пункта вида `violation` с уровнями D1/D2/D3 — или только с D0.

    Вид обязателен: `validate` проверяет содержимое только у `violation`, а
    `info` и `aggregate` не смотрит вовсе. Без этого условия «пункт без
    нарушения» доставался видом, который не проверяется ни при каких правках, и
    тест границы оставался зелёным даже со снятой границей — поймано порчей.
    """
    with путь.open(encoding="utf-8", newline="") as f:
        for строка in csv.DictReader(f):
            if строка.get("kind") != "violation" or not строка.get("id"):
                continue
            уровни = {x.strip() for x in (строка.get("levels") or "").split(";") if x.strip()}
            if bool(уровни & {"D1", "D2", "D3"}) is нарушение:
                return строка["id"]
    pytest.skip(f"в синтетической методике нет violation с нарушение={нарушение}")


def test_нарушение_без_срока_валит_проверку(manage: Callable[..., Run], data_copy: Path) -> None:
    """Главная проверка задачи: пустой срок у D1/D2/D3 — отказ, а не тишина."""
    чек_лист = data_copy / "checklist.csv"
    код = _любой_пункт(чек_лист, нарушение=True)
    _стереть_срок(чек_лист, код)

    итог = manage("validate")

    assert итог.code != 0, f"validate принял нарушение без срока: {итог.out}"
    assert код in итог.out, f"в отказе не назван пункт {код}: {итог.out}"
    assert "срок" in итог.out.lower(), f"в отказе не сказано, чего не хватает: {итог.out}"


def test_отказ_называет_цену_ошибки(manage: Callable[..., Run], data_copy: Path) -> None:
    """Отказ объясняет, ЧЕМ это кончится для партнёра, а не только чего нет.

    Проверка формата отказов проекта: человек за терминалом должен понять, что
    исправить, без чтения кода — пустая клетка читается как «немедленно».
    """
    чек_лист = data_copy / "checklist.csv"
    код = _любой_пункт(чек_лист, нарушение=True)
    _стереть_срок(чек_лист, код)

    итог = manage("validate")

    assert "days" in итог.out, f"в отказе не названа колонка: {итог.out}"
    assert "немедленн" in итог.out.lower(), f"в отказе не названа цена ошибки: {итог.out}"


def test_пункт_без_нарушения_без_срока_остаётся_нормой(
    manage: Callable[..., Run], data_copy: Path
) -> None:
    """Граница: D0 устранять нечего, и пустая клетка у него законна.

    Без этой границы проверка сломала бы боевую методику — там три таких строки.
    """
    чек_лист = data_copy / "checklist.csv"
    код = _любой_пункт(чек_лист, нарушение=False)
    _стереть_срок(чек_лист, код)

    итог = manage("validate")

    assert итог.code == 0, f"validate отказал на законном D0 без срока: {итог.out}"


def test_боевая_методика_проверку_проходит() -> None:
    """Сторож от правки, которая чинит тест ценой рабочей методики."""
    итог = run_engine(MANAGE, "validate", cwd=ROOT, env_extra={"CHECKLIST_DIR": str(ROOT / "data")})

    assert итог.code == 0, f"боевая методика перестала проходить validate: {итог.out}"
