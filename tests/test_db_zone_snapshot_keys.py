"""Аналитика по зонам читает из снимка ТЕ ИМЕНА, которые туда кладёт движок.

Зачем отдельная проверка. Снимок `inspections.by_zone` — это словарь, а не
колонки: опечатка в имени ключа внутри SQL не ломает запрос, не роняет
страницу и не краснит прогон. Она просто не находит ни одной строки, и экран
честным голосом сообщает «потерь не записано» при записанных потерях.

Именно это и случилось (#354): запросы искали `deduction`, движок пишет
`loss`, и блок «Где сеть теряет проценты» стоял пустым, пока его не открыли
на живой базе глазами. Проверки экрана до SQL не доходят — они подменяют слой
данных, — поэтому ловить такое обязана проверка самого текста запроса.

Сверяется с полями `ZoneScore`, а не со списком имён, записанным здесь:
список пришлось бы править руками, и он разошёлся бы ровно так же молча.
"""

from __future__ import annotations

import dataclasses
import re

from src.db import queries
from src.domain.models import ZoneScore

#: Как SQL достаёт поле из снимка зоны: `zone.value ->> 'имя'`.
ДОСТАЁТ = re.compile(r"zone\.value\s*->>\s*'([a-z_]+)'")

#: Запросы, которые ходят внутрь снимка. Берутся по имени из модуля, а не
#: перечислением текста: добавится третий такой запрос — проверка его увидит.
ЗАПРОСЫ = {
    имя: значение
    for имя, значение in vars(queries).items()
    if имя.endswith("_SQL") and isinstance(значение, str) and "zone.value" in значение
}


def test_снимок_зоны_читается_по_настоящим_именам_полей() -> None:
    # Arrange
    поля = {поле.name for поле in dataclasses.fields(ZoneScore)}

    # Act
    прочитанные = {
        (имя, ключ) for имя, sql in ЗАПРОСЫ.items() for ключ in ДОСТАЁТ.findall(sql)
    }

    # Assert
    чужие = {(имя, ключ) for имя, ключ in прочитанные if ключ not in поля}
    assert not чужие, (
        f"запрос читает из снимка зоны поле, которого движок туда не кладёт: {sorted(чужие)}. "
        f"Движок пишет {sorted(поля)} (`asdict(ZoneScore)` в `src/db/push.py`). "
        "Такое расхождение не роняет запрос — оно молча обнуляет аналитику."
    )


def test_проверка_вообще_смотрит_на_запросы() -> None:
    """Сторож без подопечных зелен всегда — и это худший вид зелёного.

    Переименуют запрос или уберут `zone.value` из текста — и проверка выше
    начнёт проходить на пустом множестве, ничего не проверяя.
    """
    # Assert
    assert ЗАПРОСЫ, "не найдено ни одного запроса, читающего снимок зоны"
    assert any(ДОСТАЁТ.findall(sql) for sql in ЗАПРОСЫ.values()), (
        "запросы найдены, но ни один не достаёт поля из снимка — проверка ослепла"
    )
