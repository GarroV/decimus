"""Шрифты, которые просит ядро дизайн-системы, приложение действительно отдаёт.

ПОЧЕМУ ЭТА ПРОВЕРКА ЗАВЕДЕНА. 24.09.2026 визуал перевели на канон владельца:
токены типографики уехали в продукт (`--font-ui: 'Manrope'`, `--font-num:
'Space Grotesk'`), а самих файлов шрифтов не было ни здесь, ни в дизайн-системе
— и ссылки наружу тоже. Браузер в таком случае молча берёт системное
начертание: страница читается, отвечает 200, все прежние проверки зелёные, и
единственный признак поломки — человек, который смотрит на экран и говорит, что
нового визуала не видит. Ровно так и вышло.

ЧТО СТОРОЖИТ. Каждый `url(...)` из `@font-face` разбирается прямо из копии
ядра, и по нему делается настоящий запрос к приложению. То есть проверка знает
не то, что «шрифты где-то есть», а то, что по адресу, который возьмёт браузер,
лежит настоящий woff2. Раскатка `forma`, положившая CSS без каталога `fonts/`,
красит эту проверку — а не экран владельца.

ПОЧЕМУ НЕ ХВАТАЕТ СТОРОЖА `forma`. Тот проверяет свой репозиторий: ядро и
файлы рядом с ним. Сюда файлы приезжают копией, и потеряться могут именно в
переносе — каталог не положен, путь разошёлся, статика смонтирована не оттуда.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest
from flask.testing import FlaskClient
from test_web_app import ТЕНАНТ
from web_harness import собрать

#: Копия ядра дизайн-системы у продукта. Она же — источник списка шрифтов:
#: список руками не ведётся намеренно, иначе он разойдётся с CSS молча.
ЯДРО = Path(__file__).resolve().parent.parent / "src" / "web" / "static" / "dodo-ds.css"

#: `url('fonts/manrope-latin.woff2')` → `fonts/manrope-latin.woff2`.
ССЫЛКА = re.compile(r"url\(['\"]?([^'\")]+\.woff2)['\"]?\)")

#: Первые байты файла woff2 (сигнатура `wOF2`). Отличает настоящий шрифт от
#: страницы ошибки, отданной с кодом 200 — такое бывает у перехватчиков путей.
ПОДПИСЬ = b"wOF2"


def шрифты_из_ядра() -> list[str]:
    return sorted(set(ССЫЛКА.findall(ЯДРО.read_text(encoding="utf-8"))))


@pytest.fixture
def клиент() -> FlaskClient:
    return собрать(tenant=ТЕНАНТ).test_client()


def test_ядро_вообще_просит_шрифты() -> None:
    """Половина проверки — что просить есть чего.

    Без неё разбор пустого списка даёт зелёный прогон на ядре, из которого
    `@font-face` выкинули целиком: «ни один шрифт не отдаётся неправильно»
    формально верно и совершенно бесполезно.
    """
    найдено = шрифты_из_ядра()
    assert найдено, (
        f"в {ЯДРО.name} нет ни одного @font-face с url(...*.woff2) — значит "
        f"типографика канона держится на том, что нужные шрифты уже стоят в "
        f"системе у смотрящего. У владельца они не стояли"
    )


@pytest.mark.parametrize("путь", шрифты_из_ядра())
def test_шрифт_отдаётся_по_тому_же_адресу_что_просит_css(
    клиент: FlaskClient, путь: str
) -> None:
    # Arrange — адрес собирается так же, как его соберёт браузер: относительно
    # каталога, из которого отдан сам CSS.
    адрес = f"/static/{путь}"

    # Act
    ответ = клиент.get(адрес)

    # Assert
    assert ответ.status_code == 200, (
        f"{ЯДРО.name} просит {путь}, а {адрес} отвечает {ответ.status_code}. "
        f"Браузер молча возьмёт системное начертание, и нового визуала не будет "
        f"видно — при полностью зелёном прогоне. Файлы кладёт раскатка "
        f"`python tools/spread.py --apply` из клона forma"
    )
    assert ответ.data[:4] == ПОДПИСЬ, (
        f"{адрес} отвечает 200, но это не woff2: первые байты {ответ.data[:4]!r}"
    )
