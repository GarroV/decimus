def test_слова_аудитора_не_трогаются(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """Скобка в словах человека — его скобка, а не служебная пометка методики.

    Формулировка записи отличается от вопроса пункта, значит её писал аудитор,
    и снимать с неё что-либо продукт права не имеет.
    """
    свои_слова = "(D1, D2) — так пометил ярлык сам повар, ярлыка образца А на таре нет"
    started(
        "add",
        "--qid",
        ПУНКТ_D1D2,
        "--level",
        "D2",
        "--zone",
        "fridge",
        "--evidence",
        свои_слова,
    )
    r = report("html")
    assert r.code == 0, r.text
    assert свои_слова in r.out, "продукт выправил слова аудитора вместо пометки методики"


def test_запись_без_слов_печатается_вопросом_без_префикса(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """Пустая формулировка подменяется в письме вопросом пункта — тоже без пометки.

    Сама подмена под вопросом и разбирается отдельно: T248 (блок `engine-fix`)
    — в отчёте такой строки нет вовсе, и письмо с отчётом на одних данных
    расходятся. Здесь закреплено ТОЛЬКО отсутствие служебной пометки; поведение
    подмены этот тест не благословляет и намеренно оставлен зелёным до и после
    правки T234.
    """
    started("add", "--qid", ПУНКТ_D1D2, "--level", "D2", "--zone", "fridge")
    r = report("letter")
    assert r.code == 0, r.text
    assert ПРЕФИКС_D1D2 not in r.out
    assert "Заготовка размечена ярлыком образца А" in r.out


def _боевой_пункт_с_префиксом() -> tuple[str, str, str, str]:
    """Первый пункт боевой методики, у которого пометка класса стоит в формулировке."""
    зоны = [z["code"] for z in csv.DictReader((DATA / "zones.csv").open(encoding="utf-8"))]
    for row in csv.DictReader((DATA / "checklist.csv").open(encoding="utf-8")):
        вопрос = row["question_ru"]
        классы = [x for x in (row["levels"] or "").split(";") if x]
        if row["kind"] != "violation" or not классы or not вопрос.startswith("(D"):
            continue
        свои = [z for z in (row["zones"] or "").split(",") if z and z != "*"]
        return row["id"], классы[0], (свои[0] if свои else зоны[0]), вопрос
    raise AssertionError("в боевой методике не нашлось пункта с пометкой класса в формулировке")


@requires_data
def test_боевая_методика_префикса_партнёру_не_отдаёт(tmp_path: Path) -> None:
    """Сторож на настоящих данных: на боевой методике так размечен 31 пункт из 136."""
    qid, уровень, зона, вопрос = _боевой_пункт_с_префиксом()
    рабочая = tmp_path / "chat-live"
    рабочая.mkdir()
    состояние = рабочая / "inspection.json"

    def движок(скрипт: Path, *args: str) -> Run:
        return run_engine(скрипт, *args, cwd=рабочая, state=состояние, data_dir=DATA)

    r = движок(AUDIT, "init", "--unit", "Тестовая", "--auditor", "Тест", "--date", "2026-08-21")
    assert r.code == 0, r.text
    r = движок(AUDIT, "add", "--qid", qid, "--level", уровень, "--zone", зона, "--evidence", вопрос)
    assert r.code == 0, r.text

    отчёт = движок(REPORT, "html")
    assert отчёт.code == 0, отчёт.text
    assert вопрос not in отчёт.out, f"пометка класса пункта {qid} напечатана партнёру в отчёте"

    письмо = движок(REPORT, "letter")
    assert письмо.code == 0, письмо.text
    assert вопрос not in письмо.out, f"пометка класса пункта {qid} напечатана партнёру в письме"
