"""T325: чей адрес считает ограничитель, когда впереди стоит туннель.

Ошибка здесь молчит вдвойне. Поверить `X-Forwarded-For` без своего звена
впереди — значит раздать перебирающему бесконечный запас «адресов» одной
строкой в запросе: счётчик по адресу перестаёт считать что-либо, а выглядит
работающим. Не поверить там, где звено есть, — значит свести всех, кто пришёл
снаружи, в один общий ключ.
"""

from __future__ import annotations

from flask import Flask

from src.web.remote import FORWARDED_FOR, client_address

app = Flask(__name__)

СВОЙ = "203.0.113.7"
ЧУЖОЙ = "198.51.100.200"
ТУННЕЛЬ = "127.0.0.1"


def адрес(*, trusted_proxies: int, remote: str = ТУННЕЛЬ, цепочка: str | None = None) -> str:
    заголовки = {FORWARDED_FOR: цепочка} if цепочка is not None else {}
    with app.test_request_context(
        "/login", headers=заголовки, environ_base={"REMOTE_ADDR": remote}
    ):
        return client_address(trusted_proxies=trusted_proxies)


def test_без_своих_звеньев_берётся_адрес_соединения() -> None:
    assert адрес(trusted_proxies=0, remote=СВОЙ) == СВОЙ


def test_без_своих_звеньев_заголовок_не_слушают_вовсе() -> None:
    """Умолчание: подставленный заголовок нового ключа не даёт."""
    assert адрес(trusted_proxies=0, remote=ТУННЕЛЬ, цепочка=ЧУЖОЙ) == ТУННЕЛЬ


def test_за_одним_звеном_берётся_тот_кого_записал_туннель() -> None:
    assert адрес(trusted_proxies=1, цепочка=СВОЙ) == СВОЙ


def test_подделанное_начало_цепочки_не_даёт_нового_ключа() -> None:
    """Слева пишет пришедший, справа — наш туннель. Берём справа.

    Взять левый край означало бы считать попытки по строке, которую
    перебирающий меняет на каждой попытке.
    """
    assert адрес(trusted_proxies=1, цепочка=f"{ЧУЖОЙ}, {СВОЙ}") == СВОЙ


def test_за_двумя_звеньями_отсчёт_идёт_на_одно_глубже() -> None:
    assert адрес(trusted_proxies=2, цепочка=f"{ЧУЖОЙ}, {СВОЙ}, 10.0.0.1") == СВОЙ


def test_цепочка_короче_обещанной_откатывает_к_адресу_соединения() -> None:
    """Осторожный конец развилки: общий ключ строже, чем доверие к пустоте."""
    assert адрес(trusted_proxies=2, remote=ТУННЕЛЬ, цепочка=ЧУЖОЙ) == ТУННЕЛЬ


def test_пустая_цепочка_не_даёт_пустого_ключа() -> None:
    assert адрес(trusted_proxies=1, remote=ТУННЕЛЬ, цепочка=" , ") == ТУННЕЛЬ
