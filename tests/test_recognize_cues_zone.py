"""T262: колонка «Зона» в карте кадров — словарь «объект → зона».

Владелец сформулировал требование прямо: «пицца-печь это всегда горячий цех и
никакой другой, а стеллажи бывают в разных цехах — и там нужно уточнение».
Значит, жёсткость задаёт ЧЕЛОВЕК в данных, а не вывод по пересечению зон
пунктов: замер 07.09.2026 показал, что такой вывод даёт ложную однозначность
(«стеллаж» → сухой склад, неверно) и молчит на том, что владелец назвал
жёстким («станция закусок»).

Зона живёт в той же таблице, что и пункты объекта, а не отдельным файлом: два
списка объектов гарантированно разошлись бы (правило «один факт — одно
каноническое место»).

**Пустая зона — законное значение и означает «спросить».** Ошибкой данных она
не является: на большинстве объектов зона не фиксирована, и отказ здесь сделал
бы обязательным то, что обязательным не является (тот же принцип, что у
отсутствующей карты — D068).

Карта здесь собирается прямо в тесте: проверяется правило разбора, а не
содержимое чьей-либо методики.
"""

from __future__ import annotations

from pathlib import Path

from src.recognize.config import NO_CHAT
from src.recognize.cues import Cue, load_cues, match_zones

КАРТА = """# Карта

## Подсказки по объектам

| Объект | Грязь | Поломка | Зона | Откуда |
|---|---|---|---|---|
| Печь | CLN05 | TEH05 | hot_kitchen | вопрос |
| Стеллаж | CLN07 | TEH04 | | боевая |
"""


def написать(tmp_path: Path, текст: str) -> Path:
    путь = tmp_path / "photo-cues.md"
    путь.write_text(текст, encoding="utf-8")
    return путь


def test_колонка_зоны_читается_по_заголовку(tmp_path: Path) -> None:
    строки = load_cues(написать(tmp_path, КАРТА), chat_id=NO_CHAT)

    печь = next(c for c in строки if c.phrase == "Печь")
    assert печь.zone == "hot_kitchen", "зона объекта не прочитана из колонки «Зона»"


def test_пустая_зона_законна_и_означает_спросить(tmp_path: Path) -> None:
    строки = load_cues(написать(tmp_path, КАРТА), chat_id=NO_CHAT)

    стеллаж = next(c for c in строки if c.phrase == "Стеллаж")
    assert стеллаж.zone == "", "пустая зона обязана читаться как «спросить», а не ломать разбор"
    assert стеллаж.codes == ("CLN07", "TEH04"), (
        "строка с пустой зоной перестала отдавать свои коды — пустое значение "
        "превратилось в ошибку данных"
    )


def test_колонка_зоны_кодом_не_становится(tmp_path: Path) -> None:
    """Зона стоит между колонками кодов, и путать её с ними нельзя."""
    строки = load_cues(написать(tmp_path, КАРТА), chat_id=NO_CHAT)

    печь = next(c for c in строки if c.phrase == "Печь")
    assert печь.codes == ("CLN05", "TEH05"), "в коды строки попало что-то лишнее"
    assert [заголовок for заголовок, _ in печь.by_column] == ["Грязь", "Поломка"], (
        "колонка зоны попала в разбор колонок кодов"
    )


def test_место_колонки_в_таблице_значения_не_имеет(tmp_path: Path) -> None:
    """Порядок колонок у управляющей компании свой в каждом разделе."""
    карта = """# Карта

## Подсказки по объектам

| Объект | Зона | Грязь | Поломка |
|---|---|---|---|
| Печь | hot_kitchen | CLN05 | TEH05 |
"""
    (печь,) = load_cues(написать(tmp_path, карта), chat_id=NO_CHAT)

    assert печь.zone == "hot_kitchen", "колонка зоны прочитана по номеру, а не по заголовку"
    assert печь.codes == ("CLN05", "TEH05")


def test_заголовок_колонки_читается_на_языке_карты(tmp_path: Path) -> None:
    """Карта монолингвальна, но на каком языке — код заранее не знает (T192)."""
    карта = """# Map

## Object cues

| Object | Dirt | Breakage | Zone |
|---|---|---|---|
| Oven | CLN05 | TEH05 | hot_kitchen |
"""
    (печь,) = load_cues(написать(tmp_path, карта), chat_id=NO_CHAT)

    assert печь.zone == "hot_kitchen", "английский заголовок колонки зоны не узнан"


def test_карта_без_колонки_зоны_разбирается_как_раньше(tmp_path: Path) -> None:
    """Колонка добавляется без ломки формата: её нет — зон нет, и только."""
    карта = """# Карта

## Подсказки по объектам

| Объект | Грязь | Поломка |
|---|---|---|
| Печь | CLN05 | TEH05 |
"""
    (печь,) = load_cues(написать(tmp_path, карта), chat_id=NO_CHAT)

    assert печь.zone == ""
    assert печь.codes == ("CLN05", "TEH05")


def test_зона_поднимается_словами_комментария() -> None:
    """`match_zones` отвечает тем же совпадением, что и `match_cues` кодами."""
    строки = (
        Cue(phrase="Печь", codes=("CLN05", "TEH05"), zone="hot_kitchen"),
        Cue(phrase="Стеллаж", codes=("CLN07", "TEH04")),
    )

    assert match_zones("печь грязная", строки) == ("hot_kitchen",)
    assert match_zones("стеллаж грязный", строки) == (), (
        "строка с пустой зоной обязана молчать, а не отдавать пустую строку"
    )
    assert match_zones("ничего похожего", строки) == ()


def test_две_разные_зоны_в_совпавших_строках_отдаются_обе() -> None:
    """Решать за человека разбор не вправе: несколько зон — повод спросить."""
    строки = (
        Cue(phrase="Стеллаж в горячем", codes=("CLN07",), zone="hot_kitchen"),
        Cue(phrase="Стеллаж в сухом складе", codes=("CLN07",), zone="dry_storage"),
    )

    assert set(match_zones("стеллаж грязный", строки)) == {"hot_kitchen", "dry_storage"}
