"""Список выборки и позиционный разбор не расходятся (T345, #262).

Разбор строки курсора — позиционный: `row[7]` это версия чек-листа только
потому, что она седьмая в `select`. Колонка, вставленная в СЕРЕДИНУ списка,
сдвигает всё, что правее, и проверка молча начинает печатать в письме
партнёру одно вместо другого — с верным на вид результатом и нулевым кодом
возврата.

Базы здесь не нужно: расхождение видно в самом тексте запроса. Тест поэтому
дешёвый и гоняется везде, а не только там, где поднят Postgres.
"""

from __future__ import annotations

import inspect
import re

from src.db import queries
from src.db.models import InspectionRow

#: Запросы, чью строку разбирает `_row_to_inspection`: список целиком и список
#: по точке. Они обязаны отдавать один и тот же набор колонок — разбор у них
#: общий, и разойтись им значит печатать разное в одних и тех же полях.
#: Карточка (`_GET_INSPECTION_SQL`) отдаёт свой, более широкий набор и
#: разбирается отдельно, поэтому сюда не входит.
ЗАПРОСЫ = ("_LIST_ALL_SQL", "_LIST_BY_UNIT_SQL")


def колонок_в_запросе(sql: str) -> int:
    """Сколько выражений отдаёт `select` верхнего уровня.

    Запятые внутри скобок не считаются: подзапрос `(select count(*) ...)` —
    это одна колонка, а не две.
    """
    return len(колонки_запроса(sql))


def колонки_запроса(sql: str) -> list[str]:
    """Выражения `select` верхнего уровня, по порядку.

    Скобки считаются, потому что и запятая, и само слово `from` встречаются
    внутри подзапроса — `(select count(*) from findings ...)` это одна колонка,
    а наивная разрезка по первому `from` обрубила бы список на ней.
    """
    # Комментарии вырезаются до разбора: запятая внутри `-- ...` не колонка, а
    # проверка, считающая её колонкой, краснеет на пояснении к коду.
    без_комментариев = "\n".join(re.sub(r"--.*$", "", строка) for строка in sql.split("\n"))
    хвост = re.split(r"\bselect\b", без_комментариев, maxsplit=1)[1]
    глубина = 0
    накопитель: list[str] = []
    текущая = ""
    слова = re.split(r"(\W)", хвост)
    for кусок in слова:
        if кусок == "(":
            глубина += 1
        elif кусок == ")":
            глубина -= 1
        elif глубина == 0 and кусок.lower() == "from":
            break
        if глубина == 0 and кусок == ",":
            накопитель.append(текущая.strip())
            текущая = ""
            continue
        текущая += кусок
    накопитель.append(текущая.strip())
    return [ч for ч in накопитель if ч]


def индексов_в_разборе() -> int:
    """На сколько позиций смотрит разбор строки: максимальный `row[N]` плюс один."""
    исходник = inspect.getsource(queries._row_to_inspection)
    индексы = [int(n) for n in re.findall(r"row\[(\d+)\]", исходник)]
    assert индексы, "разбор строки не читает ни одной позиции — тест смотрит не туда"
    return max(индексы) + 1


def test_все_запросы_отдают_один_и_тот_же_набор_колонок() -> None:
    наборы = {имя: колонок_в_запросе(getattr(queries, имя)) for имя in ЗАПРОСЫ}
    assert len(set(наборы.values())) == 1, f"запросы разошлись по числу колонок: {наборы}"


def test_разбор_читает_ровно_столько_колонок_сколько_отдаёт_запрос() -> None:
    assert колонок_в_запросе(queries._LIST_ALL_SQL) == индексов_в_разборе()


def test_код_чек_листа_едет_последним_а_не_в_середине() -> None:
    """Дописывать можно только в конец, пока разбор позиционный."""
    колонки = колонки_запроса(queries._LIST_ALL_SQL)
    assert "i.checklist_code" in колонки[-1]


def test_проверка_несёт_код_чек_листа_с_понятным_умолчанием() -> None:
    """Историю заливают программно, и `None` в коде чек-листа не имеет смысла."""
    поле = InspectionRow.__dataclass_fields__["checklist_code"]
    assert поле.default == "bizdev"


def test_карточка_тоже_несёт_код_чек_листа() -> None:
    """Письмо партнёру собирается по карточке — без кода она не знает, по чему проверяли."""
    assert any("checklist_code" in к for к in колонки_запроса(queries._GET_INSPECTION_SQL))
