"""#335: письмо обезличено во ВСЕХ шаблонах, а не в том одном, что рендерил тест.

Подпись и обращение по имени убраны из письма решением владельца (D175):
подпись у каждого стоит в самой почте, а отправить письмо должен любой человек
команды. Проверка на это была — и оказалась дырявой: порча при 8341ddd вернула
подпись ТОЛЬКО в `LETTER_PLAN` и прошла ЗЕЛЁНОЙ, потому что единственный тест
рендерил письмо по чистой проверке, то есть `LETTER_CLEAN`. Поймалось лишь
когда подпись вернули во все три русских шаблона.

Шаблонов у письма шесть: `LETTER_PLAN`, `LETTER_CLEAN`, `LETTER_EMPTY` на два
языка. Выбор между ними делает сам движок по составу находок, поэтому тест
задаёт СОСТАВ, а не шаблон: без находок — `EMPTY`, только D1 — `CLEAN`, с D2 —
`PLAN`. Так проверка не расходится с движком, если он поменяет условие выбора.

Письмо читает человек вне команды, и правка, уехавшая в непокрытый шаблон,
обнаруживается уже у партнёра.
"""

from __future__ import annotations

import csv
from pathlib import Path

import pytest
from conftest import AUDIT, DATA, REPORT, Run, requires_data, run_engine

#: Приметы личного письма. Подписи ищем всеми формами, какие в шаблонах были и
#: могут вернуться: одна строка поймала бы только свой язык.
ПОДПИСИ = ("С уважением", "Best regards", "Kind regards", "Dodo Brands")

#: Имя аудитора, которым заводится проверка. Оно же — то, что стояло в подписи:
#: если имя всплывёт в письме, значит подпись или обращение вернулись.
АУДИТОР = "Василий Гарро"


def _пункт_с_уровнем(уровень: str) -> tuple[str, str]:
    """Пункт боевой методики, по которому можно завести запись нужного класса.

    Берётся из самих данных, а не списком в тесте: методика правится, и
    зашитый код пункта однажды перестал бы существовать молча.
    """
    зоны = [z["code"] for z in csv.DictReader((DATA / "zones.csv").open(encoding="utf-8"))]
    for row in csv.DictReader((DATA / "checklist.csv").open(encoding="utf-8")):
        классы = [x for x in (row["levels"] or "").split(";") if x]
        if row["kind"] != "violation" or уровень not in классы:
            continue
        свои = [z for z in (row["zones"] or "").split(",") if z and z != "*"]
        return row["id"], (свои[0] if свои else зоны[0])
    raise AssertionError(f"в боевой методике нет пункта с классом {уровень}")


@requires_data
@pytest.mark.parametrize("язык", ["ru", "en"])
@pytest.mark.parametrize("состав", ["без находок", "только D1", "с планом действий"])
def test_письмо_не_подписано_и_не_обращается_по_имени(
    tmp_path: Path, язык: str, состав: str
) -> None:
    рабочая = tmp_path / f"chat-{состав}-{язык}"
    рабочая.mkdir()
    состояние = рабочая / "inspection.json"

    def движок(скрипт: Path, *args: str) -> Run:
        return run_engine(скрипт, *args, cwd=рабочая, state=состояние, data_dir=DATA)

    r = движок(
        AUDIT, "init", "--unit", "Тестовая", "--auditor", АУДИТОР, "--date", "2026-08-21"
    )
    assert r.code == 0, r.text

    if состав != "без находок":
        уровень = "D1" if состав == "только D1" else "D2"
        qid, зона = _пункт_с_уровнем(уровень)
        r = движок(AUDIT, "add", "--qid", qid, "--level", уровень, "--zone", зона)
        assert r.code == 0, r.text

    письмо = движок(REPORT, "letter", "--lang", язык)
    assert письмо.code == 0, письмо.text

    # Сначала — что письмо вообще собралось. Без этой проверки тест был бы
    # зелёным на пустом выводе, то есть ровно там, где письмо сломано сильнее
    # всего.
    текст = письмо.out
    assert "Тестовая" in текст, f"письмо не собралось: {текст[:200]!r}"

    for подпись in ПОДПИСИ:
        assert подпись not in текст, (
            f"в письме ({состав}, {язык}) вернулась подпись «{подпись}» — "
            "письмо снова личное, а отправлять его должен любой человек команды"
        )
    assert АУДИТОР not in текст, (
        f"в письме ({состав}, {язык}) названо имя аудитора — вернулась подпись "
        "или обращение по имени"
    )
