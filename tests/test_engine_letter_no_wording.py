"""T248: письмо не выдаёт формулировку пункта за слова аудитора (задача #205).

Запись, у которой аудитор не написал ни слова, доезжает до движка пустым
`evidence` — так выглядит и запись, заведённая командой без `--evidence`, и
находка, у которой формулировки нет ни на одном языке (T237, `src/mcp`).
Движок подставлял вместо недостающих слов ФОРМУЛИРОВКУ ПУНКТА по коду, да ещё
на языке письма. Вопросы методики сформулированы как утверждение нормы
(«Замороженные продукты размораживаются в соответствии со стандартом»), то есть
у отклонения оказывался текст, читающийся как «всё в порядке»; в английском
письме он вдобавок выглядел нативнее честной записи, сделанной по-русски.

В отчёте такой строки не было вовсе: `Зафиксировано:` печатается только при
непустой формулировке. Письмо и отчёт расходились на одних данных — поэтому
каждый случай здесь проверяется в обоих документах.

Граница ровно та же, что у T234: строка методики — это методика, слова
аудитора — это слова аудитора. Запись со словами печатается дословно и пунктом
не называется; запись без слов называет пункт пунктом.
"""

from __future__ import annotations

import csv
from collections.abc import Callable
from pathlib import Path

from conftest import AUDIT, DATA, REPORT, Run, requires_data, run_engine

#: Пункт синтетической методики с двумя классами и обоими языками.
ПУНКТ = "PRD01"
ВОПРОС_RU = "Заготовка размечена ярлыком образца А"
ВОПРОС_EN = "Prep item carries a sample-A tag"
ЗОНА = "fridge"
ЗОНА_RU = "Среднетемпературный шкаф"
ЗОНА_EN = "Mid-temperature cabinet"

#: Пункт с единственным критическим классом — он идёт в письмо отдельным блоком.
ПУНКТ_D3 = "PRD04"
ВОПРОС_D3_RU = "В обороте только ингредиенты из утверждённого списка"

#: Как письмо ссылается на пункт стандарта, когда слов аудитора нет.
ССЫЛКА_RU = f"пункт стандарта «{ВОПРОС_RU}»"
ССЫЛКА_EN = f"standard item “{ВОПРОС_EN}”"


def test_письмо_называет_пункт_пунктом_а_не_записью(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """Перечень по зонам: формулировка пункта не выдаётся за то, что зафиксировали."""
    started("add", "--qid", ПУНКТ, "--level", "D2", "--zone", ЗОНА)
    r = report("letter", "--lang", "ru")
    assert r.code == 0, r.text
    assert f"— {ЗОНА_RU}: {ВОПРОС_RU}" not in r.out, (
        "формулировка пункта стоит в письме на месте слов аудитора"
    )
    assert ССЫЛКА_RU in r.out, "пункт в письме не назван"


def test_письмо_называет_пункт_пунктом_и_по_английски(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """Английское письмо страдало сильнее: переведённая методика выглядит документом."""
    started("add", "--qid", ПУНКТ, "--level", "D2", "--zone", ЗОНА)
    r = report("letter", "--lang", "en")
    assert r.code == 0, r.text
    assert f"— {ЗОНА_EN}: {ВОПРОС_EN}" not in r.out, (
        "формулировка пункта стоит в английском письме на месте слов аудитора"
    )
    assert ССЫЛКА_EN in r.out, "пункт в английском письме не назван"


def test_критический_блок_письма_тоже_называет_пункт_пунктом(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """D3 идёт в письмо отдельной строкой — и собирается она другим куском кода."""
    started("add", "--qid", ПУНКТ_D3, "--level", "D3", "--zone", ЗОНА)
    r = report("letter", "--lang", "ru")
    assert r.code == 0, r.text
    assert f"Критично (D3): {ВОПРОС_D3_RU}" not in r.out, (
        "формулировка пункта выдана за находку в критическом блоке"
    )
    assert f"Критично (D3): пункт стандарта «{ВОПРОС_D3_RU}»" in r.out


def test_слова_аудитора_печатаются_дословно_и_пунктом_не_называются(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """Сторож от избытка: продукт не переписывает того, что человек написал сам."""
    слова = "На двух контейнерах ярлыка нет, на третьем ярлык чужой смены"
    started("add", "--qid", ПУНКТ, "--level", "D2", "--zone", ЗОНА, "--evidence", слова)
    r = report("letter", "--lang", "ru")
    assert r.code == 0, r.text
    assert слова in r.out, "слова аудитора не доехали до письма"
    assert "пункт стандарта" not in r.out, "ссылка на пункт подменила слова аудитора"


def test_запись_совпавшая_со_строкой_методики_остаётся_записью(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """Граница с T234: там формулировка ЕСТЬ, и решение о ней принято отдельно (D115).

    Ручной выбор пункта по кадру без комментария кладёт в запись вопрос пункта
    целиком (`src/bot/routers/record.py`). Это другая дверь и другое решение:
    формулировка записана, и печатается она как записана — без служебной
    пометки класса. Правка T248 сюда не дотягивается, и этот тест стережёт
    именно её границу.
    """
    started(
        "add",
        "--qid",
        ПУНКТ,
        "--level",
        "D2",
        "--zone",
        ЗОНА,
        "--evidence",
        f"(D1, D2) {ВОПРОС_RU}",
    )
    r = report("letter", "--lang", "ru")
    assert r.code == 0, r.text
    assert f"— {ЗОНА_RU}: {ВОПРОС_RU}" in r.out, "запись со словами перестала печататься"
    assert "пункт стандарта" not in r.out, "записанная формулировка названа ссылкой на пункт"


def test_отчёт_на_тех_же_данных_строки_записи_не_печатает(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """Отчёт и письмо обязаны говорить одно: записи нет — строки записи нет."""
    started("add", "--qid", ПУНКТ, "--level", "D2", "--zone", ЗОНА)
    r = report("html")
    assert r.code == 0, r.text
    assert "Зафиксировано:" not in r.out, "отчёт напечатал запись, которой аудитор не делал"
    assert ВОПРОС_RU in r.out, "пункт пропал из заголовка нарушения"


def test_формулировка_из_одних_пробелов_ведёт_себя_как_пустая(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """Дыра того же дефекта: пробелы проходили проверку «формулировка есть»."""
    started("add", "--qid", ПУНКТ, "--level", "D2", "--zone", ЗОНА, "--evidence", "   ")
    r = report("html")
    assert r.code == 0, r.text
    assert "Зафиксировано:" not in r.out, "отчёт напечатал пункт на месте записи из пробелов"
    письмо = report("letter", "--lang", "ru")
    assert письмо.code == 0, письмо.text
    assert ССЫЛКА_RU in письмо.out, "письмо не назвало пункт при формулировке из пробелов"


def test_пункт_в_письме_назван_на_языке_письма(
    started: Callable[..., Run], report: Callable[..., Run]
) -> None:
    """Язык — параметр: название пункта берётся по языку ПИСЬМА, а не по языку заведения."""
    started("add", "--qid", ПУНКТ, "--level", "D2", "--zone", ЗОНА)
    r = report("letter", "--lang", "en")
    assert r.code == 0, r.text
    assert ВОПРОС_EN in r.out
    assert ВОПРОС_RU not in r.out, "в английское письмо попала русская строка методики"


def _боевой_пункт() -> tuple[str, str, str]:
    """Первый пункт боевой методики, по которому можно завести нарушение."""
    зоны = [z["code"] for z in csv.DictReader((DATA / "zones.csv").open(encoding="utf-8"))]
    for row in csv.DictReader((DATA / "checklist.csv").open(encoding="utf-8")):
        классы = [x for x in (row["levels"] or "").split(";") if x and x != "D0"]
        if row["kind"] != "violation" or not классы:
            continue
        свои = [z for z in (row["zones"] or "").split(",") if z and z != "*"]
        return row["id"], классы[0], (свои[0] if свои else зоны[0])
    raise AssertionError("в боевой методике не нашлось пункта, по которому можно завести запись")


@requires_data
def test_боевая_методика_пункт_за_запись_не_выдаёт(tmp_path: Path) -> None:
    """Сторож на настоящих данных: именно на них дефект и увидели."""
    qid, уровень, зона = _боевой_пункт()
    рабочая = tmp_path / "chat-live"
    рабочая.mkdir()
    состояние = рабочая / "inspection.json"

    def движок(скрипт: Path, *args: str) -> Run:
        return run_engine(скрипт, *args, cwd=рабочая, state=состояние, data_dir=DATA)

    r = движок(AUDIT, "init", "--unit", "Тестовая", "--auditor", "Тест", "--date", "2026-08-21")
    assert r.code == 0, r.text
    r = движок(AUDIT, "add", "--qid", qid, "--level", уровень, "--zone", зона)
    assert r.code == 0, r.text

    письмо = движок(REPORT, "letter", "--lang", "ru")
    assert письмо.code == 0, письмо.text
    assert "пункт стандарта «" in письмо.out, f"пункт {qid} в письме не назван пунктом"
    отчёт = движок(REPORT, "html")
    assert отчёт.code == 0, отчёт.text
    assert "Зафиксировано:" not in отчёт.out, "отчёт напечатал запись, которой аудитор не делал"
