def _отпечатки_файлов() -> dict[str, str]:
    """Отпечатки миграций так, как их считает сам раннер.

    Считаются не своей копией `hashlib`, а `discover_migrations`: важен ровно
    тот отпечаток, который попадёт в `schema_migrations`. Сменится способ
    подсчёта — эта проверка покраснеет, и это правильно: смена способа
    обесценивает отпечатки во всех уже накатанных базах разом.
    """
    return {м.filename: м.checksum for м in discover_migrations()}


def test_закоммиченная_миграция_не_меняется() -> None:
    расхождения = {
        имя: (ожидался, стало)
        for имя, стало in _отпечатки_файлов().items()
        if (ожидался := ОТПЕЧАТКИ.get(имя)) is not None and ожидался != стало
    }
    assert not расхождения, (
        f"содержимое уже закоммиченных миграций изменилось: {sorted(расхождения)}. "
        f"Накат на базе, где они применены, теперь откажет — так встал накат на "
        f"площадке 09.09.2026 (T299). Верните файл к прежнему виду, а правку "
        f"оформите НОВЫМ файлом миграции; подгонять отпечаток в списке нельзя"
    )


def test_каждый_файл_миграции_записан_в_список() -> None:
    """Новый файл — новая строка в списке, тем же коммитом.

    Без этой половины список молча перестаёт покрывать свежие миграции:
    отпечатка нет, сравнивать не с чем, и проверка выше зелёная на файле, за
    которым никто не следит.
    """
    на_диске = set(_отпечатки_файлов())
    в_списке = set(ОТПЕЧАТКИ)
    assert на_диске == в_списке, (
        f"список отпечатков разошёлся с каталогом {MIGRATIONS_DIR.name}: нет строки для "
        f"{sorted(на_диске - в_списке)}, лишние строки для {sorted(в_списке - на_диске)}. "
        f"Новая миграция записывается в список тем же коммитом, которым появилась"
    )


def test_отпечатки_считаются_по_файлам_каталога_миграций() -> None:
    """Список не должен оказаться пересказом самого себя.

    Обе проверки выше сравнивают словарь со словарём, и если бы источником
    второго был не каталог, а тот же список, они проходили бы всегда. Здесь
    подтверждается, что файлы действительно читаются с диска.
    """
    файлы = {путь.name for путь in Path(MIGRATIONS_DIR).glob("*.sql")}
    assert файлы == set(ОТПЕЧАТКИ)
