"""Дата внутри живой фразы и названием месяца (задача #220).

На живом прогоне 07.09.2026 аудитор получал отказ «Не понял дату» на фразу, в
которой дата была: разбор требовал её в самом начале сообщения и только числами
(`^` плюс `.match` в `src/bot/info.py`). Владелец, суть претензии: вычленить дату
из сообщения — здесь даже модель не нужна.

Границу двух половин правила эти тесты и стерегут:

* дата, которая в сообщении **есть**, обязана находиться — где угодно во фразе,
  числами или названием месяца, на любом из двух языков продукта;
* то, что датой **не является**, датой не становится: неразобранное не
  записывается молча, потому что поле читается как срок и уезжает партнёру.
"""

from __future__ import annotations

from datetime import date

import pytest

from src.bot.info import parse_date

#: «Сегодня» всех случаев ниже. Зафиксировано, потому что достройка года считается
#: от него: без опоры тест начал бы падать при смене года.
СЕГОДНЯ = date(2026, 9, 7)


@pytest.mark.parametrize(
    ("сказано", "записано"),
    [
        # Дата внутри фразы — то, из-за чего задача и заведена.
        ("созвон 15.09.2026", "15.09.2026"),
        ("до 15.09.2026", "15.09.2026"),
        ("план готов к 15.09.2026", "15.09.2026"),
        ("the call is on 15.09.2026", "15.09.2026"),
        # Время перед датой: тот же ответ, что и время после неё.
        ("в 18:30 15.09.2026", "15.09.2026 18:30"),
        # Название месяца — обычная форма и в письме, и в расшифровке голоса.
        ("15 сентября 2026", "15.09.2026"),
        ("до 15 сентября 2026 года", "15.09.2026"),
        ("15 September 2026", "15.09.2026"),
        ("September 15, 2026", "15.09.2026"),
        # Год не назван: берётся ближайшая такая дата не в прошлом. Оба поля,
        # где спрашивается дата, смотрят вперёд — созвон и срок плана действий.
        ("15.09", "15.09.2026"),
        ("15 сентября", "15.09.2026"),
        ("до 3 марта", "03.03.2027"),
        ("15 сентября в 18:30", "15.09.2026 18:30"),
    ],
)
def test_дата_находится_внутри_живой_фразы(сказано: str, записано: str) -> None:
    assert parse_date(сказано, today=СЕГОДНЯ) == записано


@pytest.mark.parametrize(
    "сказано",
    [
        # Уже стерегомое прежними тестами — здесь повторено намеренно: правка
        # разбора не имеет права ослабить отказ.
        "завтра после обеда",
        "",
        "31.02.2026",
        "созвон был",
        # Число рядом со словом — не дата. Так пишут о количестве, и превратить
        # это в срок значило бы отправить партнёру выдуманную дату.
        "маркировки нет на 15 упаковках",
        "15 штук просрочено",
        # Месяц без числа: день неизвестен, а выдумывать его нельзя.
        "в сентябре",
        "in September",
        # Несуществующий день названного месяца.
        "31 февраля 2026",
    ],
)
def test_не_дата_датой_не_становится(сказано: str) -> None:
    assert parse_date(сказано, today=СЕГОДНЯ) is None
