"""Методика управляющей компании не цитируется в репозитории (T146, #138).

Репозиторий публичный (D073), а `data/` и `examples/` намеренно вне git: это
материалы управляющей компании и реальные проверки партнёров. Через код и
документы фрагменты методики просачиваются обратно — за одни сутки этот канал
затыкали трижды, и **каждый раз находилось новое**:

* сначала — цитаты в двух тестах;
* потом — что счёт занижен вчетверо: порог длины отсекал ровно ту строку,
  которая утекла целиком;
* потом — что пороги классов не попадали в поиск вообще, потому что
  сверялась только первая колонка таблицы подсказок, а они лежат в остальных.

Три ручных прохода — три разных ответа. Дело не во внимательности: проверки
не было как проверки, и канал протекал заново на первом же тесте, написанном
по боевым данным.

**Иглы строятся из методики на ходу.** Замороженный список строк сделал бы
утечкой сам этот файл — ровно то, что он ловит.

Тест требует боевую методику: это единственное место, где её читать правильно.
Сама проверка — `tools/methodology_leak.py`: в CI методики нет, и тест там
пропускается, поэтому та же проверка идёт шагом выкатки на сервере (#854).
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from conftest import DATA, requires_data

from tools import methodology_leak as leak


@requires_data
def test_методика_не_цитируется_в_коде_и_тестах() -> None:
    """Код и тесты не содержат формулировок методики — только идентификаторы.

    Документы вынесены за скобки отдельным тестом ниже: там названия зон стоят
    по построению, и это вопрос видимости репозитория, а не дефект.
    """
    находки = leak.scan(Path(__file__).resolve().parents[1], DATA)

    assert not находки, (
        "методика управляющей компании процитирована в репозитории "
        f"({len(находки)} шт.), а он публичный:\n  " + "\n  ".join(sorted(находки))
    )


@requires_data
def test_демо_набор_не_повторяет_боевую_методику() -> None:
    """Демо обещает боевых данных не касаться — проверяем, что так и есть.

    Демо-набор лежит В git, боевая методика намеренно вне его, поэтому любое
    дословное совпадение здесь — утечка того же рода, что чинили в тестах.
    """
    корень = Path(__file__).resolve().parents[1]
    demo = корень / "demo" / "data"
    if not demo.is_dir():
        pytest.skip("демо-набора нет в этой копии")

    иглы, зоны = leak.needles(DATA)
    находки: list[str] = []
    for путь in sorted(demo.iterdir()):
        if not путь.is_file():
            continue
        try:
            текст = leak.flat(путь.read_text(encoding="utf-8"))
        except (UnicodeDecodeError, OSError):
            continue
        for игла in иглы:
            if leak.occurs(игла, текст, zones=зоны):
                находки.append(f"{путь.relative_to(корень)}: «{игла[:40]}»")

    assert not находки, "демо-набор повторяет боевую методику дословно:\n  " + "\n  ".join(
        sorted(находки)
    )


@requires_data
def test_формулировки_находок_партнёров_не_цитируются() -> None:
    """Наблюдения аудитора о конкретной точке конкретного партнёра — не в git.

    Это чувствительнее методики: методику можно пересказать по смыслу, а
    формулировка находки называет, что именно нашли у названного партнёра в
    названный день. `examples/` вне git по той же причине, что и `data/`.

    Сегодня таких цитат ноль — тест заведён, чтобы так и осталось: подходящее
    место для «живого примера» в тесте выглядит соблазнительно, а цена ошибки
    здесь выше, чем у формулировки методики.

    Названия точек и города в эту проверку НЕ входят: они вплетены в
    репозиторий по построению — в документах, в журнале изменений, в фикстурах
    по всему набору. Это вопрос владельцу об идентификации партнёра, а не
    дефект, и тест, дающий шесть десятков находок, заглушат в тот же день.
    """
    корень = Path(__file__).resolve().parents[1]
    примеры = корень / "examples"
    if not примеры.is_dir():
        pytest.skip("эталонных проверок нет в этой копии")

    иглы: set[str] = set()
    for файл in примеры.glob("*/inspection.json"):
        состояние = json.loads(файл.read_text(encoding="utf-8"))
        for находка in состояние.get("findings", []):
            for ключ in ("evidence", "comment"):
                текст = (находка.get(ключ) or "").strip()
                if len(текст) >= leak.МИН_ДЛИНА:
                    иглы.add(текст)
    assert иглы, "иглы не собрались — тест перестал что-либо проверять"

    находки: list[str] = []
    for путь in leak.published_files(корень):
        if leak.outside_check(путь.relative_to(корень)):
            continue
        try:
            текст = leak.flat(путь.read_text(encoding="utf-8"))
        except (UnicodeDecodeError, OSError):
            continue
        for игла in иглы:
            if leak.occurs(игла, текст, zones=set()):
                находки.append(f"{путь.relative_to(корень)}: «{игла[:40]}»")

    assert not находки, (
        "в репозитории процитированы находки настоящих проверок партнёров:\n  "
        + "\n  ".join(sorted(находки))
    )
