"""T302: испорченную методику блок отвергает так же, как движок, а не молча.

Разбор T302 показал два места, где блок и движок читают ОДИН И ТОТ ЖЕ файл и
расходятся в выводе: нечисловой срок устранения и дубль кода пункта. Движок на
обоих завершается с объяснением (T106), блок обходился молча — нулевым сроком и
пропуском второй строки.

Почему это важно именно сейчас: правка методики руками в файле остаётся
единственным способом задать то, чего не умеют ни CLI, ни инструменты MCP
(ставки, пороги букв, порядок обхода), а дверь MCP испорченную правку не
пропускает — она гоняет `manage.py validate` на кандидате. То есть расхождение
достаётся ровно тому, кто правит файл: продукт поднимается, справочник
показывает пункт со сроком «немедленно», и отказ вылезает на точке, когда
аудитор уже приехал.

Методика синтетическая (`tests/methodology`, T141), портится её копия.
"""

from __future__ import annotations

import csv
from pathlib import Path

import pytest

from src.domain import get_item, list_items
from src.domain.errors import ConfigError

ЧЕК_ЛИСТ = "checklist.csv"


def _строки(каталог: Path) -> tuple[list[dict[str, str]], list[str]]:
    with (каталог / ЧЕК_ЛИСТ).open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        return list(reader), list(reader.fieldnames or [])


def _записать(каталог: Path, строки: list[dict[str, str]], колонки: list[str]) -> None:
    with (каталог / ЧЕК_ЛИСТ).open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=колонки)
        writer.writeheader()
        writer.writerows(строки)


@pytest.fixture
def методика(data_copy: Path, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> Path:
    """Копия синтетической методики, подставленная блоку как действующая."""
    monkeypatch.setenv("AUDIT_DATA_DIR", str(data_copy))
    monkeypatch.setenv("STATE_DIR", str(tmp_path / "state"))
    monkeypatch.chdir(tmp_path)
    return data_copy


def test_нечисловой_срок_устранения_это_отказ_а_не_молчаливый_ноль(методика: Path) -> None:
    """«10 дней» вместо «10» — отказ. Нулевой срок печатается партнёру как «немедленно».

    Движок на этом файле завершается с объяснением (T106). Пока блок читал тот
    же файл молча, у пункта выходил срок 0, и рядовое нарушение выглядело
    критическим — ровно то, что T106 чинила на своей стороне.
    """
    строки, колонки = _строки(методика)
    строки[0]["days"] = "10 дней"
    _записать(методика, строки, колонки)

    with pytest.raises(ConfigError) as отказ:
        list_items()
    текст = str(отказ.value)
    assert строки[0]["id"] in текст, "в отказе не назван пункт, который чинить"
    assert "days" in текст, "в отказе не названа колонка"
    assert "10 дней" in текст, "в отказе не показано отвергнутое значение"


def test_пустой_срок_устранения_отказом_не_является(методика: Path) -> None:
    """Пустая клетка остаётся нулём — так пишет `manage.py add` без `--days` (T106).

    Граница отказа проходит ровно там же, где у движка: запрет на пустую клетку
    сломал бы штатное заведение пункта.
    """
    строки, колонки = _строки(методика)
    строки[0]["days"] = ""
    _записать(методика, строки, колонки)

    пункт = get_item(строки[0]["id"])
    assert пункт.days == 0


def test_дубль_кода_пункта_это_отказ_а_не_пропуск_второй_строки(методика: Path) -> None:
    """Две строки с одним кодом — отказ: пункты связываются кодами, не формулировками.

    Движок отказывает (T106) именно потому, что иначе в отчёт попадает не тот
    вопрос. Блок до T302 брал первую строку и молчал, то есть на испорченном
    файле показывал аудитору вопрос, по которому движок считать отказывается.
    """
    строки, колонки = _строки(методика)
    двойник = dict(строки[1])
    двойник["id"] = строки[0]["id"]
    _записать(методика, [*строки, двойник], колонки)

    with pytest.raises(ConfigError) as отказ:
        list_items()
    assert строки[0]["id"] in str(отказ.value), "в отказе не назван спорный код"


def test_строка_комментарий_дублем_не_считается(методика: Path) -> None:
    """Человек метит строки решёткой — их и движок, и блок пропускают.

    Иначе сверка дублей отказала бы на методике, где комментариев несколько.
    """
    строки, колонки = _строки(методика)
    сколько_было = len(list_items())
    комментарий = dict(строки[0])
    комментарий["id"] = "#" + строки[0]["id"]
    второй = dict(комментарий)
    _записать(методика, [*строки, комментарий, второй], колонки)

    assert len(list_items()) == сколько_было
