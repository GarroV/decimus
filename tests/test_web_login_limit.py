"""T325: форма входа перестаёт принимать пароли, когда их перебирают.

Проверяется ПУТЬ ЦЕЛИКОМ — отправка формы, а не функция ограничителя: правило
без вызова в нужном месте ничего не закрывает, и именно так ограничитель
исчезает при правках (вынесли проверку, поменяли порядок, забыли позвать после
неудачи). Поэтому здесь ходят настоящими отправками формы.

Подменено только ХРАНИЛИЩЕ счётчика (`web_harness.Счётчики`), правило —
продуктовое. Подменить заодно и правило значило бы проверять оснастку: набор
зеленел бы и на снятом ограничителе.
"""

from __future__ import annotations

from collections.abc import Iterator
from datetime import timedelta
from typing import Any

import pytest
from flask.testing import FlaskClient
from web_harness import (
    ЛОГИН,
    ПАРОЛЬ,
    ПОЧТА,
    СВОЙ,
    Счётчики,
    подменить_двери,
    подменить_счётчики,
    собрать,
)

from src.db.web_throttle import FAILURES_BEFORE_LOCK, FORGET_AFTER, LOCK_STEPS
from src.web import auth
from src.web import inspections as data

ТЕНАНТ = "default"
АДРЕС = "203.0.113.7"
ДРУГОЙ_АДРЕС = "198.51.100.14"
#: Заведомо не тот пароль. Названной строкой, а не значением в сигнатуре:
#: значение в сигнатуре линтер справедливо принимает за зашитый пароль.
НЕ_ТОТ = "не тот пароль"
ПОРОГ_ЛОГИНА = FAILURES_BEFORE_LOCK["login"]
ПОРОГ_АДРЕСА = FAILURES_BEFORE_LOCK["address"]


@pytest.fixture
def двери(monkeypatch: pytest.MonkeyPatch) -> dict[str, list[Any]]:
    return подменить_двери(monkeypatch, tenant=ТЕНАНТ)


@pytest.fixture
def счётчики(monkeypatch: pytest.MonkeyPatch, двери: dict[str, list[Any]]) -> Счётчики:
    """Своё хранилище счётчика, до которого можно дотянуться из набора."""
    return подменить_счётчики(monkeypatch)


@pytest.fixture
def стенд(
    monkeypatch: pytest.MonkeyPatch, счётчики: Счётчики, двери: dict[str, list[Any]]
) -> Iterator[FlaskClient]:
    monkeypatch.setattr(data, "retraction_available", lambda: True)
    monkeypatch.setattr(data, "load_registry", lambda **_: data.Registry((), True))
    with собрать(tenant=ТЕНАНТ).test_client() as client:
        yield client


def попытка(
    стенд: FlaskClient, *, login: str = ЛОГИН, password: str = НЕ_ТОТ, адрес: str = АДРЕС
) -> Any:
    """Отправка формы входа так, как её шлёт браузер, — с указанного адреса."""
    return стенд.post(
        auth.LOGIN_PATH,
        data={"login": login, "password": password},
        headers={"Origin": СВОЙ},
        environ_base={"REMOTE_ADDR": адрес},
    )


def перебрать(стенд: FlaskClient, *, раз: int, login: str = ЛОГИН, адрес: str = АДРЕС) -> Any:
    ответ = None
    for _ in range(раз):
        ответ = попытка(стенд, login=login, адрес=адрес)
    return ответ


# --- дверь закрывается -------------------------------------------------------


def test_до_порога_форма_отвечает_обычным_отказом(стенд: FlaskClient) -> None:
    ответ = перебрать(стенд, раз=ПОРОГ_ЛОГИНА - 1)
    assert ответ.status_code == 401, "человек ошибся несколько раз — это ещё не перебор"


def test_на_пороге_форма_перестаёт_принимать_пароль(стенд: FlaskClient) -> None:
    ответ = перебрать(стенд, раз=ПОРОГ_ЛОГИНА)
    assert ответ.status_code == 429, (
        f"{ПОРОГ_ЛОГИНА} неудач подряд, а форма всё ещё принимает пароли — ограничителя нет"
    )


def test_запертому_не_помогает_верный_пароль(стенд: FlaskClient) -> None:
    """Главная проверка задачи.

    Ограничитель, который пропускает верный пароль, ничего не ограничивает:
    перебор ровно за этим и идёт. Поэтому запертым обязан быть ВХОД, а не
    «показ отказа».
    """
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА)
    ответ = попытка(стенд, password=ПАРОЛЬ)
    assert ответ.status_code == 429, "запертый вошёл верным паролем — запрета нет"
    assert not ответ.headers.get("Set-Cookie"), "запертому выдали сессионную куку"


def test_запертый_не_доходит_до_сверки_пароля(
    стенд: FlaskClient, двери: dict[str, list[Any]]
) -> None:
    """Сверка пароля — дорогая часть (scrypt). Запертый до неё не доходит.

    Иначе ограничитель не спасает от перегрузки: сам поток попыток остаётся
    рычагом, которым админку кладут.
    """
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА)
    было = len(двери["authenticate"])
    попытка(стенд, password=ПАРОЛЬ)
    assert len(двери["authenticate"]) == было, "запертую попытку всё равно понесли в базу учёток"


def test_ответ_запертому_называет_срок_и_на_экране_и_в_заголовке(стенд: FlaskClient) -> None:
    ответ = перебрать(стенд, раз=ПОРОГ_ЛОГИНА)
    страница = ответ.get_data(as_text=True)
    assert "мин" in страница, "человеку не сказали, сколько ждать"
    assert int(ответ.headers["Retry-After"]) > 0


# --- дверь открывается обратно ----------------------------------------------


def test_запрет_кончается_временем(стенд: FlaskClient, счётчики: Счётчики) -> None:
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА)
    счётчики.отмотать(max(LOCK_STEPS) + timedelta(minutes=1))
    assert попытка(стенд, password=ПАРОЛЬ).status_code == 302, (
        "запрет не кончился сам — человек заперт навсегда"
    )


def test_удачный_вход_забывает_неудачи(стенд: FlaskClient) -> None:
    """Иначе вчерашние промахи копятся и запирают того, кто сегодня вошёл."""
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА - 1)
    assert попытка(стенд, password=ПАРОЛЬ).status_code == 302
    ответ = перебрать(стенд, раз=ПОРОГ_ЛОГИНА - 1)
    assert ответ.status_code == 401, "счётчик не обнулился удачным входом"


def test_счётчик_забывается_после_долгой_тишины(стенд: FlaskClient, счётчики: Счётчики) -> None:
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА - 1)
    счётчики.отмотать(FORGET_AFTER + timedelta(minutes=1))
    assert попытка(стенд).status_code == 401, "давние неудачи всё ещё складываются с сегодняшними"


# --- два счётчика, а не один -------------------------------------------------


def test_запертый_логин_не_запирает_соседний(стенд: FlaskClient) -> None:
    """Запрет по логину не обязан закрывать вход остальным.

    Обратное означало бы, что запереть админку всей конторе можно перебором
    одного чужого логина.
    """
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА, login="кто-то")
    assert попытка(стенд, password=ПАРОЛЬ, адрес=ДРУГОЙ_АДРЕС).status_code == 302


def test_перебор_по_разным_логинам_упирается_в_счётчик_адреса(стенд: FlaskClient) -> None:
    """Счётчик логина такой перебор не видит: каждый логин пробуют один раз."""
    for n in range(ПОРОГ_АДРЕСА):
        ответ = попытка(стенд, login=f"логин{n}")
    assert ответ.status_code == 429, "перебор по разным логинам с одного адреса не остановлен"


def test_перебор_одного_логина_с_разных_адресов_упирается_в_счётчик_логина(
    стенд: FlaskClient,
) -> None:
    """А этот перебор не видит счётчик адреса: каждый адрес встречается редко."""
    for n in range(ПОРОГ_ЛОГИНА):
        ответ = попытка(стенд, адрес=f"198.51.100.{n + 1}")
    assert ответ.status_code == 429, "перебор одного логина с разных адресов не остановлен"


# --- вход по почте: один лимит на человека, без оракула ----------------------


def test_лимит_логина_исчерпан_вход_по_почте_отказывает_как_обычно(стенд: FlaskClient) -> None:
    """Блокировка по логину не должна быть видна через почту.

    Иначе «заперто» в ответ на почту говорило бы, что она привязана к учётке.
    """
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА)
    ответ = попытка(стенд, login=ПОЧТА, password=ПАРОЛЬ, адрес=ДРУГОЙ_АДРЕС)
    assert ответ.status_code == 401, "лимит логина виден через почту: ответ не «не подошли»"
    assert not ответ.headers.get("Set-Cookie"), "исчерпанному логину выдали сессию по почте"


def test_неудачи_по_почте_запирают_и_логин_того_же_человека(стенд: FlaskClient) -> None:
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА, login=ПОЧТА)
    ответ = попытка(стенд, password=ПАРОЛЬ, адрес=ДРУГОЙ_АДРЕС)
    assert ответ.status_code == 429, "почта и логин одного человека дали два отдельных лимита"


def test_неудачи_по_почте_не_дают_вдвое_больше_попыток(стенд: FlaskClient) -> None:
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА - 1, login=ПОЧТА)
    попытка(стенд, адрес=ДРУГОЙ_АДРЕС)
    ответ = попытка(стенд, password=ПАРОЛЬ, адрес=ДРУГОЙ_АДРЕС)
    assert ответ.status_code == 429, "лимит на логин и почту вместе больше порога"


def test_ответы_для_привязанной_и_несуществующей_почты_одинаковы(стенд: FlaskClient) -> None:
    привязанная = [
        попытка(стенд, login=ПОЧТА, адрес=АДРЕС).status_code for _ in range(ПОРОГ_ЛОГИНА + 1)
    ]
    чужая = [
        попытка(стенд, login="other@example.org", адрес=ДРУГОЙ_АДРЕС).status_code
        for _ in range(ПОРОГ_ЛОГИНА + 1)
    ]
    assert привязанная == чужая, "по ответам видно, привязана ли почта к учётке"


def test_удачный_вход_по_почте_забывает_оба_ключа(стенд: FlaskClient) -> None:
    перебрать(стенд, раз=ПОРОГ_ЛОГИНА - 1, login=ПОЧТА)
    assert попытка(стенд, login=ПОЧТА, password=ПАРОЛЬ).status_code == 302
    ответ = перебрать(стенд, раз=ПОРОГ_ЛОГИНА - 1)
    assert ответ.status_code == 401, "успех по почте не очистил ключ логина"
