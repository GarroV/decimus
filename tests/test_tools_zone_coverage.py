"""Замер покрытия словаря зон (T272, `tools/zone_coverage.py`).

Замер отвечает на вопрос «много ли осталось дописать в колонку „Зона“» — и
отвечает числом, потому что без числа «дополняем потихоньку» превращается в
ощущение. Проверяется здесь не красота отчёта, а три его утверждения, каждое
из которых легко сделать неверным незаметно:

* путь к зоне назван тот, которым она в самом деле получена, и порядок «слова
  сильнее словаря» соблюдён;
* «дописать сюда» перечисляет строки, задетые формулировками БЕЗ зоны, — то
  есть работу, которая и правда что-то покроет, а не все пустые строки карты
  подряд;
* формулировка, не задевшая карту вовсе, считается отдельно: ей колонка
  «Зона» не поможет, и смешать её с остальными значило бы пообещать покрытие,
  которого дописывание не даст.

Методика здесь синтетическая (`domain_env`): боевая лежит вне git (D002), а
её строки в репозиторий не попадают — он публичный.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from src.recognize.config import NO_CHAT
from src.recognize.cues import load_cues
from tools import zone_coverage as zc
from tools.fastpath_measure import FROM_DICTIONARY, FROM_NOWHERE, FROM_WORDS

#: «Печь» — строка карты с названной зоной: словарь её знает.
OVEN = "Печь: под лентой нагар"
#: «Стеллаж» — строка карты БЕЗ зоны: она и есть кандидат в дописывание.
RACK = "Стеллаж: пыль на полках"
#: Зона названа словами, и строка карты тоже задета.
RACK_WITH_ZONE = "В тепловом: стеллаж, пыль на полках"
#: Карту не задевает ни одной строкой.
NOTHING = "Сотрудник без бейджа"


def сказано(*notes: str) -> tuple[zc.Said, ...]:
    return tuple(zc.Said(note=note, source="проба") for note in notes)


def test_путь_к_зоне_назван_тот_которым_она_получена(domain_env: Path) -> None:
    """Подменённый путь превратил бы заслугу человека в заслугу словаря — и
    покрытие словаря выросло бы на бумаге, не изменившись на точке."""
    cues = load_cues(chat_id=NO_CHAT)

    из_словаря, из_слов, ниоткуда = zc.reach(сказано(OVEN, RACK_WITH_ZONE, RACK), cues)

    assert (из_словаря.source, из_словаря.zone) == (FROM_DICTIONARY, "hot_kitchen")
    assert (из_слов.source, из_слов.zone) == (FROM_WORDS, "hot_kitchen")
    assert (ниоткуда.source, ниоткуда.zone) == (FROM_NOWHERE, None)


def test_слова_сильнее_словаря_и_в_замере_тоже(domain_env: Path) -> None:
    """Порядок продукта (T263) обязан повторяться замером: замер, считающий
    иначе, мерил бы поведение, которого в боте нет."""
    cues = load_cues(chat_id=NO_CHAT)

    (итог,) = zc.reach(сказано("В зале: печь, под лентой нагар"), cues)

    assert (итог.source, итог.zone) == (FROM_WORDS, "dining")


def test_дописать_перечисляет_только_задетые_строки_без_зоны(domain_env: Path) -> None:
    """Перечислив все пустые строки карты подряд, замер отдал бы список работы,
    большая часть которой ничего не покроет, — и список перестали бы читать."""
    cues = load_cues(chat_id=NO_CHAT)

    итоги = zc.reach(сказано(RACK, RACK, OVEN), cues)
    раздел = "\n".join(zc._todo_section(итоги))

    assert "| Стеллаж | 2 |" in раздел, раздел
    assert "Печь" not in раздел, "строка с уже названной зоной попала в список работы"


def test_формулировка_мимо_карты_считается_отдельно(domain_env: Path) -> None:
    """Ей колонка «Зона» не поможет: не хватает самой строки карты, а заводит
    её управляющая компания. Смешанная с остальными, она обещала бы покрытие,
    которого дописывание зоны не даст."""
    cues = load_cues(chat_id=NO_CHAT)

    итоги = zc.reach(сказано(NOTHING, RACK), cues)
    раздел = "\n".join(zc._todo_section(итоги))

    assert "не задевших карту ни одной строкой: 1" in раздел, раздел


def test_покрытие_считается_без_спроса_кнопкой(domain_env: Path) -> None:
    """Спрос — работа человека, и записанный в покрытие словаря он показал бы
    сто процентов там, где словарь не знает ничего."""
    cues = load_cues(chat_id=NO_CHAT)

    раздел = "\n".join(zc._reach_section(zc.reach(сказано(OVEN, RACK, NOTHING), cues)))

    assert "Зона известна без вопроса человеку: 1 из 3 (33%)" in раздел, раздел


def test_пустой_корпус_это_код_два_а_не_нулевое_покрытие(
    domain_env: Path, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """Ноль формулировок и нулевое покрытие — разные вещи: первое означает, что
    мерить было не по чему, а напечатанные 0% прочитались бы как результат."""
    monkeypatch.setattr(zc, "corpus", lambda _root: ())

    assert zc.main(["--root", str(tmp_path)]) == 2
