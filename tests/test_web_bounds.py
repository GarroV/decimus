"""Граница блока `web`: про `src.mcp` знает ровно один модуль.

**Зачем отдельная проверка, если есть `lint-imports`.** Контракт ярусов в
`pyproject.toml` разделяет bot, mcp и web знаком `:`, а он у import-linter
означает «один ярус, и друг друга импортировать МОЖНО»
(`_NON_INDEPENDENT_LAYER_DELIMITER`). Запрет даёт знак `|`. То есть описанная в
комментарии граница между тремя поверхностями сегодня договорённость, а не
механизм — найдено порчей на T320: импорт `src.mcp` из `src.web` контракт
пропускает молча.

Сменить разделитель — правка, которая касается всех трёх блоков сразу, и решает
её не блок `web`. А вот свою половину границы блок закрыть обязан: состав
чек-листа правится дверью хранилища версий (D049, D050), и дверь эта лежит в
`src.mcp`. Разрешено это ОДНОМУ модулю — `src/web/methodology.py`, потому что
склад версий методики не принадлежит ни одной поверхности. Второй такой импорт
означал бы, что веб потихоньку берёт у MCP словарь текстов, границы сессии или
транспорт, — а это разные поверхности с разными пользователями.

Проверка читает исходники, а не импортирует модули: импорт внутри функции и
`importlib` она увидит так же, как обычную строку `import`.
"""

from __future__ import annotations

import ast
from pathlib import Path

#: Единственный модуль веба, которому разрешено знать про `src.mcp`.
ДВЕРЬ = "methodology.py"

ПАКЕТ = Path(__file__).resolve().parent.parent / "src" / "web"


def _импорты(файл: Path) -> set[str]:
    """Имена модулей, которые файл импортирует, — абсолютные и относительные."""
    дерево = ast.parse(файл.read_text(encoding="utf-8"), filename=str(файл))
    имена: set[str] = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            имена.update(alias.name for alias in узел.names)
        elif isinstance(узел, ast.ImportFrom):
            # Относительный импорт (`from . import x`) остаётся внутри блока —
            # приводим его к полному имени только для абсолютных.
            if узел.level == 0 and узел.module:
                имена.add(узел.module)
                имена.update(f"{узел.module}.{alias.name}" for alias in узел.names)
    return имена


def test_про_mcp_знает_только_дверь_методики() -> None:
    """Ни один модуль веба, кроме двери методики, не импортирует `src.mcp`."""
    нарушители = {
        файл.name: sorted(имя for имя in _импорты(файл) if имя.startswith("src.mcp"))
        for файл in sorted(ПАКЕТ.glob("*.py"))
        if файл.name != ДВЕРЬ
    }
    нарушители = {имя: пути for имя, пути in нарушители.items() if пути}
    assert not нарушители, (
        f"Блок web знает про src.mcp не только дверью методики: {нарушители}. "
        f"Общий у поверхностей только склад версий методики (src/web/{ДВЕРЬ}); "
        f"словарь текстов, границы сессии и транспорт у них разные"
    )


def test_дверь_методики_берёт_только_хранилище() -> None:
    """Сама дверь берёт у `src.mcp` хранилище и его отказы — не транспорт.

    Импорт `src.mcp.server`, `src.mcp.rpc` или `src.mcp.tools` означал бы, что
    админка поехала на поверхности агента: у неё своя сессия, свой словарь и
    свой пользователь.
    """
    разрешено = {
        "src.mcp.checklist",
        "src.mcp.checklist_tools",
        "src.mcp.config",
        "src.mcp.errors",
    }
    взято = {
        имя for имя in _импорты(ПАКЕТ / ДВЕРЬ) if имя.startswith("src.mcp.") and имя.count(".") == 2
    }
    лишнее = взято - разрешено
    assert not лишнее, (
        f"Дверь методики взяла у src.mcp лишнее: {sorted(лишнее)}. Разрешено "
        f"хранилище версий и его отказы: {sorted(разрешено)}"
    )
