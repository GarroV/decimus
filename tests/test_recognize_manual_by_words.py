"""Ручной перечень идёт от слов аудитора, а не от зоны (задачи #226, #218).

На живом прогоне 07.09.2026 владелец нажал «выбрать из списка» и получил весь
чек-лист: замер того же дня — 123 пункта по 8 на страницу, то есть 16 страниц
листания в цехе. Владелец, суть: человек на проверке не будет это вычитывать,
нужен другой механизм поиска подходящего пункта.

Вторая половина той же правки — #218. Перечень сужался ПОДСКАЗКОЙ ЗОНЫ, а
подсказкой служила зона прошлой записи. Пункт про печь живёт только в горячем
цехе, поэтому из холодного он исчезал из кнопок вовсе: аудитор не мог выбрать
его даже руками. Слова аудитора зоной не отсекаются — это и стережётся здесь.

Что НЕ меняется: когда слов нет (модель недоступна, разбор шёл по кадру),
перечень остаётся ПОЛНЫМ — всем чек-листом, а зона его только упорядочивает
(T265). Состав и порядок базы стерегут тесты в `test_recognize_manual.py`,
и ослаблять их эта задача не имеет права.
"""

from __future__ import annotations

from pathlib import Path

from src.domain import list_items
from src.recognize.config import NO_CHAT
from src.recognize.manual import manual_candidates


def test_слова_аудитора_дают_короткий_перечень(domain_env: Path) -> None:
    """«Грязная печь» — это единицы пунктов, а не весь чек-лист."""
    полный = manual_candidates("hot_kitchen", chat_id=NO_CHAT)

    итог = manual_candidates("hot_kitchen", note="грязная печь", chat_id=NO_CHAT)

    assert {c.code for c in итог} <= {c.code for c in полный} | {"CLN05", "TEH05"}
    assert len(итог) < len(полный)
    assert len(итог) <= 8, f"перечень должен влезать в одну страницу, а он {len(итог)}"
    assert "CLN05" in {c.code for c in итог}


def test_пункт_чужой_зоны_из_слов_достижим(domain_env: Path) -> None:
    """Главный дефект #218: печь живёт в горячем цехе, а названа из холодного.

    До правки кнопки собирались по подсказке зоны, и пункта про печь в них не
    было вовсе — аудитор не мог исправить промах даже вручную.
    """
    зональные = {i.code for i in list_items(zone="cold_kitchen")}
    assert "CLN05" not in зональные, "предпосылка теста: печь не живёт в холодном цехе"

    итог = manual_candidates("cold_kitchen", note="грязная печь", chat_id=NO_CHAT)

    assert "CLN05" in {c.code for c in итог}


def test_без_слов_перечень_остаётся_полным(domain_env: Path) -> None:
    """Слов нет — сузить нечем, и перечень остаётся всем чек-листом (T265)."""
    все = {i.code for i in list_items() if i.kind == "violation"}

    итог = manual_candidates("hot_kitchen", note="", chat_id=NO_CHAT)

    assert {c.code for c in итог} == все


def test_слова_без_попаданий_перечень_не_обрезают(domain_env: Path) -> None:
    """Сказанное, которого карта не знает, не должно оставлять аудитора без кнопок.

    Пустой перечень здесь был бы худшим исходом: последний рубеж выбора
    превратился бы в тупик ровно там, где предыдущие два уже промолчали.
    Перечень при этом полный — зоной он не режется (T265).
    """
    итог = manual_candidates("hot_kitchen", note="абракадабра шурум-бурум", chat_id=NO_CHAT)

    assert {c.code for c in итог} == {i.code for i in list_items() if i.kind == "violation"}


def test_каждый_пункт_короткого_перечня_несёт_классы_и_текст(domain_env: Path) -> None:
    """Кнопка обязана предлагать то, что примет движок: код, классы, формулировку."""
    итог = manual_candidates("hot_kitchen", note="грязная печь", chat_id=NO_CHAT)

    assert итог
    for пункт in итог:
        assert пункт.levels
        assert пункт.title
