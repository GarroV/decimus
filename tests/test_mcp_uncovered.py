"""Чтение накопителя непокрытых формулировок владельцем (T270).

Накопитель (`src/domain/uncovered.py`, T268) копит случаи, когда аудитор
что-то сказал, а записи не появилось. Сам по себе он файл в состоянии
проверки; ценность у него ровно одна — управляющая компания читает его как
список кандидатов «слово → зона, встретилось N раз» и по частоте дописывает
карту кадров. Здесь проверяется это чтение.

Два свойства важнее остальных, и обоими накопитель отличается от простого
счётчика.

**Пустота не выдаётся за разбор.** «Кандидатов нет» и «накопитель пуст» —
разные ответы, и агент, пересказывающий их человеку, обязан различать их
словами, а не догадываться по нулю.

**Ничего не применяется.** Пополнение карты кадров остаётся ручным (решение
D077): по этой карте быстрый путь пишет находку БЕЗ подтверждения аудитора,
и слово, дописанное автоматически, уехало бы в отчёт партнёру без чьего-либо
ведома. Готового вызова `add_photo_cue` здесь поэтому нет намеренно — ровно
по тому же доводу, по какому его нет у предложений (`suggestions._code_note`):
раздел карты и формулировка строки из сказанного не выводятся.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pytest

from src.domain import (
    OUTCOME_ABANDONED,
    OUTCOME_RECORDED,
    OUTCOME_REFUSED,
    ZONE_SOURCE_DICTIONARY,
    ZONE_SOURCE_WORDS,
    UncoveredEntry,
    record_uncovered,
)
from src.mcp import uncovered as api
from src.mcp.errors import ToolError


def случай(
    note: str,
    *,
    outcome: str = OUTCOME_ABANDONED,
    zone: str = "",
    zone_source: str = "",
    chosen_code: str = "",
    suggested_code: str = "",
    checklist_version: str = "",
) -> UncoveredEntry:
    """Одна запись накопителя. `outcome` с умолчанием: здесь важен не он, а слова."""
    return UncoveredEntry(
        note=note,
        outcome=outcome,
        zone=zone,
        zone_source=zone_source,
        chosen_code=chosen_code,
        suggested_code=suggested_code,
        checklist_version=checklist_version,
    )


def кандидаты(ответ: dict[str, Any]) -> list[str]:
    return [строка["word"] for строка in ответ["candidates"]]


def кандидат(ответ: dict[str, Any], слово: str) -> dict[str, Any]:
    (строка,) = [c for c in ответ["candidates"] if c["word"] == слово]
    return строка


# --- Пустота ------------------------------------------------------------------


def test_пустой_накопитель_говорит_что_он_пуст_а_не_что_кандидатов_нет() -> None:
    """Ноль кандидатов при пустом накопителе и ноль при разобранном — разные
    вещи: первое означает «сигнала не приходило», второе «сигнал пришёл и
    ничего не дал». Слитые в один ответ, они первый раз же будут пересказаны
    человеку как «всё покрыто»."""
    ответ = api.build(())
    assert ответ["candidates"] == []
    assert ответ["considered"]["cases"] == 0
    assert "no formulations" in ответ["status"], ответ["status"]


def test_ответ_всегда_говорит_что_ничего_не_применено() -> None:
    """Агент пересказывает человеку статус, и «собрано N кандидатов» без этой
    приписки читается как «N слов добавлено в карту»."""
    for записи in ((), (случай("грязная печь"),)):
        ответ = api.build(записи)
        assert ответ["applied"] is False
        assert api.NOT_APPLIED in ответ["status"], ответ["status"]


# --- Склейка по основе --------------------------------------------------------


def test_разные_формы_одного_слова_считаются_вместе() -> None:
    """Ради этого инструмент и заводился: «печь» и «печи» — одно слово, и
    разнесённые по двум строкам они выглядят как два редких случая вместо
    одного частого, то есть прячут ровно тот сигнал, за которым сюда идут."""
    ответ = api.build(
        (случай("грязная печь"), случай("нагар на печи"), случай("печи в саже")),
    )
    строка = кандидат(ответ, "печи")
    assert строка["count"] == 3, f"формы не склеились: {ответ['candidates']}"
    формы = {ф["form"]: ф["count"] for ф in строка["forms"]}
    assert формы == {"печь": 1, "печи": 2}, формы


def test_названо_то_слово_которое_произносили_а_не_основа() -> None:
    """Основа — внутренний ключ склейки, а не слово языка: показанная человеку,
    она выглядит опечаткой и в карту кадров в таком виде не попадает."""
    ответ = api.build((случай("нагар на печи"),))
    assert кандидаты(ответ) == ["нагар", "печи"], кандидаты(ответ)
    assert "печ" not in кандидаты(ответ), "человеку показана основа, а не слово"


def test_слова_без_смысла_в_кандидаты_не_идут() -> None:
    """Предлоги и союзы встречаются в каждой второй формулировке и, попав в
    выдачу, займут её верх целиком — то есть вытеснят то, ради чего её читают."""
    ответ = api.build((случай("на печи и в углу"),))
    assert "на" not in кандидаты(ответ)
    assert "и" not in кандидаты(ответ)


def test_повтор_слова_внутри_одной_фразы_не_удваивает_счёт() -> None:
    """Счёт означает «во скольких случаях слово встретилось», а не «сколько раз
    произнесено»: удвоение подняло бы наверх многословную формулировку, а не частую."""
    ответ = api.build((случай("печь грязная, печь в нагаре"),))
    assert кандидат(ответ, "печь")["count"] == 1


# --- Зона рядом со словом -----------------------------------------------------


def test_зона_называется_рядом_со_словом_с_числом_повторов() -> None:
    """Форма выдачи из контракта блока: «слово → зона, встретилось N раз».
    Слово без зоны не говорит управляющей компании, куда класть строку карты."""
    ответ = api.build(
        (
            случай("грязная печь", zone="hot_kitchen", zone_source=ZONE_SOURCE_DICTIONARY),
            случай("нагар на печи", zone="hot_kitchen", zone_source=ZONE_SOURCE_WORDS),
            случай("печи в саже", zone="cold_kitchen", zone_source=ZONE_SOURCE_WORDS),
        )
    )
    зоны = [(з["zone"], з["count"]) for з in кандидат(ответ, "печи")["zones"]]
    assert зоны == [("hot_kitchen", 2), ("cold_kitchen", 1)], зоны


def test_зона_не_вывелась_названа_пустотой_а_не_кодом() -> None:
    """Пустая строка среди кодов зон читается как код зоны с пустым именем —
    то есть как зона, которой в методике нет. «Зоны не вывелось» — это
    отсутствие значения, и в выдаче оно обязано выглядеть отсутствием."""
    ответ = api.build((случай("стеллаж грязный"),))
    зоны = кандидат(ответ, "стеллаж")["zones"]
    assert зоны == [{"zone": None, "count": 1}], зоны


# --- Исход и выбранный пункт --------------------------------------------------


def test_исходы_считаются_порознь() -> None:
    """«Формулировка ничему не соответствует» и «соответствует, но аудитор
    не стал разбирать» требуют разных правок карты, и слитые в одно число они
    неразличимы."""
    ответ = api.build(
        (
            случай("грязная печь", outcome=OUTCOME_ABANDONED),
            случай("печи в саже", outcome=OUTCOME_REFUSED),
            случай("нагар на печи", outcome=OUTCOME_RECORDED, chosen_code="CLN05"),
        )
    )
    assert кандидат(ответ, "печи")["outcomes"] == {
        OUTCOME_ABANDONED: 1,
        OUTCOME_REFUSED: 1,
        OUTCOME_RECORDED: 1,
    }


def test_выбранный_в_итоге_пункт_назван_рядом_со_словом() -> None:
    """Слово, за которым стоит уже известный пункт, — готовый кандидат в карту;
    слово, за которым не стоит ничего, — вопрос к человеку. Различить их по
    выдаче обязано быть можно."""
    ответ = api.build(
        (
            случай("нагар на печи", outcome=OUTCOME_RECORDED, chosen_code="CLN05"),
            случай("печи в саже", outcome=OUTCOME_RECORDED, chosen_code="CLN05"),
            случай("грязная печь", outcome=OUTCOME_ABANDONED),
        )
    )
    assert кандидат(ответ, "печи")["chosen_codes"] == [{"code": "CLN05", "count": 2}]


def test_готового_вызова_пополнения_карты_в_ответе_нет() -> None:
    """Решение D077 и довод `suggestions._code_note`: раздел карты и
    формулировка строки из сказанного не выводятся, и собранный за человека
    вызов решил бы за управляющую компанию ровно то, что D077 оставляет ей."""
    ответ = api.build((случай("нагар на печи", outcome=OUTCOME_RECORDED, chosen_code="CLN05"),))
    assert "add_photo_cue" not in str(ответ["candidates"])


# --- Фразы --------------------------------------------------------------------


def test_фразы_показаны_дословно_с_числом_повторов() -> None:
    """По фразе человек понимает, что именно было сказано; по слову — что
    дописывать. Одно другого не заменяет (тот же довод, что у T194)."""
    ответ = api.build((случай("грязная печь"), случай("грязная печь"), случай("печи в саже")))
    фразы = {ф["phrase"]: ф["count"] for ф in кандидат(ответ, "печь")["heard"]["phrases"]}
    assert фразы == {"грязная печь": 2, "печи в саже": 1}


def test_фраза_без_значимых_слов_не_теряется() -> None:
    """Накопитель существует затем, чтобы сигнал не пропадал. Формулировка, из
    которой не вышло ни одного кандидата, потерялась бы молча — а это ровно тот
    исход, ради снятия которого его и завели."""
    ответ = api.build((случай("на и у"), случай("грязная печь")))
    assert кандидаты(ответ) == ["грязная", "печь"], кандидаты(ответ)
    assert ответ["unclassified_phrases"] == [{"phrase": "на и у", "count": 1}]
    assert ответ["considered"]["without_candidate_words"] == 1


# --- Порядок и предел ---------------------------------------------------------


def test_частое_слово_впереди_редкого_а_при_равенстве_порядок_задан() -> None:
    """Выдача, зависящая от порядка записей в файле, менялась бы между двумя
    одинаковыми вопросами, и человек прочитал бы это как изменение в данных."""
    ответ = api.build((случай("печи в саже"), случай("грязная печь"), случай("стеллаж")))
    assert кандидаты(ответ) == ["печи", "грязная", "саже", "стеллаж"], кандидаты(ответ)


def test_предел_режет_и_говорит_что_режет() -> None:
    """Обрезанная выдача, выданная за полную, — это разбор по половине сигнала,
    который выглядит точно так же, как разбор по всему."""
    записи = tuple(случай(f"печь{n} грязная") for n in range(5))
    ответ = api.build(записи, limit=2)
    assert len(ответ["candidates"]) == 2
    assert ответ["truncated"] is True
    assert api.build(записи)["truncated"] is False


@pytest.mark.parametrize("негодный", [0, -1])
def test_негодный_предел_отказ_а_не_молчаливая_замена(негодный: int) -> None:
    """Молча подставленное умолчание отдало бы выдачу, которой не просили, и
    спросивший прочитал бы её как ответ на свой вопрос."""
    with pytest.raises(ToolError):
        api.build((случай("грязная печь"),), limit=негодный)


# --- Границы выборки ----------------------------------------------------------


def test_версии_методики_названы_в_выборке() -> None:
    """Карта кадров правится под конкретное издание чек-листа: кандидаты,
    собранные через два переиздания, правятся разными строками."""
    ответ = api.build(
        (
            случай("грязная печь", checklist_version="imf-2026-01-01-aaaaaaaaaaaa"),
            случай("печи в саже", checklist_version="imf-2026-02-02-bbbbbbbbbbbb"),
            случай("нагар на печи"),
        )
    )
    сведения = ответ["considered"]
    assert сведения["checklist_versions"] == [
        "imf-2026-01-01-aaaaaaaaaaaa",
        "imf-2026-02-02-bbbbbbbbbbbb",
    ]
    assert сведения["without_version"] == 1


def test_оговорки_уезжают_в_ответ_а_не_остаются_в_модуле() -> None:
    """Читающий обязан узнать границы выборки из самой выборки: оговорка,
    оставшаяся в исходнике, человеку не достанется никогда."""
    ответ = api.build((случай("грязная печь"),))
    assert list(api.CAVEATS) == ответ["caveats"]
    assert ответ["caveats"], "оговорки пусты — границы выборки нигде не названы"


# --- Чтение из состояния проверки ---------------------------------------------


def test_читает_накопители_всех_проверок(domain_env: Path) -> None:
    """Владелец спрашивает по сети, а не по чату: чат — это внутреннее имя
    разговора в мессенджере, и называть его в вопросе некому."""
    record_uncovered(11, случай("грязная печь"))
    record_uncovered(22, случай("нагар на печи"))
    ответ = api.read_all()
    assert ответ["considered"]["cases"] == 2
    assert кандидат(ответ, "печи")["count"] == 2


def test_испорченный_накопитель_отказ_и_без_пути_на_диске(domain_env: Path) -> None:
    """Молчаливая пустота здесь означает потерянный сигнал. Путь при этом в
    ответ не уезжает: по нему видно устройство каталогов деплоя и имя
    пользователя, под которым поднят сервер (T120)."""
    record_uncovered(11, случай("грязная печь"))
    файл = next(domain_env.glob("chat_*/uncovered.json"))
    файл.write_text("{ не json", encoding="utf-8")
    with pytest.raises(ToolError) as отказ:
        api.read_all()
    текст = str(отказ.value)
    assert str(файл) not in текст, f"путь уехал в ответ: {текст}"
    assert "STATE_DIR" in текст, f"отказ не называет, где искать: {текст}"
