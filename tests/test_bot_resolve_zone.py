"""T263: одна точка вывода зоны — слова, словарь, спрос. Пятого источника нет.

Задача выросла из живого прогона владельца (#218, #225). Два его требования
стоят рядом и оба жёсткие:

* «пицца-печь это всегда горячий цех и никакой другой» — объект со словарной
  зоной ставится жёстко, без вопроса;
* «стеллажи бывают в разных цехах — и там нужно уточнение» — объект без зоны
  спрашивает, а не подставляет догадку.

И отдельно #225: «полы в холодном» — так место называют на точке, и разбор
обязан узнать зону в этой форме, иначе она молча уедет в чужую.

Прошлой записи среди источников нет намеренно (T264): именно ею печь и попала в
холодный цех — гадала не модель.
"""

from __future__ import annotations

import logging
from pathlib import Path

import pytest
from bot_harness import CHAT_ID

from src.bot.zones import ASK, DICTIONARY, WORDS, allowed_zones, resolve_zone, zone_from_words
from src.domain import get_item, list_zones

# --- зона, названная словами в живой форме (#225) ---------------------------


@pytest.mark.parametrize(
    ("слова", "зона"),
    [
        # Дословный случай задачи: до неё разбор отвечал `None`, и дальше
        # подставлялась зона ПРОШЛОЙ записи.
        ("полы в холодном", "cold_kitchen"),
        ("в тепловом нагар на подине", "hot_kitchen"),
        ("на кассе грязно", "dining"),
        ("в мучном рассыпана мука", "dough"),
        ("in the cold station the floor is dirty", "cold_kitchen"),
    ],
)
def test_место_узнаётся_без_существительного(domain_env: Path, слова: str, зона: str) -> None:
    assert zone_from_words(слова, chat_id=CHAT_ID) == зона


@pytest.mark.parametrize(
    "слова",
    [
        # Признак ПРЕДМЕТА, а не место: без предлога это не форма без
        # существительного, а прилагательное при своём существительном.
        "холодная вода не идёт",
        "тесто холодное на ощупь",
        # Имя без семьи определения не даёт вовсе: «стеллаж» — это объект,
        # который стоит в разных цехах, а не зона.
        "стеллаж грязный",
        "на стеллаже коробки",
    ],
)
def test_признак_предмета_зоной_не_становится(domain_env: Path, слова: str) -> None:
    assert zone_from_words(слова, chat_id=CHAT_ID) is None


def test_названное_целиком_имя_сильнее_формы_без_существительного(domain_env: Path) -> None:
    """Определение весит одно слово и спорить с названным именем не должно.

    Названы два места: одно определением («в холодном»), другое именем целиком.
    Выигрывает названное целиком — тем же правилом, каким длинное имя выигрывает
    у короткого.
    """
    слова = "в холодном на стеллаже хранения коробки на полу"

    assert zone_from_words(слова, chat_id=CHAT_ID) == "dry_storage"


# --- порядок источников -----------------------------------------------------


def test_слова_аудитора_сильнее_словаря(domain_env: Path) -> None:
    """Его слово берётся всегда — но расхождение называется, а не глотается."""
    итог = resolve_zone("в тепловом печь грязная", "CLN05", chat_id=CHAT_ID)

    assert (итог.zone, итог.source) == ("hot_kitchen", WORDS)
    assert итог.conflict is None, "зона объекта и названная совпали — расхождения нет"


def test_печь_без_названной_зоны_попадает_в_горячий_цех(domain_env: Path) -> None:
    """Слова владельца: «пицца-печь это всегда горячий цех и никакой другой».

    Одна зона в словаре = жёстко, без вопроса. До задачи здесь подставлялась
    зона прошлой записи, и печь уезжала в холодный цех.
    """
    итог = resolve_zone("печь грязная", "CLN05", chat_id=CHAT_ID)

    assert (итог.zone, итог.source) == ("hot_kitchen", DICTIONARY)
    assert итог.conflict is None


def test_стеллаж_без_названной_зоны_спрашивает(domain_env: Path) -> None:
    """Слова владельца: «стеллажи бывают в разных цехах — нужно уточнение».

    Зона здесь не подставляется ничем: пустая колонка «Зона» и означает
    «спросить». Вывод по пересечению зон пунктов дал бы одну — и неверную.
    """
    итог = resolve_zone("стеллаж грязный", "CLN01", chat_id=CHAT_ID)

    assert итог.zone is None, "зона подставилась там, где владелец просил спросить"
    assert итог.source == ASK
    assert "dry_storage" not in итог.options, (
        "сухой склад попал в кнопки: методика не даёт этому пункту такой зоны"
    )


def test_расхождение_слов_и_словаря_называется_до_фиксации(domain_env: Path) -> None:
    """Случай владельца: «холодный цех, пицца-печь». Молча не пишется ни то, ни то."""
    итог = resolve_zone("в холодном печь грязная", "CLN05", chat_id=CHAT_ID)

    assert (итог.zone, итог.source) == ("cold_kitchen", WORDS), "слово аудитора обязано остаться"
    assert итог.conflict is not None, "расхождение проглочено — аудитор о нём не узнает"
    assert (итог.conflict.spoken, итог.conflict.dictionary) == ("cold_kitchen", "hot_kitchen")
    assert итог.conflict.phrase == "Печь", "расхождение нечем объяснить: объект не назван"


def test_объект_с_разными_зонами_в_карте_ничего_не_выводит(domain_env: Path) -> None:
    """Зон у объекта несколько — выбирать за человека разбор не вправе."""
    итог = resolve_zone("шкаф с дверцей не закрывается", "TEH06", chat_id=CHAT_ID)

    assert итог.source == ASK


def test_прошлая_запись_среди_источников_не_значится(domain_env: Path) -> None:
    """Проверка устройства, а не поведения: у вывода зоны три входа, и памяти

    среди них нет. Подпись функции — единственное место, где это видно
    механизмом, а не обещанием в доке (#218).
    """
    import inspect

    параметры = set(inspect.signature(resolve_zone).parameters)

    assert параметры == {"note", "item_code", "chat_id"}, (
        "у вывода зоны появился лишний вход — проверьте, не память ли это"
    )


# --- кнопки спроса: только допустимые методикой зоны (T266) -----------------


def test_кнопки_только_из_зон_допустимых_методикой(domain_env: Path) -> None:
    """Спрашивать тем, чего движок не примет, нельзя: кнопка дала бы отказ."""
    пункт = get_item("CLN05", chat_id=CHAT_ID)

    assert allowed_zones("CLN05", chat_id=CHAT_ID) == ("hot_kitchen",)
    assert пункт.zones == ["hot_kitchen"], "оснастка проверяет не то: у пункта не одна зона"


def test_пункт_во_всех_зонах_даёт_все_кнопки(domain_env: Path) -> None:
    все = tuple(zone.code for zone in list_zones(chat_id=CHAT_ID))

    assert allowed_zones(None, chat_id=CHAT_ID) == все, "пункт не назван — сузить перечень нечем"
    assert allowed_zones("НЕТ-ТАКОГО", chat_id=CHAT_ID) == все, (
        "неизвестный пункт обязан давать все зоны, а не пустые кнопки"
    )


def test_кнопки_идут_в_порядке_методики(domain_env: Path) -> None:
    """Порядок зон задаёт управляющая компания, а не сортировка кода."""
    все = [zone.code for zone in list_zones(chat_id=CHAT_ID)]
    свои = allowed_zones("CLN01", chat_id=CHAT_ID)

    assert list(свои) == [code for code in все if code in свои]


# --- битые данные карты -----------------------------------------------------


def test_несуществующая_зона_в_карте_не_роняет_разбор(
    domain_env: Path,
    data_copy: Path,
    monkeypatch: pytest.MonkeyPatch,
    caplog: pytest.LogCaptureFixture,
) -> None:
    """Опечатка управляющей компании — запись в журнал, а не молчаливая подстановка.

    Отказ здесь был бы хуже: карта числится необязательным файлом методики
    (D068), и падение всплыло бы не при подъёме стенда, а в чате у аудитора.
    """
    карта = data_copy / "photo-cues.md"
    карта.write_text(
        карта.read_text(encoding="utf-8").replace("| hot_kitchen |", "| hot_kithcen |"),
        encoding="utf-8",
    )
    monkeypatch.setenv("AUDIT_DATA_DIR", str(data_copy))

    with caplog.at_level(logging.WARNING):
        итог = resolve_zone("печь грязная", "CLN05", chat_id=CHAT_ID)

    assert итог.source == ASK, "зоны, которой нет в методике, подставлять нельзя"
    assert "hot_kithcen" in caplog.text, "опечатка в карте прошла молча"
