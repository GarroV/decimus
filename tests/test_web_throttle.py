"""T325: правило ограничителя перебора — арифметика, без базы и без экрана.

Здесь проверяется то, чья ошибка молчит. Ограничитель не падает и не кричит:
ошибка в шаге или в сроке забвения оставляет форму входа открытой для перебора,
а выглядит она при этом ровно так же, как рабочая. Поэтому правило вынесено в
чистые функции (`src/db/web_throttle.py`) и проверяется свойствами, а не
пересказом констант: пересказ покраснел бы при любой настройке порога, ничего
при этом не поймав.

Живой путь до Postgres проверяет `tests/test_db_web_throttle.py`, а путь через
форму входа — `tests/test_web_login_limit.py`.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

import pytest

from src.db.web_throttle import (
    FAILURES_BEFORE_LOCK,
    FORGET_AFTER,
    LOCK_STEPS,
    SCOPE_ADDRESS,
    SCOPE_LOGIN,
    SCOPES,
    Counter,
    canonical_address,
    key_fingerprint,
    lock_for,
    verdict_of,
)

СЕЙЧАС = datetime(2026, 9, 18, 12, 0, tzinfo=UTC)


def строка(failures: int, *, назад: timedelta = timedelta(0)) -> Counter:
    return Counter(failures=failures, updated_at=СЕЙЧАС - назад)


# --- сколько неудач терпится ------------------------------------------------


@pytest.mark.parametrize("scope", SCOPES)
def test_ниже_порога_ключ_не_заперт(scope: str) -> None:
    """Последняя попытка перед порогом обязана проходить: человек ошибается."""
    порог = FAILURES_BEFORE_LOCK[scope]
    assert lock_for(порог - 1, scope=scope) == timedelta(0)


@pytest.mark.parametrize("scope", SCOPES)
def test_на_пороге_запрет_наступает(scope: str) -> None:
    assert lock_for(FAILURES_BEFORE_LOCK[scope], scope=scope) > timedelta(0)


@pytest.mark.parametrize("scope", SCOPES)
def test_каждая_следующая_неудача_не_укорачивает_запрет(scope: str) -> None:
    """Срок растёт или стоит, но не убывает.

    Убывающий шаг — это дыра, которую видно только арифметикой: перебор
    дождался бы длинного запрета, а дальше шёл бы по коротким.
    """
    порог = FAILURES_BEFORE_LOCK[scope]
    сроки = [lock_for(n, scope=scope) for n in range(порог, порог + len(LOCK_STEPS) + 5)]
    assert сроки == sorted(сроки)


@pytest.mark.parametrize("scope", SCOPES)
def test_запрет_не_растёт_бесконечно(scope: str) -> None:
    """Потолок есть, и он не запирает человека на сутки за чужой перебор."""
    порог = FAILURES_BEFORE_LOCK[scope]
    assert lock_for(порог + 10_000, scope=scope) == max(LOCK_STEPS)
    assert max(LOCK_STEPS) <= timedelta(hours=1)


@pytest.mark.parametrize("scope", SCOPES)
def test_счётчик_не_забывается_раньше_чем_кончится_запрет(scope: str) -> None:
    """Главный инвариант двух констант, которые правятся рядом.

    Забвение раньше запрета означало бы, что ключ открывается ДОСРОЧНО и сам,
    причём тем раньше, чем злее был перебор: строка исчезает, счётчик обнуляется,
    посчитанный по нему запрет исчезает вместе с ним.
    """
    assert FORGET_AFTER > lock_for(FAILURES_BEFORE_LOCK[scope] + 10_000, scope=scope)


# --- приговор по строке счётчика --------------------------------------------


def test_пустой_счётчик_никого_не_запирает() -> None:
    assert not verdict_of(None, scope="login", now=СЕЙЧАС).locked


def test_свежая_строка_за_порогом_запирает() -> None:
    приговор = verdict_of(строка(FAILURES_BEFORE_LOCK["login"]), scope="login", now=СЕЙЧАС)
    assert приговор.locked
    assert приговор.retry_after > timedelta(0)


def test_запрет_кончается_временем_а_не_попытками() -> None:
    """Прошёл срок — дверь открыта снова, хотя счётчик не тронут."""
    давняя = строка(FAILURES_BEFORE_LOCK["login"], назад=max(LOCK_STEPS) + timedelta(seconds=1))
    assert not verdict_of(давняя, scope="login", now=СЕЙЧАС).locked


def test_оставшийся_срок_уменьшается_со_временем() -> None:
    свежая = verdict_of(строка(FAILURES_BEFORE_LOCK["login"]), scope="login", now=СЕЙЧАС)
    полежавшая = verdict_of(
        строка(FAILURES_BEFORE_LOCK["login"], назад=timedelta(seconds=30)),
        scope="login",
        now=СЕЙЧАС,
    )
    assert полежавшая.retry_after < свежая.retry_after


def test_срок_человеку_округляется_вверх() -> None:
    """«Приходите через 0 минут» — это приглашение долбиться в закрытую дверь."""
    почти = строка(FAILURES_BEFORE_LOCK["login"], назад=min(LOCK_STEPS) - timedelta(seconds=1))
    приговор = verdict_of(почти, scope="login", now=СЕЙЧАС)
    assert приговор.locked
    assert приговор.retry_after_minutes >= 1
    assert приговор.retry_after_seconds >= 1


# --- ключ счётчика ----------------------------------------------------------


def test_введённое_человеком_в_ключ_не_попадает() -> None:
    """В базу уезжает отпечаток, а не то, что напечатали в поле «логин».

    Туда печатают, среди прочего, пароль от соседней системы — и он оставался
    бы в базе дословно.
    """
    отпечаток = key_fingerprint("director")
    assert "director" not in отпечаток
    assert len(отпечаток) == 64
    assert set(отпечаток) <= set("0123456789abcdef")


def test_один_и_тот_же_логин_считается_одним_ключом() -> None:
    """Иначе счётчик обходится сменой регистра и пробелом."""
    assert key_fingerprint(" Director ") == key_fingerprint("director")


def test_разные_ключи_не_складываются_в_один() -> None:
    assert key_fingerprint("director") != key_fingerprint("manager")


# --- адрес до отпечатка приводится к канону (T328) ---------------------------


@pytest.mark.parametrize(
    ("одна_запись", "другая_запись"),
    [
        ("2001:db8::1", "2001:db8:0:0:0:0:0:1"),
        ("2001:DB8::1", "2001:db8::1"),
        ("::ffff:203.0.113.7", "203.0.113.7"),
        (" 203.0.113.7 ", "203.0.113.7"),
    ],
)
def test_один_адрес_записанный_по_разному_даёт_один_ключ(
    одна_запись: str, другая_запись: str
) -> None:
    """Иначе счётчик по адресу обходится сменой записи того же адреса.

    Сжатые и развёрнутые нули IPv6, IPv4 внутри IPv6, регистр — всё это один и
    тот же отправитель, и второй счётчик у него означает второй запас попыток.
    """
    assert key_fingerprint(canonical_address(одна_запись)) == key_fingerprint(
        canonical_address(другая_запись)
    )


def test_разные_адреса_в_один_ключ_не_сливаются() -> None:
    """Обратная половина: канон не обязан склеивать соседей по подсети."""
    assert canonical_address("203.0.113.7") != canonical_address("203.0.113.8")
    assert canonical_address("2001:db8::1") != canonical_address("2001:db8::2")


def test_неразобранный_адрес_остаётся_ключом() -> None:
    """`unknown` (сокет без адреса) обязан считаться, а не пропадать из учёта."""
    assert canonical_address("unknown") == "unknown"
    assert len(key_fingerprint(canonical_address("unknown"))) == 64


# --- якорь на САМИ ЗНАЧЕНИЯ, а не на логику вокруг них (T327) ----------------
#
# Всё, что выше, считает порог от константы — и поэтому переживает любую её
# правку. Замер это подтвердил: `FAILURES_BEFORE_LOCK` подняли до 100 000, то
# есть ограничитель сняли начисто, и одиннадцать проверок формы входа остались
# зелёными. Проверки не виноваты: они сторожат правило «после порога запирает»,
# и сторожат верно. Просто боевое значение порога не сторожило НИЧТО.
#
# Здесь стоит второе: значения остаются осмысленными. Не «равны пяти» — такой
# якорь красился бы при любой настройке и его бы подогнали не глядя, — а «лежат
# в пределах, за которыми обещание продукта перестаёт быть правдой».

#: Порог по логину: выше этого «пять промахов — уже не опечатка» превращается в
#: «подбирай сколько влезет». Взято с запасом от нынешних пяти.
ПОТОЛОК_ПОРОГА_ЛОГИНА = 10

#: Порог по адресу выше, потому что за одним адресом законно живёт контора
#: целиком. Но не настолько выше, чтобы перестать быть порогом.
ПОТОЛОК_ПОРОГА_АДРЕСА = 50

#: Сколько попыток за сутки с одного ключа означает «подбор перестал
#: окупаться». Не тугая граница нынешних значений (они дают три десятка), а
#: линия, за которой обещание из `docs/12-web-admin.md` — «упирается в
#: несколько попыток в час» — становится неправдой.
ПОТОЛОК_ПОПЫТОК_В_СУТКИ = 120

#: Предохранитель от бесконечного цикла в счёте ниже: при снятом ограничителе
#: попытки бесплатны, и время в модели не двигается вовсе.
ПРЕДЕЛ_ШАГОВ = 10_000

СУТКИ = timedelta(days=1)


def проб_за_сутки(*, scope: str) -> int:
    """Сколько раз упорный доберётся до сверки пароля за сутки, долбясь без пауз.

    Считается ТЕМИ ЖЕ функциями, что стоят в продукте: копия правила рядом с
    проверкой сторожила бы саму себя. Модель простая и честно названная —
    перебирающий бьёт без перерыва и ждёт ровно столько, сколько его заперли.
    """
    момент = timedelta(0)
    неудач = 0
    проб = 0
    while момент <= СУТКИ and проб < ПРЕДЕЛ_ШАГОВ:
        проб += 1
        неудач += 1
        момент += lock_for(неудач, scope=scope)
    return проб


@pytest.mark.parametrize("scope", SCOPES)
def test_упорный_перебор_упирается_в_десятки_попыток_в_сутки(scope: str) -> None:
    """Главный якорь: обещание продукта, посчитанное из боевых значений.

    Красится он не от «цифра не та», а от «подбор снова окупается»: снятый
    порог, запрет длиной в секунду, потолок срока в минуту — всё это здесь
    видно как тысячи попыток в сутки.
    """
    проб = проб_за_сутки(scope=scope)
    assert проб < ПРЕДЕЛ_ШАГОВ, (
        f"за сутки по ключу «{scope}» проходит больше {ПРЕДЕЛ_ШАГОВ} попыток — "
        f"это не ограничитель, а его отсутствие"
    )
    assert проб <= ПОТОЛОК_ПОПЫТОК_В_СУТКИ, (
        f"за сутки по ключу «{scope}» проходит {проб} попыток при потолке "
        f"{ПОТОЛОК_ПОПЫТОК_В_СУТКИ}: подбор снова окупается"
    )


def test_порог_по_логину_остаётся_человеческим() -> None:
    """Пять промахов — не опечатка; пятьдесят — уже не порог."""
    порог = FAILURES_BEFORE_LOCK[SCOPE_LOGIN]
    assert 2 <= порог <= ПОТОЛОК_ПОРОГА_ЛОГИНА, (
        f"порог по логину {порог}: ниже двух он запирает человека на первой же "
        f"опечатке, выше {ПОТОЛОК_ПОРОГА_ЛОГИНА} — перестаёт мешать подбору"
    )


def test_порог_по_адресу_выше_логинного_но_остаётся_порогом() -> None:
    """За адресом бывает контора целиком — но не бесконечный запас попыток."""
    по_адресу = FAILURES_BEFORE_LOCK[SCOPE_ADDRESS]
    assert FAILURES_BEFORE_LOCK[SCOPE_LOGIN] <= по_адресу <= ПОТОЛОК_ПОРОГА_АДРЕСА, (
        f"порог по адресу {по_адресу} обязан лежать между порогом логина и {ПОТОЛОК_ПОРОГА_АДРЕСА}"
    )


def test_самый_короткий_запрет_не_короче_минуты() -> None:
    """Запрет на секунды перебору не мешает вовсе, а выглядит как ограничитель."""
    assert min(LOCK_STEPS) >= timedelta(minutes=1), (
        f"самый короткий запрет {min(LOCK_STEPS)}: короче минуты он не замедляет "
        f"подбор, зато создаёт видимость, что подбор замедлен"
    )
