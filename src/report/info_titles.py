"""Подписи полей информационной части — формулировки вопросов по кодам.

В базе поле записано КОДОМ (`INF01`, `INF03`, …) и ответом дословно. Человеку
код ничего не говорит, а ответ «Да» без вопроса не значит вовсе ничего —
замечание владельца 28.09: «не ясно что да? что нет? какие вопросы то были?».

Правило общее для двух поверхностей — карточки MCP (`src/mcp/info_part.py`) и
карточки веба (`src/web/inspections.py`) — и потому живёт здесь, у общего
для них яруса. Две копии разошлись бы молча: одна подписала бы ответ
формулировкой другой версии, и заметить это было бы нечем.

**Подпись берётся из ТОЙ версии методики, которой помечена проверка.**
Формулировку вопроса правит управляющая компания, и сегодняшняя подпись под
прошлогодним ответом — другой вопрос под прежней датой (D033, D049).
"""

from __future__ import annotations

import csv
from pathlib import Path

from ..domain.models import TEXT_LANGS, pick_text
from .engine_call import to_log
from .errors import ReportError
from .letters import Papers, pinned

#: Колонка методики с кодом пункта — та же, что читает движок.
CODE_COLUMN = "id"

#: Файл методики, в котором лежат формулировки пунктов.
ITEMS_FILE = "checklist.csv"

#: Почему подписи есть — или почему их нет (T243). Слитые в одно «нет», они
#: посылали читающего искать снимок, которого никто не терял.
#:
#: * `FOUND` — методика той версии на машине есть, подписи взяты из неё;
#: * `NOT_AT_HAND` — издание не опознано (сверку ведёт `pinned`, T236);
#: * `NOT_A_NAME` — идентификатор версии в проверке именем каталога быть не
#:   может: чинить надо запись, а не диск.
FOUND = "found"
NOT_AT_HAND = "not-at-hand"
NOT_A_NAME = "not-a-name"


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as f:
        return [
            {k: (v or "") for k, v in row.items() if k is not None} for row in csv.DictReader(f)
        ]


def titles(version: str, *, lang: str, papers: Papers) -> tuple[dict[str, str], str]:
    """Подписи пунктов по кодам из методики этой версии и что с самой методикой.

    Второе значение отделено от пустого словаря намеренно: «методики этой
    версии на машине нет» и «методика есть, а такого пункта в ней нет» — разные
    ответы человеку, и по пустому словарю их не различить.

    Отказом это не становится ни в каком случае: подписи — украшение к
    записанным ответам, и ответы читаются без единого файла методики. Отказ
    вместо них означал бы, что испорченная строка в базе прячет от человека
    документ, который уже ушёл партнёру.
    """
    if lang not in TEXT_LANGS:
        return {}, NOT_AT_HAND
    try:
        найдено = pinned(version, papers)
    except ReportError:
        return {}, NOT_A_NAME
    if найдено is None:
        return {}, NOT_AT_HAND
    каталог, _ = найдено
    try:
        строки = _rows(каталог / ITEMS_FILE)
    except OSError:
        # Путь — в лог процесса, а не в ответ (T120): снимок версии без файла
        # пунктов — поломка хранилища, и чинящему нужно знать, где смотреть.
        to_log("методику версии проверки не прочитать", метка="info", методика=каталог)
        return {}, NOT_AT_HAND
    подписи: dict[str, str] = {}
    for строка in строки:
        код = (строка.get(CODE_COLUMN) or "").strip().upper()
        подпись = pick_text(
            строка.get("question_ru", ""), строка.get("question_en", ""), lang
        ).strip()
        # Первое вхождение кода, а не последнее: движок читает дубль так же.
        # Строка-комментарий пропускается там же.
        if код and not код.startswith("#") and подпись:
            подписи.setdefault(код, подпись)
    return подписи, FOUND
