"""Общее для тех, кто зовёт движок подпроцессом: где он лежит, сколько ждать, что печатать.

Вынесено сюда из `src/mcp/checklist.py` (T321), когда пересборка письма
понадобилась ВТОРОЙ поверхности — веб-админке. Слой выбран не по красоте:
`lint-imports` держит `src.bot`, `src.mcp` и `src.web` пирами, и общее у двух
пиров обязано лежать ярусом ниже. Скопировать эти двадцать строк в третий раз
было нельзя: `_clean` вычищает из текста движка путь к каталогу продукта, и
копия, отставшая на одну правку, однажды отдала бы наружу устройство машины.

Движок здесь по-прежнему ЗОВЁТСЯ, а не импортируется: контракт
`engine-not-imported` запрещает импорт всем блокам `src`, и правила разметки
письма и расчёта живут в движке в одном экземпляре.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

from ..domain.version import SEGMENT_BYTES, is_one_segment
from .errors import ReportError


class EngineCallError(ReportError):
    """Движок позвать не вышло, или позван он был с негодным аргументом.

    Отдельный тип, а не общий `ReportError`: зовущие блоки переводят его в
    свой словарь отказов — MCP в `ToolError`, админка в экран с причиной, — и
    смешать его со сбоем сборки PDF значило бы показать человеку не то.
    """


#: Каталог версий методики внутри хранилища. Имя общее для всех, кто в это
#: хранилище смотрит: разойдясь, они читали бы разные каталоги.
VERSIONS_DIR = "versions"


def edition_dirs(store_root: Path, edition: str) -> list[Path]:
    """Где в хранилище может лежать издание — все места сразу, годность решает отпечаток.

    Хранилище стало двухуровневым (T341, D183): издания живут в
    `<store>/<пространство>/<код>/versions/`, а не в `<store>/versions/`.
    Однослойный путь остаётся в перечне намеренно — хранилище, которое ещё не
    переносили, обязано читаться как раньше, иначе письмо по вчерашней проверке
    вдруг перестало бы собираться.

    Имя издания уже проверено вызывающим (`check_version`), но перебор каталогов
    добавляет к пути два своих куска, и оба берутся с диска, а не из ответа
    базы: подставить `..` сюда нечему.

    Порядок ответа устойчив (обход отсортирован), а на правильность он не
    влияет вовсе: годится тот каталог, чьё СОДЕРЖИМОЕ и есть это издание, —
    решает сверка отпечатка у вызывающего, а не очередь.
    """
    места = [store_root / VERSIONS_DIR / edition]
    if store_root.is_dir():
        for пространство in sorted(p for p in store_root.iterdir() if p.is_dir()):
            if пространство.name.startswith(".") or пространство.name == VERSIONS_DIR:
                continue
            for чеклист in sorted(c for c in пространство.iterdir() if c.is_dir()):
                места.append(чеклист / VERSIONS_DIR / edition)
    return места


#: Чем заменяется путь кандидата в тексте отказа движка. Движок называет файл,
#: в котором проблема, — а это временная копия: показать её значит показать
#: путь, которого у человека нет и не будет.
CANDIDATE_LABEL = "<каталог новой версии>"

#: Сколько ждём движок. Разбор пары CSV — секунды; всё, что дольше, — зависший
#: подпроцесс, держащий поток сервера.
ENGINE_TIMEOUT_SEC = 60

#: Что печатает сам интерпретатор питона, умерший фатально. В выводе движка
#: такого не бывает: свои отказы он объясняет словами и выходит нормально.
RUNTIME_FATAL = "Fatal Python error"

#: ...и что при этом инициализация не закончилась. `core initialized` означает,
#: что до первой строки скрипта дело НЕ дошло: повторить запуск безопасно.
RUNTIME_BEFORE_SCRIPT = "Python runtime state: core initialized"

REPO_ROOT = Path(__file__).resolve().parents[2]
AUDIT_SCRIPT = REPO_ROOT / "engine" / "audit.py"


def to_log(повод: str, *, метка: str = "engine", **пути: Path) -> None:
    """Напечатать пути в лог процесса — рядом с отказом, но не внутри него.

    Печатается в `stderr`: в отказ, уходящий наружу, путь с диска попадать не
    должен (T120), а чинящему он нужен. Метка называет зовущего, чтобы в общем
    журнале было видно, чей это запуск.
    """
    подробности = ", ".join(f"{имя}={путь}" for имя, путь in пути.items())
    print(f"[{метка}] {повод}: {подробности}", file=sys.stderr)


def clean(text: str, *paths: Path) -> str:
    """Убрать из текста движка пути с диска.

    Названные каталоги — временные копии: путей, которых у человека нет и не
    будет, в ответе быть не должно. Корень продукта вычищается отдельно и до
    конца: движок падает без общего перехвата, а трейсбек печатает путь к своим
    файлам — то есть каталог, куда развёрнут продукт, вместе с именем
    пользователя. Отрезается ровно корень, поэтому «engine/manage.py»
    остаётся: по нему чинить можно, а устройство машины по нему не читается
    (T120).
    """
    out = text
    for path in paths:
        out = out.replace(str(path), CANDIDATE_LABEL)
    out = out.replace(f"{REPO_ROOT}{os.sep}", "")
    return out.strip()


def check_version(version: str) -> str:
    """Имя версии как кусок пути внутри хранилища — или отказ.

    Правило одно на весь продукт (`domain.version.is_one_segment`) — то же,
    которым полка снимков домена решает, годится ли издание в имя каталога.
    Два правила на одно имя расходятся молча, поэтому оно здесь одно.

    Отказ называет НАСТОЯЩУЮ причину: испорченный идентификатор, а не
    «незнакомый алфавит», — иначе человека отправляют переименовывать законное
    издание его же управляющей компании.
    """
    value = (version or "").strip()
    if not is_one_segment(value):
        raise EngineCallError(
            f"«{version}» не может быть именем каталога издания: в идентификаторе версии не "
            f"бывает разделителей пути, и «.», «..» и пустая строка именем каталога тоже не "
            f"бывают (длина — до {SEGMENT_BYTES} байт). Идентификатор выглядит как "
            f"«imf-2026-09-03-3f5a91b2c7d0» — имя набора, дата издания и отпечаток данных; "
            f"имя набора задаёт управляющая компания, и латиницей оно быть не обязано. "
            f"Перечень версий отдаёт checklist_versions"
        )
    return value
