"""Скрипт установки, который сервер отдаёт по публичному GET (#244, D112).

Форма взята у соседнего продукта (`swarm-brain`, `functions/v1/swarm-setup`):
публичный GET отдаёт bash-скрипт, человек запускает его одной строкой из бота,
токен приезжает ОКРУЖЕНИЕМ. Своего здесь ровно одно отличие — скрипт
настраивает и Claude Code (прямой HTTP, без моста), потому что наш сервер это
умеет, а их — нет.

**Почему раздаёт сервер, а не бот текстом.** Сообщение телеграма копируется
целиком и обрывается на 4096 знаках: прежняя редакция слала сорок строк с
телом моста внутри, и человек копировал их с потерями. Скрипт, лежащий за
адресом, копированию не подлежит вовсе.

**Почему без токена.** В скрипте нет ни одного секрета: адрес и токен человек
подставляет сам, запуская его. Требовать токен на скачивание значило бы
требовать его до того, как человек узнал, куда его вписывать.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

#: Путь, по которому сервер отдаёт установщик. Выбран коротким: он попадает в
#: строку, которую человек вставляет в терминал с телефона в руке.
INSTALL_PATH = "/setup"

#: Самообновление моста (D626): мост при старте спрашивает здесь версию и отпечаток
#: (`BRIDGE_META_PATH`, JSON) и, если версия на сервере новее своей, скачивает файл
#: (`BRIDGE_SCRIPT_PATH`). В отличие от `/setup` обе двери требуют токен:
#: они отдают то, что человек потом запустит у себя, и анонимному клиенту
#: нет причины это видеть.
BRIDGE_META_PATH = "/bridge"
BRIDGE_SCRIPT_PATH = "/bridge/script"

#: Что отдаётся. `text/plain`, а не `application/x-sh`: файл не скачивается, а
#: уходит в `bash` по конвейеру, и браузер, открывший адрес руками, должен
#: показать текст, а не предложить сохранение.
INSTALL_CONTENT_TYPE = "text/plain; charset=utf-8"

_ROOT = Path(__file__).resolve().parents[2]
_INSTALLER = _ROOT / "tools" / "mcp_install.sh"
_BRIDGE = _ROOT / "tools" / "mcp_bridge.sh"

#: Место, куда подставляется тело моста. Оно не пишется в установщике строкой:
#: копия разъехалась бы с оригиналом на первой правке и разъехалась бы молча.
#:
#: Маркер ищется ОТДЕЛЬНОЙ СТРОКОЙ, а не подстрокой: то же слово стоит в шапке
#: установщика, где объясняется, что сюда подставляется, — и подстановка по
#: первому вхождению уехала бы в комментарий, оставив настоящее место пустым.
#: Поймано тестом раздачи, а не глазами.
_BRIDGE_MARK = "\n@BRIDGE@\n"


class InstallScriptError(RuntimeError):
    """Установщик собрать не из чего — отдавать нечего."""


def install_script() -> str:
    """Готовый текст установщика с подставленным телом моста.

    Отказ, а не пустая строка: скрипт без моста прошёл бы до конца и оставил
    человека с настройкой, которая не работает, — молчаливый промах ровно того
    сорта, из-за которого задача и заведена.
    """
    for файл in (_INSTALLER, _BRIDGE):
        if not файл.exists():
            raise InstallScriptError(f"нет файла {файл} — установщик собрать не из чего")
    шаблон = _INSTALLER.read_text(encoding="utf-8")
    if _BRIDGE_MARK not in шаблон:
        raise InstallScriptError(f"в {_INSTALLER} нет места для моста ({_BRIDGE_MARK!r})")
    мост = _BRIDGE.read_text(encoding="utf-8")
    собран = шаблон.replace(_BRIDGE_MARK, "\n" + мост.rstrip("\n") + "\n", 1)
    if _BRIDGE_MARK in собран:
        raise InstallScriptError("место для моста осталось незаполненным: маркеров больше одного")
    return собран


#: Строка версии в шапке моста: целое число, растёт на каждую правку, которую надо
#: донести до уже поставленных мостов. Сравнивает его сам мост (`tools/mcp_bridge.sh`).
_VERSION_LINE = re.compile(r"^BRIDGE_VERSION=(\d+)$", re.MULTILINE)


def bridge_script() -> str:
    """Мост ровно в том виде, в каком он ложится на диск человека.

    Тот же текст, что установщик подставляет вместо `@BRIDGE@`
    (`rstrip` + один перевод строки): отпечаток от него совпадает с отпечатком
    файла, который лежит после установки, и обновление не видит «разницы»,
    которой нет.
    """
    if not _BRIDGE.exists():
        raise InstallScriptError(f"нет файла {_BRIDGE} — отдавать нечего")
    return _BRIDGE.read_text(encoding="utf-8").rstrip("\n") + "\n"


def bridge_meta() -> dict[str, object]:
    """Версия и SHA-256 актуального моста. Отказ, если в мосте нет строки версии."""
    текст = bridge_script()
    найдено = _VERSION_LINE.search(текст)
    if найдено is None:
        raise InstallScriptError("в мосте нет строки BRIDGE_VERSION=<число>")
    return {
        "version": int(найдено.group(1)),
        "sha256": hashlib.sha256(текст.encode("utf-8")).hexdigest(),
    }
