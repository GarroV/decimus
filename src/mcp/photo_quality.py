"""Предупреждение о ужатом кадре, пришедшем в MCP base64-строкой (#1196).

Модель печатает base64 в аргумент инструмента знак за знаком, и снимок на несколько
мегабайт она сама ужимает до миниатюры в 20 КБ. Сервер такую миниатюру принимает —
запись без кадра допустима (D309), и запрещать маленький кадр значило бы терять и его.
Но в PDF партнёру на 560 пикселях не читаются этикетки, сроки и показания термометра,
на которых держатся записи. Поэтому ответ говорит об этом прямо и называет пути, по
которым идёт оригинал: мост с папки (`local_attach_photos`, D583) или песочница
(`import_upload_photos`).
"""

from __future__ import annotations

import io

from PIL import Image, UnidentifiedImageError

#: Длинная сторона кадра, ниже которой мелкий текст на снимке уже не читается.
#: Ужатые Claude кадры приходят по 560 px, снимок телефона — от 3000 px.
LOW_RES_LONG_SIDE = 1000


def is_low_resolution(width: int, height: int) -> bool:
    """Кадр мельче порога по длинной стороне (одно место для предупреждения и списка кадров)."""
    return max(width, height) < LOW_RES_LONG_SIDE


def low_resolution_warning(data: bytes) -> str | None:
    """Строка предупреждения, если кадр мельче `LOW_RES_LONG_SIDE`, иначе ничего.

    Картинку, которую библиотека не прочла, здесь не судим: формат проверяет
    приём кадра, а предупреждение о размере без размера было бы выдумкой.
    """
    try:
        with Image.open(io.BytesIO(data)) as картинка:
            ширина, высота = картинка.size
    except (UnidentifiedImageError, OSError):
        return None
    if not is_low_resolution(ширина, высота):
        return None
    return (
        f"low_resolution: кадр {ширина}×{высота} — мельче {LOW_RES_LONG_SIDE} px по длинной "
        f"стороне; этикетки, сроки и показания на нём в PDF могут не читаться. Приложен, но "
        f"оригинал лучше передать мимо base64: local_attach_photos (папка на компьютере) "
        f"или import_upload_photos (песочница)"
    )
