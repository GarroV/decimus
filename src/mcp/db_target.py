"""Непригодное окружение базы — «не задано» или «ведёт не туда» (#521).

Инструменты MCP ловят отказ окружения блока `db` (`ConfigError`) целиком и
отвечают своим «на этом стенде не подключено: не задана переменная …». После
#515 у этого отказа есть наследник — расхождение подключений
(`DatabaseTargetError`): переменная задана, только ведёт в другую базу. Под
текстом «не задано» он отправлял бы человека заводить переменную, которая уже
есть, пока настоящая причина — строка, указывающая не туда.

Поэтому расхождение отвечает своим кодом отказа (`db_target`) и общими
словами: ни базы, ни хоста, ни роли, ни имени переменной в ответе нет — ответ
инструмента уходит в модель, то есть за пределы машины (T120). Подробности без
пароля ложатся в журнал сервера на уровне ERROR тем же правилом, что у веба
(`src/db/target_refusal.py`).
"""

from __future__ import annotations

from ..db.target_refusal import note_target_mismatch
from .errors import ToolError

#: Ответ агенту на расхождение подключений.
DB_TARGET_MISMATCH = (
    "Подключения к базе на этом стенде ведут в разные базы, поэтому вызов остановлен — "
    "иначе данные читались бы или писались не там. Это отказ настройки стенда, а не "
    "незаданная переменная и не отсутствие данных: подробности остались в логе сервера, "
    "он не уезжает с машины. Обратитесь к администратору"
)


def config_refusal(exc: BaseException, not_connected: str) -> ToolError:
    """Отказ окружения базы → отказ инструмента: расхождение баз или «не подключено».

    Код отказа написан литералом намеренно: по литералу его находит сторож
    каталога (`tests/test_web_refusal_texts.py`) и требует текст `refusal.db_target`
    на каждом языке интерфейса — тот же, что показывает экран веба.
    """
    if note_target_mismatch(exc):
        return ToolError(DB_TARGET_MISMATCH, refusal="db_target")
    return ToolError(not_connected)
