"""Порядок обхода точки: правка `route.csv` через агента (T317, хвост T313).

`route.csv` — порядок, в котором аудитор физически идёт по пиццерии: зоны и,
если управляющая компания так решит, пункты внутри обхода (T061). До этой
задачи файл правился только текстовым редактором: у чек-листа и карты слов
инструменты были, у маршрута — ни одного.

Три вещи, из которых здесь всё следует.

**Проверить коды обязан этот блок, потому что больше некому.** Движок
`route.csv` не читает вовсе, и `manage.py validate` о нём не знает: правка
маршрута проходит проверку кандидата насквозь, что бы в ней ни было написано.
Между опечаткой в коде зоны и вставшим обходом на точке стоит ровно один
заслон — этот. Разбор продукта строгий (`src/domain/route.py`): код, которого
в методике нет, — отказ при чтении методики, то есть у аудитора в руках.

**Пометки человека переживают правку.** В боевом файле живут строки `#`,
объясняющие, почему порядок такой. Переписать файл целиком значило бы стереть
работу управляющей компании молча, поэтому строки данных заменяются ПО МЕСТАМ,
которые занимали, а всё остальное остаётся как лежало.

**Проверяет правку тот, кто маршрут читает.** После записи кандидат
разбирается `src.domain.route` — тем же кодом, который работает в продукте, — и
порядок сверяется с задуманным. Свой разборщик означал бы, что блок согласен
сам с собой, а аудитор на точке видит другое.

Хранилище и ход правки — общие с остальной методикой (`checklist.apply_edit`):
снимок версии → правка копии → проверка → новая версия рядом. Публикация
отдельным вызовом (D049), потому что маршрут — часть методики, а не настройка
рядом с ней: он входит в отпечаток версии (`DATA_FILES`).
"""

from __future__ import annotations

import csv
from collections.abc import Sequence
from pathlib import Path

from ..domain import route as продукт
from ..domain.errors import ConfigError
from ..domain.route import ITEM, ROUTE_FILE, ZONE
from .checklist import Outcome, Store, _clean, _ensure, _version_dir, apply_edit, check_code
from .errors import ChecklistError

#: Шаг позиций в файле. Десятка оставлена намеренно (T061): вставить зону между
#: двумя соседними человек должен уметь, не перенумеровывая весь файл.
STEP = 10

#: Шапка файла. Пишется только когда маршрута в версии ещё нет вовсе.
HEADER = "entity,code,order"

#: Откуда берутся годные коды: справочник той же версии методики и его колонка.
СПРАВОЧНИКИ = {ZONE: ("zones.csv", "code"), ITEM: ("checklist.csv", "id")}

ВИДЫ = {ZONE: "зоны", ITEM: "пункта"}


def _строки(path: Path, колонка: str) -> list[dict[str, str]]:
    """Строки справочника методики в порядке файла, пустые коды отброшены."""
    with path.open(encoding="utf-8-sig", newline="") as f:
        return [
            {k: (v or "") for k, v in row.items() if k is not None}
            for row in csv.DictReader(f)
            if (row.get(колонка) or "").strip()
        ]


def _известные(data_dir: Path, entity: str) -> dict[str, str]:
    """Коды справочника: свёрнутый регистр → написание методики.

    Написание методики важно: продукт сверяет маршрут со справочником кодом в
    код, и «FRIDGE» вместо «fridge» он не узнает — отказом на точке, а не здесь.
    Поэтому в файл уходит код справочника, а не то, как его набрали в вызове.
    """
    файл, колонка = СПРАВОЧНИКИ[entity]
    return {
        строка[колонка].strip().casefold(): строка[колонка].strip()
        for строка in _строки(data_dir / файл, колонка)
    }


def _названо(codes: Sequence[str] | None, *, entity: str) -> list[str] | None:
    """Проверить форму списка до всякой правки: не строка, коды кодами, без дублей."""
    if codes is None:
        return None
    if isinstance(codes, str):
        raise ChecklistError(
            f"Порядок обхода ({ВИДЫ[entity]}) ожидается списком кодов, а пришла одна строка "
            f"«{codes}». Список — это последовательность: «сначала эта, потом та»"
        )
    получилось: list[str] = []
    видели: set[str] = set()
    for код in codes:
        проверенный = check_code(str(код))
        if проверенный.casefold() in видели:
            raise ChecklistError(
                f"Код «{проверенный}» назван в порядке обхода дважды. Порядок — это "
                f"последовательность, и дубль означает, что одно из двух мест ошибочно; "
                f"такой маршрут продукт читать откажется"
            )
        видели.add(проверенный.casefold())
        получилось.append(проверенный)
    return получилось


def _сверить(codes: list[str], *, entity: str, data_dir: Path) -> list[str]:
    """Коды маршрута → коды методики. Незнакомый код — отказ здесь и сейчас.

    Тот самый заслон: движок этого файла не читает, значит принятая версия с
    опечаткой дошла бы до точки, где обход просто встанет отказом разбора.
    """
    известные = _известные(data_dir, entity)
    неизвестные = [код for код in codes if код.casefold() not in известные]
    if неизвестные:
        raise ChecklistError(
            f"В порядке обхода названы коды, которых в методике нет: "
            f"{', '.join(неизвестные)}. "
            + (
                f"Зоны этой версии: {', '.join(известные.values())}"
                if entity == ZONE
                else f"Пунктов в этой версии {len(известные)}, перечень отдаёт checklist_items"
            )
            + ". Маршрут связывается кодами, а не формулировками, и код, которого в методике "
            "нет, продукт читать откажется — увидит это уже аудитор на точке"
        )
    return [известные[код.casefold()] for код in codes]


def _места(строки: list[str]) -> dict[str, list[int]]:
    """Где в файле лежат строки данных каждого вида. Всё прочее — текст человека.

    Первая строка — шапка (`entity,code,order`): её разбор продукта тоже
    пропускает, поэтому и здесь она не данные.
    """
    места: dict[str, list[int]] = {ZONE: [], ITEM: []}
    for номер, строка in enumerate(строки):
        if номер == 0:
            continue
        вид = строка.split(",", 1)[0].strip()
        if вид in места:
            места[вид].append(номер)
    return места


def _переписать(текст: str, новые: dict[str, list[str] | None]) -> str:
    """Заменить строки данных ПО МЕСТАМ, оставив пометки человека там, где они были.

    Список длиннее прежнего — лишние строки встают сразу за последней своей;
    короче — освободившиеся места исчезают. Вида, которого в вызове не назвали,
    правка не касается вовсе: половины маршрута независимы.
    """
    строки = текст.splitlines() or [HEADER]
    места = _места(строки)
    подстановки: dict[int, str] = {}
    удалить: set[int] = set()
    хвосты: dict[int, list[str]] = {}
    for entity, коды in новые.items():
        if коды is None:
            continue
        свои = места[entity]
        готовые = [f"{entity},{код},{(номер + 1) * STEP}" for номер, код in enumerate(коды)]
        for номер, место in enumerate(свои):
            if номер < len(готовые):
                подстановки[место] = готовые[номер]
            else:
                удалить.add(место)
        хвост = готовые[len(свои) :]
        if хвост:
            хвосты.setdefault(свои[-1] if свои else len(строки) - 1, []).extend(хвост)
    получилось: list[str] = []
    for номер, строка in enumerate(строки):
        if номер not in удалить:
            получилось.append(подстановки.get(номер, строка))
        получилось.extend(хвосты.get(номер, ()))
    return "\n".join(получилось) + "\n"


def _разобрать(data_dir: Path) -> продукт.Route:
    """Маршнрут глазами продукта. Путей стенда в отказе не остаётся."""
    try:
        return продукт.load(data_dir)
    except ConfigError as беда:
        raise ChecklistError(
            f"Маршрут обхода ({ROUTE_FILE}) в этой версии методики не читается разбором "
            f"продукта: {_clean(str(беда), data_dir)}"
        ) from None


def _выстроить(
    значения: list[dict[str, str]], порядок: dict[str, int], *, колонка: str, что: str
) -> list[dict[str, str]]:
    """Порядок, в котором значения получит продукт. Неизвестный код — отказ разбора."""
    try:
        return продукт.arrange(значения, порядок, lambda строка: строка[колонка], what=что)
    except ConfigError as беда:
        raise ChecklistError(str(беда)) from None


def _проверено(кандидат: Path, новые: dict[str, list[str] | None]) -> None:
    """Сверить записанное разбором ПРОДУКТА, а не своим.

    Без этой сверки правка возвращала бы успех, не сделав работы: файл
    свободной формы, и строка, записанная чуть не так, тихо перестаёт быть
    строкой маршрута.
    """
    маршрут = _разобрать(кандидат)
    видно = {ZONE: маршрут.zones, ITEM: маршрут.items}
    for entity, коды in новые.items():
        if коды is None:
            continue
        ожидаемое = {код: (номер + 1) * STEP for номер, код in enumerate(коды)}
        if видно[entity] != ожидаемое:
            raise ChecklistError(
                f"После правки разбор продукта видит порядок {видно[entity]}, а не "
                f"{ожидаемое}. Правка записана не так, как задумана"
            )
        файл, колонка = СПРАВОЧНИКИ[entity]
        выстроено = _выстроить(
            _строки(кандидат / файл, колонка),
            видно[entity],
            колонка=колонка,
            что=ВИДЫ[entity],
        )
        получилось = [строка[колонка].strip() for строка in выстроено][: len(коды)]
        if получилось != коды:
            raise ChecklistError(
                f"После правки продукт пойдёт по порядку {', '.join(получилось)}, а не "
                f"{', '.join(коды)}. Правка записана не так, как задумана"
            )


