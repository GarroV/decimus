def read(store: Store, *, version: str | None = None) -> dict[str, object]:
    """Порядок ОБХОДА этой версии, а не содержимое файла.

    Зоны идут так, как их получит аудитор: названные маршрутом впереди в его
    порядке, неназванные следом, в порядке методики (`arrange`). Иначе агент
    пересказал бы человеку файл, а на точке порядок оказался бы другим.
    """
    каталог = _version_dir(store, _ensure(store) if version is None else version)
    маршрут = _разобрать(каталог)
    зоны = _выстроить(
        _строки(каталог / "zones.csv", "code"), маршрут.zones, колонка="code", что=ВИДЫ[ZONE]
    )
    пункты = _строки(каталог / "checklist.csv", "id")
    в_маршруте = [
        {"code": строка["id"].strip(), "order": маршрут.items[строка["id"].strip()]}
        for строка in _выстроить(пункты, маршрут.items, колонка="id", что=ВИДЫ[ITEM])
        if строка["id"].strip() in маршрут.items
    ]
    return {
        "version": каталог.name,
        "status": (
            f"the route names {len(маршрут.zones)} of {len(зоны)} zones and "
            f"{len(в_маршруте)} of {len(пункты)} checklist items; whatever it does not name "
            f"follows what it does, in checklist order"
        ),
        "zones": [
            {
                "code": строка["code"].strip(),
                "name_ru": строка.get("name_ru", ""),
                "name_en": строка.get("name_en", ""),
                "order": маршрут.zones.get(строка["code"].strip()),
            }
            for строка in зоны
        ],
        "items": в_маршруте,
        "items_total": len(пункты),
    }


# --- правка -------------------------------------------------------------------


def set_route(
    store: Store,
    *,
    tenant: str,
    zones: Sequence[str] | None = None,
    items: Sequence[str] | None = None,
    version_name: str | None = None,
    note: str | None = None,
) -> Outcome:
    """Задать порядок обхода: зоны, пункты или и то и другое.

    Названный вид переписывается целиком — порядок это последовательность, и
    одна зона в отрыве от остальных не говорит ничего. Неназванный вид не
    трогается вовсе. Пустой список снимает порядок для своего вида: маршрут,
    не называющий ничего, — законное состояние методики (порядок остаётся тем,
    в котором строки лежат в методике).
    """
    названо = {ZONE: _названо(zones, entity=ZONE), ITEM: _названо(items, entity=ITEM)}
    if all(коды is None for коды in названо.values()):
        raise ChecklistError(
            "Не названо ни одного порядка: ожидается zones — коды зон в том порядке, в "
            "котором аудитор идёт по пиццерии, и/или items — коды пунктов чек-листа. "
            "Вызов, который ничего не задаёт, агент перескажет человеку как сделанную работу"
        )

    def _mutate(кандидат: Path, _holder: Path) -> tuple[str | None, str]:
        # Разбор прежнего файла до правки: маршрут, который продукт уже не
        # читает, чинится рядом с человеком, а не переписывается вслепую.
        _разобрать(кандидат)
        новые = {
            entity: None if коды is None else _сверить(коды, entity=entity, data_dir=кандидат)
            for entity, коды in названо.items()
        }
        путь = кандидат / ROUTE_FILE
        текст = путь.read_text(encoding="utf-8-sig") if путь.is_file() else HEADER + "\n"
        путь.write_text(_переписать(текст, новые), encoding="utf-8")
        _проверено(кандидат, новые)
        сказано = ", ".join(
            f"{entity}s: {', '.join(коды) if коды else 'order dropped'}"
            for entity, коды in новые.items()
            if коды is not None
        )
        return None, f"walking route set — {сказано}"

    return apply_edit(
        store,
        tenant=tenant,
        tool="set_route",
        mutate=_mutate,
        version_name=version_name,
        note=note,
    )
