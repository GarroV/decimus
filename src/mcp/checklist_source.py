"""Исходник эталона для того, кого по нему проверяют (T315, D132).

Чек-лист — эталон управляющей компании: она его пишет, она им проверяет.
Партнёру эталон не принадлежит и им не правится, но **видеть** его он обязан:
владелец дословно — «базово он должен будет видеть исходник». До этой задачи
права было одно на всё: `MCP_CHECKLIST_TENANTS` подставлял хранилище версий, а
через одно и то же хранилище шли и правка, и чтение, — значит, партнёр не видел
эталона вовсе, а дать ему увидеть можно было только вместе с правкой.

Поэтому здесь отдельный модуль, а не флаг «только чтение» у соседа (D125).
Причина не в стиле: заслон в этом блоке стоит на ВИДЕ инструмента, а вид
решает, какое из двух хранилищ подставит транспорт. Обработчики, живущие своим
модулем, делают границу проверяемой снаружи — `tests/test_mcp_catalogue.py`
требует, чтобы у инструмента вида «исходник» обработчик лежал именно здесь, а
записи здесь нет вовсе: из хранилища берутся только читающие функции.

**Отдаются поля эталона, а не строка файла как она лежит.** Рядом с эталоном в
`checklist.csv` живут собственные колонки управляющей компании — их заводят
свободно, узнаются они по заголовку (T289), и содержимое их продукту
неизвестно. Инструмент методики отдаёт строку целиком намеренно (T109): её
читает та же УК, которая эти колонки и завела. Здесь читает другая сторона,
поэтому перечень полей назван — и новая колонка УК не уезжает партнёру просто
потому, что её завели.
"""

from __future__ import annotations

from typing import Any

from . import checklist as store_api
from .checklist import Store

#: Поля пункта, составляющие эталон: чем проверяют (вопрос), в каком процессе,
#: каких классов бывает нарушение и в какой срок его закрывают. Названо
#: списком, а не «всё, кроме известных служебных»: список исключений пропускает
#: новое, а список полей — нет.
ПОЛЯ_ПУНКТА: tuple[str, ...] = (
    "id",
    "kind",
    "process_code",
    "process_ru",
    "process_en",
    "question_ru",
    "question_en",
    "levels",
    "zones",
    "days",
)

#: Поля зоны: код, название и доля зоны в оценке. Доля — часть эталона, а не
#: внутренняя механика: по ней считается вычет, который партнёр видит в отчёте.
ПОЛЯ_ЗОНЫ: tuple[str, ...] = ("code", "name_ru", "name_en", "share_pct")


def _пункт(строка: dict[str, str]) -> dict[str, Any]:
    """Пункт эталона в том виде, в каком его читает сторона проверяемого.

    `id` переименован в `code`: снаружи пункты связываются кодами, и слово
    «код» стоит во всех отказах и во всех соседних инструментах.
    """
    отобранное = {поле: строка.get(поле, "") for поле in ПОЛЯ_ПУНКТА}
    код = отобранное.pop("id")
    return {"code": код, **отобранное}


def _зона(строка: dict[str, str]) -> dict[str, Any]:
    return {поле: строка.get(поле, "") for поле in ПОЛЯ_ЗОНЫ}


def checklist_source(
    *, tenant: str, store: Store, version: str | None = None, process: str | None = None
) -> dict[str, Any]:
    """Эталон, по которому идут проверки: пункты, зоны, классы и сроки.

    Без критериев — они бывают на страницу и отдаются по одному пункту
    (`checklist_source_item`), ровно как у инструментов управляющей компании.

    Версия по умолчанию — ДЕЙСТВУЮЩАЯ, а не последняя записанная: правка живёт
    в новой версии до публикации (D050), и показать партнёру непубликованный
    черновик значило бы сказать «вас проверяют по этому», когда движок считает
    по другому. Назвать старую версию можно: отчёт годичной давности посчитан
    по ней, и он обязан оставаться объяснимым.
    """
    выбранная = version or store_api.current_version(store)
    строки = store_api.read_items(store, version=выбранная)
    отбор = (process or "").strip().lower()
    if отбор:
        строки = [
            r
            for r in строки
            if отбор in (r.get("process_ru", "") + r.get("process_en", "")).lower()
        ]
    зоны = store_api.read_items(store, version=выбранная, what="zones")
    return {
        "tenant": tenant,
        "version": выбранная,
        "filters": {"process": process},
        "count": len(строки),
        "status": (
            f"{len(строки)} checklist items in version {выбранная}"
            if строки
            else f"no checklist items match in version {выбранная}"
        ),
        "items": [_пункт(строка) for строка in строки],
        "zones": [_зона(строка) for строка in зоны],
    }


def checklist_source_item(
    *, tenant: str, store: Store, code: str, version: str | None = None
) -> dict[str, Any]:
    """Один пункт эталона вместе с критериями D1/D2/D3.

    Критерии — единственный источник того, при каких условиях пункт D1, а при
    каких D2 или D3 (`docs/02-domain.md`). Без них проверяемый видит вычет, но
    не видит, из чего он вышел, и спорить ему нечем.
    """
    выбранная = version or store_api.current_version(store)
    пункт = store_api.read_item(store, code=code, version=выбранная)
    return {
        "tenant": tenant,
        "version": выбранная,
        "status": f"checklist item {пункт['id']} found in version {выбранная}",
        "item": {**_пункт(пункт), "criteria": пункт.get("criteria", "")},
    }
