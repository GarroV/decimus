"""Отказы блока `recognize`.

Тип отказа решает, что делает бот: переспросить аудитора, показать кнопки
ручного выбора или не подниматься вовсе. Поэтому классы разные, а не один
общий: по тексту сообщения такое решение принимать нельзя.
"""

from __future__ import annotations


class RecognizeError(Exception):
    """Базовый отказ разбора."""


class RecognizeConfigError(RecognizeError):
    """Разбирать нечем: нет карты кадров, ключа модели или ffmpeg.

    Отдельный класс нужен, чтобы бот не молчал: без карты кадров сужение
    перечня превращается в догадку, а тихо взятый неполный перечень —
    ровно та ошибка, которую разведка признала самой опасной.
    """


class ModelUnavailable(RecognizeError):
    """Модель не ответила: сеть, ключ, лимит, таймаут, испорченный ответ.

    Проверку это не роняет — бот переходит на ручной выбор пункта кнопками
    (`manual_candidates`).
    """


class ModelKeyRejected(RecognizeError):
    """Провайдер не принял ключ модели (проверка на экране «Подключения», D491)."""


class TranscriptionFailed(RecognizeError):
    """Голосовое не разобрано: не перекодировалось, не распозналось, пустое.

    Аудитора просят написать текстом; проверка продолжается.
    """


#: Что видит человек, когда месячный потолок расхода пространства исчерпан (D759). Текст
#: двуязычный: на веб и в бот он попадает ключом из `texts`, а здесь — для журналов,
#: MCP и мест, где показывают текст исключения как есть.
MODEL_LIMIT_MESSAGE = (
    "Месячный лимит расхода пространства исчерпан. Обратитесь в управляющую компанию. / "
    "The space's monthly spending limit has been reached. Please contact the management company."
)


class ModelLimitReached(ModelUnavailable, TranscriptionFailed):
    """Месячный потолок расхода модели пространства исчерпан (D759): вызов не делается.

    Наследует и `ModelUnavailable`, и `TranscriptionFailed`: так каждая дверь, что уже
    переживает недоступную модель или неразобранный голос, переживёт и этот отказ —
    проверка идёт вручную, ручной ввод без модели работает. Отличить его от сбоя нужно
    лишь затем, чтобы сказать человеку причину (`except ModelLimitReached` раньше
    остальных). Повтор не поможет: потолок поднимает управляющая компания или он
    сбрасывается с новым месяцем (UTC).
    """

    def __init__(self) -> None:
        super().__init__(MODEL_LIMIT_MESSAGE)
