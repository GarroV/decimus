"""Границы на свободный текст ответа модели (F-131).

Структурные поля ответа (пункт, зона, уверенность, показание) проверяет схема
и разбор. Свободные строки — формулировка, основание, вопрос — уходят
аудитору и в отчёт партнёра как есть, и держать их было нечем.

Это защита от мусора, а не цензура смысла: из текста убираются управляющие
символы и невидимки, слишком длинный хвост усекается с пометкой. Находка не
отбрасывается и не переписывается; нормальный вывод проходит без изменений.
"""

from __future__ import annotations

import unicodedata

#: Пределы щедрые: формулировка — одно-два предложения (десятки-сотни знаков).
#: Всё, что длиннее, — не находка, а сбой модели; но находку это не отменяет.
MAX_WORDING_CHARS = 1500
MAX_REASON_CHARS = 1500
MAX_QUESTION_CHARS = 1000

#: Пометка усечения: человек видит, что текст обрезан, а не дописан моделью.
TRUNCATED_MARK = " […усечено]"

#: Нужные в тексте управляющие: перенос строки и табуляция. ZWJ склеивает
#: составные эмодзи, поэтому из невидимок остаётся.
_KEEP = frozenset({"\n", "\t", "‍"})
_STRIPPED_CATEGORIES = frozenset({"Cc", "Cf", "Cs"})


def clean_text(value: str, max_chars: int) -> str:
    """Свободное поле ответа: без управляющих символов и невидимок, не длиннее предела."""
    kept = "".join(
        ch for ch in value if ch in _KEEP or unicodedata.category(ch) not in _STRIPPED_CATEGORIES
    ).strip()
    if len(kept) <= max_chars:
        return kept
    return kept[:max_chars].rstrip() + TRUNCATED_MARK
