"""T034: модель недоступна — перечень пунктов для ручного выбора кнопками.

`ModelUnavailable` не роняет проверку (см. `errors.py`): бот ловит отказ и
показывает те же пункты, что пошли бы в запрос к модели, но без обращения к
сети и без ранжирования по словам комментария — порядок тот же, что в самом
чек-листе. Функция здесь не решает, сколько кнопок показать за раз: контракт
блока «не больше пяти» — это про кандидатов модели, ранжированных по
уверенности (аудитор на телефоне не разберёт больше на экране предложений).
Ручной перечень — не предложение, а полный список для осознанного выбора;
показывать ли его страницами — решение бота (T034 со стороны `bot`), не этого
блока.

Пункты ручного решения аудитора (`MGM22`, `MGM23`) здесь есть — это ровно тот
случай, где ответ выставляет только человек.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from src.domain import allowed_levels, get_item

from .config import DEFAULT_LANG
from .cues import load_cues, match_cues
from .shortlist import shortlist


@dataclass(frozen=True)
class ManualCandidate:
    """Один пункт для кнопки ручного выбора: код, допустимые классы, текст."""

    code: str
    levels: tuple[str, ...]
    title: str


def manual_candidates(
    zone_hint: str | None, *, note: str = "", lang: str = DEFAULT_LANG, chat_id: int | None
) -> tuple[ManualCandidate, ...]:
    """Пункты для ручного выбора — без сети и без модели.

    `note` — слова аудитора, если они были (#226). Карта слов работает здесь
    поиском: «печь» поднимает единицы пунктов, и перечень становится ими, а не
    всем чек-листом (замер 07.09.2026: 123 пункта по 8 на страницу — 16 страниц
    листания в цехе). Карта промолчала или слов нет вовсе — перечень остаётся
    полным перечнем — всем чек-листом, а не перечнем одной зоны.

    **Зона здесь не режет ничего** (T265, #218) — ни найденное словами, ни базу
    перечня. Пункт про печь живёт только в горячем цехе, и при подсказке
    «холодный цех» он исчезал из кнопок вовсе: аудитор не мог выбрать верный
    пункт даже вручную, то есть последний рубеж выбора отказывал ровно в том
    случае, ради которого он и существует. Печь обязана быть достижима из
    холодного цеха.

    `zone_hint` задаёт ПОРЯДОК перечня: пункты названной зоны идут первыми,
    остальные остаются за ними. `None` — зона неизвестна, и порядок остаётся
    порядком чек-листа. `with_manual=True` — отличие от запроса к модели: тут
    решает человек, и `MGM22`/`MGM23` ему доступны.

    `chat_id` обязателен и умолчания не имеет (T226): кнопка обязана предлагать
    ровно то, что примет движок этой проверки, — пункт и класс её издания
    (T169). Ошибка здесь заметнее всего: аудитор жмёт кнопку, а запись не
    проходит, и на точке это выглядит поломкой на ровном месте.
    """
    picked = shortlist(note, zone_hint, with_manual=True, chat_id=chat_id)
    codes = picked.codes
    # Карта промолчала — перечень остаётся полным. Пустые кнопки на последнем
    # рубеже выбора были бы худшим исходом: два предыдущих пути уже промолчали,
    # и тупик здесь означает потерянную находку (#219).
    найденные = _found_by_words(note, codes, chat_id=chat_id)
    return _candidates(найденные or codes, lang=lang, chat_id=chat_id)


def _found_by_words(note: str, codes: Sequence[str], *, chat_id: int | None) -> tuple[str, ...]:
    """Коды перечня, поднятые словами аудитора, в порядке перечня.

    Зоной эта выборка не режется намеренно (T265, #218) — пункт про печь живёт
    в горячем цехе, и из холодного он исчезал из кнопок вовсе, то есть аудитор
    не мог исправить промах даже вручную.
    """
    слова = note.strip()
    if not слова:
        return ()
    подсказанные = set(match_cues(слова, load_cues(chat_id=chat_id)))
    return tuple(code for code in codes if code in подсказанные)


def _candidates(
    codes: Sequence[str], *, lang: str, chat_id: int | None
) -> tuple[ManualCandidate, ...]:
    return tuple(
        ManualCandidate(
            code=code,
            levels=tuple(allowed_levels(code, chat_id=chat_id)),
            title=get_item(code, chat_id=chat_id).question(lang),
        )
        for code in codes
    )


def search_items(
    word: str, *, lang: str = DEFAULT_LANG, chat_id: int | None
) -> tuple[ManualCandidate, ...]:
    """Пункты, которые карта слов поднимает по этому слову (T267, #226).

    Основной вход в ручной выбор. Без модели и без сети: совпадение идёт по
    основам слов карты кадров, то есть по тому же механизму, каким работает
    быстрый путь. «Печь» поднимает 4 пункта, «стеллаж» — 3, и аудитор видит
    ровно их.

    Замер 07.09.2026 объясняет, зачем это вообще: ручной перечень — 123 пункта
    по 8 на страницу, то есть **16 страниц листания** в цехе с занятыми руками.
    Листание остаётся, но запасным входом: сперва слово, и только если слово
    ничего не подняло — перечень зоны страницами.

    **Зоны у поиска нет намеренно.** Слово называет объект, а не место; резать
    найденное зоной значило бы вернуть ровно тот дефект, из-за которого пункт
    про печь был недостижим из холодного цеха (#218). Зона спрашивается ПОСЛЕ
    выбора пункта, и спрашивается тем, что методика этому пункту даёт (T266).

    Пусто — законный ответ «карта такого слова не знает», а не отказ: дальше
    формулировка уходит в накопитель (T268), а аудитору предлагается зона и
    пункты этой зоны. Тупика нет ни в одной ветке.
    """
    if not word.strip():
        return ()
    offered = shortlist(word, None, with_manual=True, chat_id=chat_id)
    return _candidates(
        _found_by_words(word, offered.codes, chat_id=chat_id), lang=lang, chat_id=chat_id
    )
