"""Что блок отдаёт наружу: предложения, а не решения.

Контракт из `docs/furca/plan.md`: не более пяти кандидатов, `needs_human`
поднимается при низкой уверенности или пустом списке. Пустой список — валидный
ответ: бот переспрашивает человека, а не выдумывает запись.
"""

from __future__ import annotations

from dataclasses import dataclass, field

#: Код, которым модель говорит «ничего из перечня не подходит». Он обязан быть в
#: перечислении: без варианта отказа модель выбирает ближайший пункт — это
#: показала разведка на боевом кадре.
NONE_CODE = "NONE"

#: Зона, которой модель говорит «из слов аудитора места не видно». Выводить зону
#: из вида кадра запрещено (правило 6): стена за кассовой стойкой — это зал,
#: даже если рядом стоит ведро.
UNKNOWN_ZONE = "UNKNOWN"


@dataclass(frozen=True)
class Candidate:
    """Один вариант записи, который аудитор подтверждает или отвергает."""

    code: str
    level: str
    zone: str
    wording: str
    confidence: float
    reason: str = ""
    #: Претензии к формулировке от проверки правил фиксации: масштаб за кадром,
    #: додуманный характер повреждения, похвала без основания. Не пустой список
    #: означает, что запись показывается человеку с пометкой, а не молча.
    flags: tuple[str, ...] = ()
    #: Показание термометра или щупа на кадре, °C (#836). Пусто — кадр не про
    #: замер температуры либо цифры не видно. Читает его модель, а значит может
    #: ошибиться (6 прочитано как 26): поэтому число показывается аудитору
    #: отдельной строкой, и он его исправляет.
    reading_c: float | None = None


#: Классы, которые различает уточняющий вопрос: у нарушений, не у замера и рекомендации.
ANSWER_LEVELS = ("D1", "D2", "D3")


@dataclass(frozen=True)
class Answer:
    """Вариант ответа на уточняющий вопрос и класс, который он даёт (#1107)."""

    text: str
    level: str


@dataclass(frozen=True)
class Suggestion:
    """Ответ разбора на один комментарий аудитора."""

    candidates: tuple[Candidate, ...] = ()
    needs_human: bool = True
    #: Что спросить у аудитора, когда по кадру и комментарию непонятно (правило 7).
    question: str = ""
    #: Варианты ответа на вопрос о пороге класса — кнопками (#1107). Пусто —
    #: вопрос не о классе или варианты негодны, тогда он показывается текстом.
    answers: tuple[Answer, ...] = ()
    #: Смотрели ли на кадр. Кадр разбирается только когда комментарий неоднозначен.
    used_photo: bool = False
    #: Ответ собран без модели — из справочника. Бот показывает кнопки выбора.
    degraded: bool = False
    #: Расход на запрос, для замера стоимости. Пусто, когда модель не звали.
    usage: dict[str, int] = field(default_factory=dict)
    #: Коды, которые ушли модели перечнем кандидатов, в порядке показа (#367).
    #: Нужны разбору промаха: не было нужного кода в перечне — модель тут ни при чём.
    shortlist: tuple[str, ...] = ()
    #: Увиденное на кадрах пачки СВЕРХ сказанного аудитором (D208). Только
    #: предложения: бот показывает их отдельным сообщением и ничего по ним не
    #: пишет сам. Пусто — пачки не было или на кадрах ничего сверх слов нет.
    also_seen: tuple[Candidate, ...] = ()
    #: Пункты словаря подсказок, которых модель не назвала, хотя задала вопрос
    #: (D597): «может быть и это», без формулировки и уверенности. Показывает
    #: их мини-апп нижними карточками; бот пока нет (#1112).
    cue_extras: tuple[Candidate, ...] = ()

    def top(self) -> Candidate | None:
        return self.candidates[0] if self.candidates else None
