"""Зона из слов аудитора: обиходные названия мест и разбор текста (T124, D047, D048).

Вынесено из `bot/zones.py` (#1015), чтобы MCP подбирал зону теми же словами, что
бот: `src.mcp` не вправе импортировать `src.bot`, а `recognize` ниже обоих.
Поведение разбора не менялось; `bot.zones` реэкспортирует эти имена.

Зону определяет человек (правило 6 `docs/03-recording-rules.md`), отдельного
шага «выберите зону» нет (D047). **Названия зон берутся из методики, а не из
списка в коде**: управляющая компания правит `data/zones.csv`, и переименованная
зона обязана начать узнаваться сама. В коде живёт только то, чего в методике нет,
— как зону называют вслух. Список короткий и растёт по факту: каждая строка
взята из слов владельца или из боевых проверок в `examples/`.

**Совпадение — по строке целиком, длинная сильнее короткой.** Названы две зоны
разом — разбор не выбирает за человека и молчит.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence

from src import domain
from src.domain.models import TEXT_LANGS, Zone

from . import language
from .cues import stems, words_and_gaps

#: Языки названий зон. Совпадает с языками интерфейса бота (`bot.texts.UI_LANGS`);
#: расхождение ловит `tests/test_bot_zone_from_words.py`.
NAME_LANGS = TEXT_LANGS

#: Как зоны называют вслух — то, чего в `data/zones.csv` нет.
#:
#: Источники каждой строки, и других нет:
#: * `dining` — «в зале», «Полы в зале», «за кассовой стойкой» из боевых
#:   проверок `examples/`; «кассовая зона» — слова владельца при решении D064.
#: * `dough` — «Тестомес не накрыт» из боевой проверки Белград-2; «мучной цех» —
#:   слова владельца из ответа 03.09.2026 («мучной цех, на дрожжах нет
#:   маркировки»), пойманные приёмкой: методика называет зону тестомесильным
#:   цехом, а вслух её называют мучным.
#: * `freezer` — «морозилка», обиходная форма названия из методики.
#: * `hot_kitchen` — «температура продуктов на линии» с выезда 14.10.2026 (#838):
#:   «это же будет всегда горячая зона». Хватает «на линии»: целая фраза его
#:   содержит, а склонять длинное имя замер падежей не умеет. «Линия раздачи» —
#:   как это место называют на точке. «Линия», «лайн/лайне», «саладетта» — слова
#:   владельца (D207, #1015): это одно место, и оно в горячем цехе.
#:
#: Чего здесь намеренно НЕТ: названий холодильного оборудования. Это
#: оборудование, и в боевых проверках оно стоит в горячем цехе, а не в
#: одноимённой камере — короткое слово утащило бы запись в чужую зону.
#: Сами названия здесь не выписаны: это строки методики управляющей компании, а
#: репозиторий публичный (`tests/test_methodology_leak.py`).
SPOKEN: dict[str, tuple[str, ...]] = {
    "dining": ("зал", "касса", "кассовая"),
    "dough": ("тестомес", "мучной цех"),
    "freezer": ("морозилка",),
    "hot_kitchen": (
        "на линии",
        "линия раздачи",
        "линия",
        "лайн",
        "саладетта",
    ),
}

#: Сокращения цехов, как их произносят и пишут аудиторы (D244, #444): «ГЦ» —
#: горячий цех, «ХЦ» — холодный. Основа короче `MIN_STEM`, поэтому через `stems`
#: они не проходят и ищутся отдельно — только целым словом, а не внутри чужого
#: («гц» в середине слова не срабатывает). Регистр не важен. Код зоны, которого
#: нет в издании проверки, сокращение молча пропускает.
ABBREVIATIONS: dict[str, str] = {
    "гц": "hot_kitchen",
    "хц": "cold_kitchen",
}

#: Вес сокращения при споре имён: как у названия из двух слов («горячий цех»),
#: потому что оно и есть такое название целиком. Оборудование, названное в той
#: же фразе («холодильник ГЦ»), зону не перебивает.
_ABBREVIATION_WEIGHT = 2

#: Чем разрезается название зоны на самостоятельные имена: составное имя зоны —
#: это два имени одного места, и произносят их по отдельности.
_SPLIT = re.compile(r"[/,]|\sи\s|\sand\s")

#: Предлоги места — данные языка, а не константа кода (T192): по ним форма без
#: существительного («в холодном») отличается от признака предмета («холодная
#: вода»). Третий язык добавляется словарём, а не правкой этого файла.
_PLACE_PREPOSITIONS = language.place_prepositions()


def _names(code: str, title: str) -> list[str]:
    return [part.strip() for part in _SPLIT.split(title) if part.strip()]


def phrases(
    *, chat_id: int | None, zones: Sequence[Zone] | None = None
) -> dict[str, tuple[frozenset[str], ...]]:
    """Основы слов каждого имени зоны: код зоны → набор произносимых строк.

    `chat_id` называется всегда и умолчания не имеет (T225): имена берутся из
    издания ТОЙ проверки (T169), иначе зона, переименованная переизданием,
    переставала бы узнаваться в словах аудитора посреди его же выезда.

    Пустой чат — не умолчание, а отдельный законный ответ «проверки нет»: так
    зовёт замер по боевым выгрузкам (`tools/fastpath_measure.py`), которому
    читать нечего, кроме действующей методики. Разница между «нет проверки» и
    «забыли передать» и есть причина, по которой умолчания здесь нет.

    Методика читается на каждом обращении, а не кешируется: её подкладывают
    томом снаружи, и кеш означал бы работу по старым названиям до перезапуска
    (тем же живёт `recognize.cues.load_cues`).
    """
    out: dict[str, tuple[frozenset[str], ...]] = {}
    # `zones` — справочник, уже прочитанный вызывающим из издания (MCP читает версию
    # хранилища методики, а не действующую по `AUDIT_DATA_DIR`).
    for zone in domain.list_zones(chat_id=chat_id) if zones is None else zones:
        names = [name for lang in NAME_LANGS for name in _names(zone.code, zone.title(lang))]
        names.extend(SPOKEN.get(zone.code, ()))
        found = {frozenset(s) for name in names if (s := stems(name))}
        out[zone.code] = tuple(found)
    return out


def qualifiers(named: Mapping[str, tuple[frozenset[str], ...]]) -> dict[str, str]:
    """Основа-определение → код зоны: «холодн» → холодный цех (T263).

    Так место называют без существительного — «полы в холодном», «в горячем».
    Имя зоны при этом произнесено НЕ целиком, и брать за него любое слово имени
    нельзя: «Стеллаж хранения» — имя из двух слов, но «стеллаж» зоной не
    является, стеллажи стоят в разных цехах (слова владельца).

    Поэтому определением считается основа, у которой есть **семья**: имя, в
    которое она входит, содержит ещё и головное слово, общее с именем ДРУГОЙ
    зоны («цех» у горячего и холодного, «камера» у холодильной и морозильной).
    Внутри такой семьи определение и есть всё различие, поэтому названное одно
    оно называет зону однозначно. У имени-одиночки, ни с кем головного слова не
    делящего, определения нет вовсе — и это не упущение, а отказ гадать.

    Примеры имён здесь намеренно неполны: это строки методики управляющей
    компании, а репозиторий публичный (`tests/test_methodology_leak.py`).

    Сама основа обязана вести ровно к одной зоне: ведущая к двум ничего не
    различает и в словарь не попадает.
    """
    где: dict[str, set[str]] = {}
    for code, names in named.items():
        for name in names:
            for stem in name:
                где.setdefault(stem, set()).add(code)
    головные = {stem for stem, codes in где.items() if len(codes) > 1}
    out: dict[str, str] = {}
    for code, names in named.items():
        for name in names:
            if len(name) < 2 or not (name & головные):
                continue
            for stem in name - головные:
                if len(где[stem]) == 1:
                    out[stem] = code
    return out


def named_places(note: str) -> set[str]:
    """Основы слов, стоящих сразу за предлогом места (T263).

    Предлог здесь — то, чем форма без существительного отличается от признака
    предмета: «полы **в** холодном» называет место, а «холодная вода» — воду.
    Без этого различия определение зоны начало бы срабатывать на любом
    прилагательном («горячая вода течёт» → горячий цех), то есть ровно тем
    гаданием, которое задача убирает.

    Разделитель между предлогом и словом обязан быть пустым или пробельным: за
    знаком препинания стоит уже другая часть фразы — тем же правилом живёт
    отрицание в `recognize.fastpath`.
    """
    words, gaps = words_and_gaps(note)
    места: set[str] = set()
    for index, word in enumerate(words[:-1]):
        if word in _PLACE_PREPOSITIONS and not gaps[index].strip():
            места |= stems(words[index + 1])
    return места


def zone_from_words(
    note: str, *, chat_id: int | None, zones: Sequence[Zone] | None = None
) -> str | None:
    """Код зоны, названной в этих словах. Не названа или названы две — `None`.

    `None` — обычный ответ, а не отказ, и означает он «зону здесь не назвали»:
    дальше её ищет словарь объектов, а не нашёл и он — спрашивает сам аудитор
    (`resolve_zone`). Памятью о прошлой записи `None` больше не заполняется ни в
    одной ветке (T264, #218).

    Имя, названное целиком, сильнее формы без существительного всегда: длина
    совпавшего имени — мера того, насколько его произнесли, а определение
    («в холодном») весит одно слово по устройству.
    """
    words = stems(note)
    spoken_words, _ = words_and_gaps(note)
    abbreviated = {ABBREVIATIONS[w] for w in spoken_words if w in ABBREVIATIONS}
    if not words and not abbreviated:
        return None
    named = phrases(chat_id=chat_id, zones=zones)
    # Длина совпавшего имени — мера того, насколько это имя произнесли, а не
    # задели одним словом: имя из двух основ весомее имени из одной.
    best: dict[str, int] = {}
    for code, names in named.items():
        for name in names:
            if name <= words:
                best[code] = max(best.get(code, 0), len(name))
    for code in abbreviated & named.keys():
        best[code] = max(best.get(code, 0), _ABBREVIATION_WEIGHT)
    if not best:
        # Имя целиком не названо — место могли назвать определением («в
        # холодном»). Ветка стоит ПОСЛЕ полного имени, а не соревнуется с ним:
        # определение весит одно слово, и спор с названным именем оно всегда
        # проигрывало бы, а лишний способ проиграть — лишний способ разойтись.
        словарь = qualifiers(named)
        найдено = {словарь[stem] for stem in named_places(note) if stem in словарь}
        return найдено.pop() if len(найдено) == 1 else None
    top = max(best.values())
    winners = [code for code, size in best.items() if size == top]
    return winners[0] if len(winners) == 1 else None
