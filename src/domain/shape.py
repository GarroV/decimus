"""Оценочная форма издания: чем считали, а не что написано (T349, #337).

Ряд оценок по сети молча смешивает проверки, посчитанные по разным ценам.
Правка ставки вычета или порога буквы делает проверки до и после неё
несравнимыми, и средняя по такому ряду выглядит совершенно правдоподобно — это
худший вид ошибки: не падение, а цифра, которой верят.

Отличать издания по их ИДЕНТИФИКАТОРУ для этого не годится. Он меняется от
любой правки методики (D050), в том числе от опечатки в формулировке и от
перевода названия зоны, — признак срабатывал бы на каждом издании, и его
перестали бы читать. Нужен ответ на более узкий вопрос: **считали ли эти два
издания одинаково.**

Поэтому здесь собирается отпечаток ровно того, что участвует в цене:

* ставки, пороги и правила букв из `scoring.json` — без ярлыков и сроков;
* состав пунктов, которые вообще могут обернуться вычетом, с их классами,
  зонами и видом строки;
* доли зон — вес, с которым находка входит в оценку.

И не участвует ничего больше: формулировки, критерии, карта кадров, порядок
строк, сроки устранения, названия зон и переводы. Их правка ряд не рвёт.

**Оценка здесь не считается и считаться не может.** Проценты, буква и разбивка
приходят только из `engine/audit.py score` (жёсткое требование проекта); этот
модуль читает те же файлы, чтобы ответить, одинаковы ли ПРАВИЛА, по которым
считал движок.
"""

from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path
from typing import Any

#: Длина отпечатка — та же, что у идентификатора издания (`version`). Совпадение
#: не случайно: оба отвечают на вопрос «то же самое?» и оба показываются
#: человеку рядом, и разная длина читалась бы как разная природа.
SHAPE_LEN = 12

#: Файлы, из которых собирается форма. Остальные файлы методики на цену не
#: влияют вовсе: `criteria.md` и `photo-cues.md` помогают аудитору, `route.csv`
#: задаёт порядок обхода, `checklist_version.txt` — имя издания.
SHAPE_FILES = ("checklist.csv", "zones.csv", "scoring.json")

#: Ключи `scoring.json`, которые в цену не входят. `deadlines` и `plan_due_days`
#: — сроки: они уезжают в предписание партнёру, но ни процента, ни буквы не
#: двигают. Остальное — подписи и комментарии.
NOT_PRICE = frozenset({"deadlines", "plan_due_days", "label_ru", "label_en", "_logic"})


def _без_подписей(значение: Any) -> Any:
    """То же дерево настроек, но без текста и сроков.

    Служебные ключи (`_comment`, `_logic`) срезаются по подчёркиванию: их в
    методике заводит управляющая компания по мере надобности, и перечислять их
    поимённо значило бы ловить каждый новый после того, как он уже разорвал
    ряд.
    """
    if isinstance(значение, dict):
        return {
            ключ: _без_подписей(вложенное)
            for ключ, вложенное in sorted(значение.items())
            if not ключ.startswith("_") and ключ not in NOT_PRICE
        }
    if isinstance(значение, list):
        return [_без_подписей(элемент) for элемент in значение]
    return значение


def _строки(путь: Path) -> list[dict[str, str | None]]:
    with путь.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def _поле(строка: dict[str, str | None], ключ: str) -> str:
    return (строка.get(ключ) or "").strip()


def _пункты(каталог: Path) -> list[list[Any]]:
    """Пункты, которые могут обернуться вычетом, — и только то, чем они его меряют.

    Влияющим считается пункт, у которого есть КЛАССЫ: без класса находку по
    нему не записать, а значит и в вычет он не превращается. Это точнее
    перечня видов строк — вид заводит управляющая компания, и новый вид без
    классов молча попал бы в цену.

    Классы и зоны сортируются: `D1;D2` и `D2;D1` — одно и то же правило,
    записанное двумя способами, и рвать ряд перестановкой внутри клетки
    нельзя.
    """
    собранные: list[list[Any]] = []
    for строка in _строки(каталог / "checklist.csv"):
        код = _поле(строка, "id")
        if not код or код.startswith("#"):
            continue
        классы = sorted(
            {
                x.strip().upper()
                for x in _поле(строка, "levels").replace(",", ";").split(";")
                if x.strip()
            }
        )
        if not классы:
            continue
        зоны = sorted({z.strip() for z in _поле(строка, "zones").split(",") if z.strip()})
        собранные.append([код, _поле(строка, "kind") or "violation", классы, зоны])
    return sorted(собранные, key=lambda пункт: str(пункт[0]))


def _зоны(каталог: Path) -> list[list[Any]]:
    """Код зоны и её доля. Название и перевод — подпись в отчёте, а не вес."""
    собранные = [
        [_поле(строка, "code"), float(_поле(строка, "share_pct") or 0)]
        for строка in _строки(каталог / "zones.csv")
        if _поле(строка, "code")
    ]
    return sorted(собранные, key=lambda зона: str(зона[0]))


def scoring_shape(data_dir: Path) -> str | None:
    """Отпечаток цены этого каталога методики или `None`, если его не собрать.

    `None` — не отказ и не «сравнимо». Каталога может не быть на машине вовсе
    (издание старой проверки, снимок которой не сохранился), файлы могут не
    читаться. Каждый такой случай означает ровно «ответа нет», и выдать его за
    сравнимость значило бы соврать в ту самую сторону, ради которой задача
    заведена. Что делать с незнанием, решает спрашивающий.
    """
    try:
        ставки = json.loads((data_dir / "scoring.json").read_text(encoding="utf-8"))
        форма = {
            "scoring": _без_подписей(ставки),
            "items": _пункты(data_dir),
            "zones": _зоны(data_dir),
        }
    except (OSError, ValueError, KeyError):
        return None
    слепок = json.dumps(форма, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(слепок.encode("utf-8")).hexdigest()[:SHAPE_LEN]
