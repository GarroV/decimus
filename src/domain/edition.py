"""Издание методики, на котором идёт проверка, и его снимок рядом с состоянием.

Задача T169. До неё проверка была привязана к методике только отметкой: имя
издания записывалось на старте, а работала она всё равно по тому каталогу,
который лежит в `AUDIT_DATA_DIR` СЕЙЧАС. Публикация (D049) переставляет этот
каталог под живой проверкой, и дальше проверка набирает записи по новому
изданию, оставаясь помеченной прежним. Сверка T148 стоит на подсчёте и такую
проверку ловит только в конце — когда аудитор уже уехал с точки.

**Снимок берётся на старте, и дальше проверка идёт по нему.** Издание, при
котором проверку начали, копируется в `STATE_DIR/methodology/<издание>/`, и
каждый вызов движка по этой проверке — запись, правка, подсчёт, отчёт — идёт по
этому каталогу, а не по действующему. Переиздание методики посреди выезда
перестаёт быть событием для идущей проверки: смешаться нечему, отказывать не в
чем, аудитор ничего не замечает.

Почему снимок лежит рядом с СОСТОЯНИЕМ, а не в хранилище версий MCP, хотя
хранилище (D049) для того и построено:

* **Каталог методики продукту доступен только на чтение.** В `docker-compose.yml`
  он смонтирован `:ro` — писать снимок туда бот не может физически.
* **Хранилища версий в контейнере бота нет вовсе.** Смонтированы ровно два
  каталога: методика (`:ro`) и том состояния. `MCP_CHECKLIST_STORE` бот не
  видит, и настроен он по умолчанию пустым — то есть решение, опирающееся
  только на хранилище, не закрывало бы дефект в той настройке, в которой
  продукт работает.
* **Том состояния переживает пересоздание контейнера** (решение D004) — ровно
  как и сами проверки, снимок которых здесь и хранится.

Снимок **адресуется содержимым**: имя каталога — тот же составной идентификатор
издания (D050), которым помечается проверка. Отсюда три свойства даром: два чата,
начатые на одном издании, делят один снимок; повторный снимок того же издания —
не работа, а проверка что он на месте; подложенный снимок опознаётся отпечатком
и в дело не идёт.

Модуль не импортирует ни `state`, ни `checklist` намеренно: оба зовут его сами
(`state` — чтобы снять снимок на старте, `checklist` — чтобы прочитать пункты
того издания, по которому идёт проверка), и обратный импорт замкнул бы их.
"""

from __future__ import annotations

import json
import logging
import os
import shutil
import tempfile
from dataclasses import replace
from pathlib import Path
from typing import Any

from .config import DATA_FILES, Settings
from .engine import DOMAIN_KEY, state_file
from .version import VERSION_FILE, compose, edition_of, is_one_segment

logger = logging.getLogger(__name__)

#: Полка снимков внутри каталога состояния: `STATE_DIR/methodology/<код>/<издание>/`.
#: Уровень кода появился с множественностью чек-листов (T346, D177): имя
#: издания выводится из содержимого методики, поэтому два разных чек-листа
#: однажды дадут одинаковое имя. В плоской полке второй не упал бы — он
#: опознал бы чужой снимок как свой по отпечатку, и проверка посчиталась бы
#: по чужой методике.
#: Не `checklist_data`: так называется форк методики, который движок подхватывает
#: сам, и папка с таким именем в каталоге состояния — отказ на старте (T024).
SHELF_DIR = "methodology"

#: Код чек-листа, которым является существующая методика (D181). Он уезжает в
#: базу к каждой проведённой проверке и не меняется никогда, поэтому служит
#: умолчанием везде, где кода ещё не передают.
#:
#: Живёт здесь, а не в `checklist.py`: тот импортирует эту сторону сам
#: (`pin`), и объявление там замкнуло бы импорт в кольцо. То же значение
#: объявлено в `src/mcp/checklist_layout.py` — два дома у одного кода это
#: дрейф, и он заведён отдельной задачей.
DEFAULT_CODE = "bizdev"

#: Что входит в снимок. `DATA_FILES` — сама методика (то же, из чего считается
#: отпечаток), плюс файл издания: без него снимок опознавался бы как `local-…`
#: и не сошёлся бы с отметкой проверки, в которой стоят имя и дата от УК.
SNAPSHOT_FILES = (*DATA_FILES, VERSION_FILE)


def shelf(settings: Settings, code: str = DEFAULT_CODE) -> Path:
    """Каталог, в котором лежат снимки изданий этого чек-листа."""
    return settings.state_dir / SHELF_DIR / code


def _flat_shelf(settings: Settings) -> Path:
    """Полка до уровня кода: `STATE_DIR/methodology/<издание>/`.

    Читается, но не пишется. Снимки, снятые до T346, лежат здесь, и ими
    помечены уже записанные проверки: перестать их находить значит собрать
    письмо партнёру не по той методике — или не собрать вовсе. Новые снимки
    туда не кладутся, поэтому старая полка вымывается сама.
    """
    return settings.state_dir / SHELF_DIR


def shelf_dirs(shelf_root: Path, version: str) -> list[Path]:
    """Где на полке может лежать это издание — все места сразу.

    Полка стала двухуровневой (T346), а снимки, снятые до неё, лежат прямо в
    корне; и то и другое читается. Перебор нужен потребителю, который знает
    издание, но не знает код чек-листа: письмо собирается по отметке проверки,
    а отметка — это издание, кода в ней нет.

    Годность решает не очередь, а отпечаток у вызывающего: годится тот
    каталог, чьё СОДЕРЖИМОЕ и есть это издание, кто бы его ни положил. Тот же
    порядок и по той же причине держит хранилище версий MCP
    (`report.engine_call.edition_dirs`).

    Имя издания вызывающий проверяет до вызова: свои куски пути берутся с
    диска, подставить `..` сюда нечем.
    """
    места = [shelf_root / version]
    if shelf_root.is_dir():
        места += [
            код / version
            for код in sorted(k for k in shelf_root.iterdir() if k.is_dir())
            if not код.name.startswith(".")
        ]
    return места


def _identifies(path: Path, version: str) -> bool:
    """Тот ли это снимок: сходится ли его отпечаток с отметкой проверки.

    Сходится — значит содержимое ровно то, которым помечена проверка: имя,
    дата и отпечаток считаются той же формулой, что штампует отметку (D050).
    Не сходится — снимок в дело не идёт: считать по каталогу, который выдаёт
    себя за издание проверки, ровно тот дефект, ради которого всё это.

    Сам ответ считает `version.edition_of` — тот же код, которым тот же вопрос
    задаёт хранилище версий MCP (`mcp.letters.pinned`). Свести пришлось на
    дефекте T236: там сверки не было вовсе, и два ответа на один вопрос
    расходились молча. Здесь остаётся только предупреждение в лог — оно про
    ЭТУ полку и в общем ответе ему не место.

    Отказывать при испорченном снимке нельзя: снимок — не окружение продукта,
    и его беда обязана стоить ровно того, что снимка нет, а не остановки
    работы аудитора.
    """
    прочитано = edition_of(path, DATA_FILES)
    if прочитано is None and path.is_dir():
        logger.warning("снимок издания %s не читается как издание: %s", version, path)
    return прочитано == version


def snapshot(settings: Settings, version: str, code: str = DEFAULT_CODE) -> Path | None:
    """Годный снимок этого издания или `None`, если его нет.

    Ищется сперва на полке своего чек-листа, затем — только для кода по
    умолчанию — на старой плоской полке: до T346 чек-лист был один, и снимки
    прошлых изданий лежат там. Чужому коду плоская полка не предлагается: её
    содержимое принадлежит методике бизнес-девелопера, а не всякому, кто
    спросил.
    """
    if not is_one_segment(version):
        return None
    path = shelf(settings, code) / version
    if _identifies(path, version):
        return path
    if code != DEFAULT_CODE:
        return None
    прежний = _flat_shelf(settings) / version
    return прежний if _identifies(прежний, version) else None


def _copy(source: Path, target: Path) -> None:
    """Положить снимок на полку целиком или не положить вовсе.

    Каталог собирается во временном месте на той же полке и въезжает на место
    переименованием: увиденный вполглаза наполовину скопированный снимок — это
    подсчёт по половине методики, а движок недостающий файл добирает молча.
    """
    target.parent.mkdir(parents=True, exist_ok=True)
    holder = Path(tempfile.mkdtemp(dir=str(target.parent), prefix=".snapshot-"))
    try:
        made = holder / "data"
        made.mkdir()
        for name in SNAPSHOT_FILES:
            origin = source / name
            if origin.is_file():
                shutil.copy2(origin, made / name)
        os.replace(made, target)
    except OSError:
        # Занято — значит тот же снимок положил кто-то другой: имя выведено из
        # содержимого, и двух разных изданий под одним именем не бывает.
        if not target.is_dir():
            raise
    finally:
        shutil.rmtree(holder, ignore_errors=True)


def keep(settings: Settings, code: str = DEFAULT_CODE) -> str:
    """Снять снимок действующей методики и вернуть издание, которым он опознан.

    Возвращаемое издание — то, которым помечается проверка. Считается оно по
    КАТАЛОГУ, с которого снимали, а не по `AUDIT_DATA_DIR` вообще: публикация
    переставляет указатель, и путь, разрешённый один раз, дальше не уедет
    из-под копирования на середине.

    Снимок не сняли — не отказ: проверка останется без него и вернётся к
    поведению T148 (сверка на подсчёте и отказ). Отказать на старте значило бы
    не пустить аудитора на точку из-за неполадки с диском, а это дороже.
    """
    source = Path(os.path.realpath(settings.data_dir))
    version = compose(source, DATA_FILES)
    if snapshot(settings, version, code) is not None:
        return version
    if not is_one_segment(version):
        logger.warning("издание %s не годится в имя каталога — снимок не снят", version)
        return version
    target = shelf(settings, code) / version
    if target.exists():
        # Каталог под этим именем есть, но снимком не опознан: испорчен, снят
        # порванным копированием или подложен. Держать его незачем — имя
        # выведено из содержимого, а правильное содержимое у нас на руках.
        # Убираем здесь, а не в `_copy`: иначе первая же проверка после порчи
        # осталась бы без снимка и вернулась к отказу на подсчёте.
        shutil.rmtree(target, ignore_errors=True)
        logger.warning("испорченный снимок издания %s снят с полки заново: %s", version, target)
    try:
        _copy(source, target)
    except OSError as exc:
        logger.warning("снимок издания %s не снят (%s): %s", version, exc, target)
        return version
    if not _identifies(target, version):
        # Методику правили прямо во время копирования: снятое не сходится с
        # тем, чем помечена проверка. Такой снимок хуже отсутствующего.
        shutil.rmtree(target, ignore_errors=True)
        logger.warning("снимок издания %s не сошёлся с ним самим и убран", version)
    return version


def recorded(chat_id: int, settings: Settings) -> str:
    """Издание, которым помечена проверка этого чата. Нет проверки — пусто.

    Файл читается напрямую, а не через `state.read_state`: тот зовёт разбор
    всей проверки, а разбор зовёт методику — то есть этот же модуль. Пустая
    строка здесь означает одно: пометки нет, и работать надо по действующей
    методике, как работали до версионирования.

    Испорченный файл состояния здесь не отказ: об этом внятно отказывает
    `state.read_state`, и вторая формулировка того же отказа, прилетевшая
    раньше, увела бы человека не туда.
    """
    path = state_file(chat_id, settings)
    if not path.is_file():
        return ""
    try:
        raw: Any = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return ""
    if not isinstance(raw, dict):
        return ""
    block = raw.get(DOMAIN_KEY)
    if not isinstance(block, dict):
        return ""
    return str(block.get("checklist_version") or "")


def data_dir(chat_id: int, settings: Settings) -> Path:
    """Каталог методики, по которому идёт ЭТА проверка.

    Порядок ровно такой:

    1. Проверка не помечена изданием — действующая методика. Так помечены
       проверки, заведённые до версионирования, и ломать их задним числом
       нельзя (D033).
    2. Действующая методика и есть то издание — она же. Обычный случай: пока
       методику не переиздавали, ничего не меняется вовсе.
    3. Есть снимок того издания — он. Это и есть закрытие T169: проверка,
       начатая до переиздания, продолжается по своему изданию.
    4. Снимка нет — действующая методика, а расхождение поймает сверка на
       подсчёте (T148) и отдаст решение человеку.
    """
    version = recorded(chat_id, settings)
    if not version:
        return settings.data_dir
    if version == compose(settings.data_dir, DATA_FILES):
        return settings.data_dir
    kept = snapshot(settings, version)
    return kept if kept is not None else settings.data_dir


def pin(chat_id: int, settings: Settings) -> Settings:
    """То же окружение, но с методикой ТОЙ проверки, а не действующей."""
    return replace(settings, data_dir=data_dir(chat_id, settings))
