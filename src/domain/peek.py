"""Переключатель пространств главного админа: куда можно заглянуть и кому (D726).

Главный админ УК одним нажатием смотрит на сервис глазами партнёра — проверить, что
там творится. Правила здесь, а не в маршруте: «кому», «куда» и «кем он тогда работает»
решает одно место, маршрут и заслон только спрашивают.

* **Кому** — только настоящей учётке с ролью главного админа в УК, чья сессия прошла
  вторую ступень (или у кого второго способа нет вовсе: тогда проходить нечему).
* **Куда** — только в пространства из `PEEK_SPACES`. Код из запроса сверяется с этим
  перечнем, а не принимается на слово; наличие пространства в `tenants` проверяет база.
* **Кем** — партнёрским админом (`PEEK_ROLE`): экраны и меню те же, что у него.
* **Только просмотр** — любая запись при включённом переключателе отказывается
  (`src/web/peek.py`); исключение — само переключение и выход.
"""

from __future__ import annotations

from .tenants import HQ_TENANT, SUPERADMIN_ROLE, canonical_tenant

#: Пространства, куда можно заглянуть. Расширяется правкой кода, а не настройкой:
#: каждое — осознанное решение владельца (первым заведено тестовое `TEST`).
PEEK_SPACES: tuple[str, ...] = ("TEST",)

#: Роль, которой главный админ работает в чужом пространстве: админ партнёра.
PEEK_ROLE = "admin"

#: Значение поля формы «вернуться в своё пространство».
HOME = HQ_TENANT


def may_peek(*, role: str, tenant: str, second_step_ok: bool) -> bool:
    """Может ли эта учётка пользоваться переключателем — по НАСТОЯЩИМ роли и пространству."""
    return role == SUPERADMIN_ROLE and canonical_tenant(tenant) == HQ_TENANT and second_step_ok


def is_peek_space(code: str | None) -> bool:
    """Код есть в перечне допустимых пространств (точное совпадение, без поправок)."""
    return code is not None and code in PEEK_SPACES


def target_of(raw: str | None) -> str | None:
    """Поле формы → пространство для записи в сессию.

    `HOME` → `None` (вернуться), код из перечня → он сам, всё прочее → `ValueError`:
    произвольный код из запроса не принимается.
    """
    value = (raw or "").strip()
    if value == HOME:
        return None
    if is_peek_space(value):
        return value
    raise ValueError(f"в это пространство переключаться нельзя: {value!r}")
