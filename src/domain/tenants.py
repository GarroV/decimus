"""Код тенанта управляющей компании и перевод старого кода (D234, #439).

Тенант УК называется `HQ`. До 29.09.2026 он назывался `default`, и этот код
остался там, куда миграция базы не дотягивается: в файлах состояния идущих
проверок бота и в переменных окружения стендов (`WEB_TENANT`,
`BOT_MCP_TENANT`, `MCP_CHECKLIST_TENANTS`). Поэтому старый код переводится на
входе, одним правилом для всех поверхностей, а не правкой каждого файла.
"""

from __future__ import annotations

#: Тенант управляющей компании: только он заводит новые пиццерии (D233).
HQ_TENANT = "HQ"

#: Прежние коды тенантов → нынешние.
LEGACY_TENANTS: dict[str, str] = {"default": HQ_TENANT}


def canonical_tenant(code: str) -> str:
    """Нынешний код тенанта: старый переводится, остальные — как есть."""
    cleaned = code.strip()
    return LEGACY_TENANTS.get(cleaned, cleaned)


def may_add_units(tenant: str) -> bool:
    """Заводить новые пиццерии может только управляющая компания (D233, D234).

    Партнёры выбирают из справочника своих стран, но не пополняют его: справочник
    один и принадлежит УК (D284). Одно правило на бота и на веб-админку (#437).
    Граница — `unit.create` «только УК» в матрице; роль спрашивает маршрут.
    """
    from .permissions import open_to_space

    return bool(canonical_tenant(tenant)) and open_to_space("unit.create", tenant)


#: Контролинг: видит и ведёт только раздел «Рейтинги» (D319, D358).
CONTROL_ROLE = "control"

#: Главный админ (D362, D364): всё по проекту, включая назначение других
#: главных админов. Только в УК (`0041`); последнего действующего снять нельзя —
#: держит база, а не экран.
SUPERADMIN_ROLE = "superadmin"


#: Бизнес-девелопер (D440): пользуется сервисом полностью (проверки, приёмка,
#: письма, предписания, экшн-планы, рейтинги на чтение), но людей, страны и
#: ключи не трогает. Только УК (`0060`); заменил аудитора УК.
DEVELOPER_ROLE = "developer"

#: Гость (D440): вся сеть только на чтение; ничего не меняет и не отправляет.
#: Только УК (`0060`).
GUEST_ROLE = "guest"

#: ОСБ — отдел сопровождения бизнеса (D599): права гостя на чтение, ведёт
#: предписания на странице «ОСБ». К странам не привязана (D606). Только УК.
OSB_ROLE = "osb"


def _may(role: str | None, tenant: str | None, action: str) -> bool:
    # Матрица живёт в `permissions`, а она сама опирается на этот модуль: импорт
    # внутри функции, чтобы не замкнуть круг на загрузке.
    from .permissions import role_may

    return role_may(role, tenant, action)


def may_manage_ratings(role: str | None, tenant: str) -> bool:
    """Загружать рейтинги и править их справочники — `ratings.manage` (D319, D420).

    Видеть рейтинги могут все (D327, «рейтинги видят все») — это решает не
    эта функция, а отсутствие заслона на чтении.
    """
    return _may(role, tenant, "ratings.manage")
