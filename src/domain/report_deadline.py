"""Срок отправки отчёта партнёру и название события в календаре проверяющего (D740).

Правило владельца: отсчёт идёт со следующего дня после дня проверки; суббота и воскресенье
не считаются; срок — ТРЕТИЙ рабочий день, а не «через три дня» (проверка в пятницу → среда).
Праздники не учитываются: календаря праздников по странам у продукта нет.

Ядро по правилу «ошибка молчалива»: сбитый срок — это правдоподобная дата в календаре
человека, а не ошибка. Поэтому тесты (`tests/test_report_deadline.py`) держат примеры
владельца, а день проверки здесь — местная дата страны: её записывает проверяющий в самой
проверке (`inspections.inspection_date`), а не момент сервера.
"""

from __future__ import annotations

from datetime import date, timedelta

#: Сколько рабочих дней даётся на отчёт, считая со следующего дня после проверки.
REPORT_WORKING_DAYS = 3

#: Понедельник—пятница по `date.weekday()`: суббота (5) и воскресенье (6) не считаются.
_FIRST_WEEKEND_DAY = 5

#: Название события по языку интерфейса человека; третий язык — строкой сюда.
_TITLES = {
    "ru": "Отправить отчёт по проверке — {unit} ({day})",
    "en": "Send the inspection report — {unit} ({day})",
}


def report_due_date(inspection_day: date) -> date:
    """Крайний день отправки отчёта партнёру: третий рабочий день после дня проверки."""
    день = inspection_day
    осталось = REPORT_WORKING_DAYS
    while осталось:
        день += timedelta(days=1)
        if день.weekday() < _FIRST_WEEKEND_DAY:
            осталось -= 1
    return день


def event_title(unit: str, inspection_day: date, lang: str) -> str:
    """«Отправить отчёт по проверке — <пиццерия> (<дд.мм>)»; язык не из списка — английский.

    В скобках — день ПРОВЕРКИ, не срок: по названию видно, о какой проверке напоминание,
    а срок — это сам день события.
    """
    шаблон = _TITLES.get(lang, _TITLES["en"])
    return шаблон.format(unit=unit.strip(), day=inspection_day.strftime("%d.%m"))
