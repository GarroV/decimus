"""Отказы блока `web`.

Один базовый класс по образцу соседних блоков: вызывающий (точка входа,
`src/web/__main__.py`) ловит любой отказ блока одним `except WebError` и
печатает внятную причину вместо трассировки.
"""

from __future__ import annotations


class WebError(Exception):
    """Базовый отказ блока `web`."""


class WebConfigError(WebError):
    """Окружение веб-админки непригодно: адрес, порт, тенант или язык."""


class WebTextError(WebError):
    """Текста нет в каталоге, язык не заведён или тексту не передан параметр."""


class MethodologyRefused(WebError):
    """Дверь методики не приняла правку: отказал движок или само хранилище.

    Отдельный тип, потому что это НЕ поломка админки: отклонённая правка —
    обычный и частый исход (движок не принял методику, правка ничего не
    изменила, такой версии в хранилище нет). Показывается она словами двери на
    той же странице, а не пятисоткой.
    """


class SectionRegistryError(WebError):
    """Реестр разделов разошёлся с экранами, которые на самом деле построены.

    Отдельный тип, потому что это единственный отказ блока, который обязан
    случиться на СБОРКЕ приложения, а не в запросе: признак «построен /
    не построен» (D138) живёт данными, и расхождение данных с фактом — та
    самая тихая ложь, ради которой признак и заведён данными.
    """
