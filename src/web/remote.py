"""Чей это адрес: кто пришёл на страницу, когда между нами стоит туннель.

Нужно ровно одному — счётчику неудачных входов (T325). Считать попытки «по
адресу» можно только зная адрес; за туннелем сервер видит адрес туннеля, и
без этого модуля счётчик по адресу стал бы одним общим на всех, кто приходит
снаружи.

**ЗАГОЛОВКУ ВЕРИМ РОВНО НАСТОЛЬКО, НАСКОЛЬКО СКАЗАНО В НАСТРОЙКЕ.**
`X-Forwarded-For` ставит кто угодно: доверять ему по умолчанию — значит
раздать каждому перебирающему бесконечный запас «адресов» одной строкой в
запросе. Поэтому умолчание — не верить вовсе, а сколько звеньев впереди нас
стоит своих, говорит `WEB_TRUSTED_PROXIES`.

**СЧЁТ ИДЁТ С КОНЦА ЦЕПОЧКИ, А НЕ С НАЧАЛА.** Левый край `X-Forwarded-For`
пишет клиент, правый дописывает ближайший к нам посредник. Взять левый — это и
есть «верить постороннему»: там лежит ровно то, что он захотел там увидеть.
При одном своём звене нужен последний элемент, при двух — предпоследний.
"""

from __future__ import annotations

from flask import request

FORWARDED_FOR = "X-Forwarded-For"

#: Что уходит в счётчик, когда адреса нет вовсе (такое бывает у тестового
#: клиента и у сокета без адреса). Строка, а не `None`: у счётчика ключ
#: обязателен, и «неизвестно» — это один общий ключ, а не отсутствие учёта.
UNKNOWN = "unknown"


def client_address(*, trusted_proxies: int) -> str:
    """Адрес, по которому считаются неудачные попытки входа.

    Цепочка короче обещанной — берётся адрес соединения. Это осторожный конец
    развилки: общий ключ на всех запирает вход строже, чем нужно, а доверие к
    недостающему звену не запирает никого.
    """
    прямой = request.remote_addr or UNKNOWN
    if trusted_proxies <= 0:
        return прямой
    цепочка = [звено.strip() for звено in request.headers.get(FORWARDED_FOR, "").split(",")]
    цепочка = [звено for звено in цепочка if звено]
    if len(цепочка) < trusted_proxies:
        return прямой
    return цепочка[-trusted_proxies]
