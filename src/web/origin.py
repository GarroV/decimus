"""Заслон происхождения: пропустить отправку формы только со своей же страницы.

Отдельным модулем, потому что заслон нужен трём местам сразу — снятию
проверки, входу и выходу, — а три копии одной проверки разошлись бы при первой
же правке. Это и есть «переиспользовать, а не дублировать»: правило живёт в
одном месте, а места применения только называют его.
"""

from __future__ import annotations

from urllib.parse import urlsplit

from flask import abort, request


def over_https() -> bool:
    """Идёт ли этот запрос по HTTPS — включая случай «TLS снял туннель».

    Живёт здесь, а не рядом с кукой, потому что ответ нужен двум местам сразу:
    флагу `Secure` у сессионной куки и заслону происхождения ниже. Две копии
    этого рассуждения — ровно тот случай, ради которого модуль и заведён.

    `X-Forwarded-Proto` учитывается потому, что наружу админка выходит
    туннелем (D100): TLS заканчивается на туннеле, а до сервера на петле
    доезжает обычный HTTP. Подставить заголовок может только тот, кто уже
    дотянулся до петли, — то есть сам туннель.
    """
    return request.is_secure or request.headers.get("X-Forwarded-Proto", "").lower() == "https"


def refuse_foreign_origin() -> None:
    """Пропустить POST только со своей же страницы. Во всех прочих случаях — отказ.

    Зачем он нужен помимо входа: у админки есть необратимые действия (снятие
    проверки убирает кадры из хранилища), и чужая страница, открытая в том же
    браузере вошедшего человека, могла бы запустить их одним скрытым запросом.
    Сессионная кука при этом уехала бы сама — браузер прикладывает её к запросу
    независимо от того, кто этот запрос затеял.

    **Правило: разрешает совпадение, а не отсутствие данных.** Происхождение
    берётся из `Origin`, а если его нет — из `Referer`; нет ни одного — отказ.
    Прежняя редакция пропускала запрос без `Origin`, рассуждая так: заголовок
    ставит браузер, значит его отсутствие безопасно. Рассуждение неверное
    дважды. Во-первых, заголовок ставит не всякий браузер и не во всяком случае
    (политика источника ссылки, старые версии, встроенные просмотрщики).
    Во-вторых, проверка, которая на пустом входе разрешает, — это не проверка,
    а пропуск: обойти её достаточно тем, чтобы заголовок не пришёл, и
    злоупотребить этим легче, чем подделать значение.

    **Сверяется схема вместе с хостом, а не один `netloc`.** Иначе
    `http://хост` и `https://хост` считались бы одним происхождением, и заслон
    снимался бы понижением схемы.

    **Своя схема берётся так же, как у куки** (`over_https`), а не из
    `request.host_url`. За туннелем сервер видит обычный HTTP, а браузер
    присылает `Origin` со схемой `https` — сравнение «как видит сервер» не
    совпало бы никогда, и заслон отвечал бы 403 на КАЖДЫЙ POST: вход, выход,
    снятие проверки. То есть публикация наружу (D100, D154) ломала бы админку
    целиком, а чинил бы это тот, кому «продакшен не работает», — самый
    вероятный способ снять заслон неправильно. Понижение схемы при этом
    по-прежнему отвергается: `https` наружу и `http` в `Origin` — разные
    происхождения.
    """
    свой = urlsplit(request.host_url)
    своя_схема = "https" if over_https() else свой.scheme
    источник = request.headers.get("Origin") or request.headers.get("Referer")
    if not источник:
        abort(403)
    пришёл = urlsplit(источник)
    if (пришёл.scheme, пришёл.netloc) != (своя_схема, свой.netloc):
        abort(403)
