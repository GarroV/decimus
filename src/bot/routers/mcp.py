"""Настройка подключения к MCP: личный токен человеку на его учётку (T209, T253, T261).

Решения D087 (пункт меню и готовая строка), D098 (личный токен), D448 (выпуск
себе сам, без круга).

**Что человек получает.** Готовую строку настройки своего Claude со своим
личным токеном внутри — вставил в терминал, и подключение есть. Токен здесь
деталь строки, а не отдельный предмет разговора: человек не «получает токен», а
получает работающую настройку.

**Клиент один — Claude Desktop (#222, решение D103).** До T261 пункт слал
команду для Claude Code всем подряд: она работала, но настраивала не тот
клиент, и владелец не нашёл наш сервер в настройках приложения. T261 добавил
вопрос «какой Claude», а #222 его снял — владелец назвал развилку ненужной, и
поддерживаемая настройка осталась одна. Кнопка при этом сохранилась как
согласие: по нажатию выпускается токен, а выпуск гасит прежний, то есть ломает
уже работающую настройку. Токен стоит ровно в одном сообщении переписки
(`tests/test_bot_mcp_setup.py`).

**Команда не рассказывается словами, а выполняется** — она правит файл
настроек, где у человека уже стоят свои серверы. Собирается в
`src/bot/mcp_setup.py`: кладёт мост `tools/mcp_bridge.sh` в `~/.decimus/bin`
и дописывает одну запись штатным `plutil`. Ни Node, ни Python на машине
человека не нужны.

**Чего не было до T253.** Токен заводился руками в `.env` записью
«арендатор=токен» (`src/mcp/config.py`), принадлежал СТОРОНЕ и открывал всю её
историю проверок; связи «этот человек — этот токен» у бота не было никакой,
поэтому печатать он не мог ничей — напечатанный был бы выдан наугад. Отзыв же
был правкой файла с перезапуском сервера, то есть отъёмом доступа сразу у всех.

**Что появилось.** Токен выпускается на учётку человека, хранится
отпечатком (`src/db/mcp_access.py`), показывается один раз и при повторном
вызове заменяет прежний — о чём человеку говорится прямо, потому что снаружи
внезапно переставшая работать настройка выглядит поломкой Claude, а не
следствием собственного действия.

**Круга больше нет** (D448, аудит 12.10). Доступ к Claude никто никому не
выдаёт: любой, кого бот пускает (действующая учётка с полевой ролью), выпускает
токен себе сам — на свою учётку, по живой привязке бота
(`mcp_access.issue_token`). Что можно в Claude, решает роль учётки
(`src/mcp/policy.py`), срок токена — `MCP_TOKEN_TTL_DAYS`; доступ кончается
отключением учётки или сменой роли. Та же функция выпуска стоит за мини-аппом и
за настройками веба.
"""

from __future__ import annotations

import asyncio
import logging
import os

from aiogram import F, Router
from aiogram.filters import Command
from aiogram.types import CallbackQuery, Message

from src.db.errors import DbError, UnboundError
from src.domain.log_ids import log_id

from ..keyboards import MCP_SETUP_SEND, mcp_setup_keyboard
from ..lang import chat_ui_lang
from ..mcp_setup import setup_command
from ..texts import t

logger = logging.getLogger(__name__)

#: Имя команды настройки. Она же объявляется в общем меню телеграма (D448).
MCP_COMMAND = "mcp"

#: Адрес MCP-сервера, который бот ПЕЧАТАЕТ в команде установки. Не адрес, куда
#: бот ходит: он туда не ходит вовсе.
#:
#: Своя переменная, а не `MCP_HOST`/`MCP_PORT` соседнего блока, и причин две.
#: Первая — блоки пиры и друг друга не импортируют, а вторая важнее: сервер
#: слушает петлю (`127.0.0.1`), и человеку с другой машины эта строка не
#: подходит — он идёт туннелем, и в команде у него стоит свой адрес. Это разные
#: факты, и копией одного другой не является.
#: Живёт в `mcp_setup` (D373): её читает и мини-апп, а роутеры aiogram ему не нужны.
from ..mcp_setup import MCP_URL_VAR as MCP_URL_VAR  # noqa: E402


def setup_url(lang: str) -> str:
    """Адрес для команды установки — из окружения стенда или заглушка.

    Пусто — не отказ: пункт меню обязан работать и на стенде, где адрес никто
    не задавал, а заглушка ЗАГЛАВНЫМИ стоит в строке ровно там же, где стоял бы
    адрес, и видна человеку. Подставить сюда петлю по умолчанию значило бы
    выдать догадку за настройку — и человек искал бы, почему «готовая» команда
    не соединяется.
    """
    return (os.environ.get(MCP_URL_VAR) or "").strip() or t("mcp.url_unknown", lang)


def build_mcp_router() -> Router:
    """Роутер настройки MCP: пункт и выпуск по кнопке."""
    router = Router(name="mcp")

    @router.message(Command(MCP_COMMAND))
    async def on_mcp(message: Message) -> None:
        """Что произойдёт по кнопке — и ничего кроме этого (T261, #222).

        Токен здесь НЕ выпускается намеренно. Выпуск гасит прежний, то есть
        ломает уже сделанную настройку, а открыть пункт и посмотреть — не
        повод её ломать. До T261 так и было: вызов пункта наказывал за
        любопытство, и узнавал об этом человек из третьего сообщения.
        """
        lang = chat_ui_lang(message.chat.id)
        await message.answer(t("mcp.offer", lang), reply_markup=mcp_setup_keyboard(lang))

    @router.callback_query(F.data == MCP_SETUP_SEND)
    async def on_send(callback: CallbackQuery) -> None:
        """Готовая команда настройки Claude Desktop — с личным токеном внутри.

        Разными сообщениями не для красоты: в телеграме копируется сообщение
        ЦЕЛИКОМ одним движением, и команда, склеенная с объяснением, приезжала
        бы в терминал вместе с ним. Здесь это важнее прежнего — в команде стоит
        настоящий токен.

        Порядок: объяснение, чем эта команда особенная (что она для macOS и что
        чужие серверы уцелеют), сама команда, что надо перезапустить, и только
        потом — что прежний токен отозван. Всё, мимо чего пройти нельзя, стоит
        ПОСЛЕ команды: первое сообщение человек, пришедший сюда второй раз,
        читает по диагонали.
        """
        await callback.answer()
        message = callback.message
        if not isinstance(message, Message):
            # Нажатие без сообщения (кнопка старше 48 часов, инлайн-режим):
            # отвечать некуда. Токен при этом не выпускается — иначе человек
            # остался бы с погашенным прежним и без нового.
            return
        lang = chat_ui_lang(message.chat.id)
        user = callback.from_user
        from src.db.mcp_access import issue_token

        try:
            выпущен = await asyncio.to_thread(issue_token, user.id)
        except UnboundError:
            # Токен выпускается только на учётку сайта (аудит 12.10, D448):
            # пускают и сотрудников УК по списку окружения, у них учётки нет.
            await message.answer(t("mcp.unbound_self", lang))
            return
        except DbError:
            # В журнал — разбор, человеку — что делать. Значения токена нет ни
            # там, ни там: выпуск до него не дошёл.
            logger.exception("токен доступа к MCP не выпущен для %s", log_id(user.id))
            await message.answer(t("mcp.unavailable", lang))
            return
        await message.answer(t("mcp.setup", lang))
        # Срок — до команды: после неё человек читает только «перезапустите».
        await message.answer(t("mcp.expires", lang, date=выпущен.expires_at.date().isoformat()))
        await message.answer(setup_command(url=setup_url(lang), token=выпущен.value))
        await message.answer(t("mcp.code_restart", lang))
        if выпущен.replaced_previous:
            await message.answer(t("mcp.replaced", lang))

    return router
