"""Карта синонимов формулировок со стороны разговора (T285, решение D119).

Решение владельца: если аудитор сказал иначе или с ошибками и **прямого**
совпадения формулировки с методикой не нашлось, разобранная формулировка
складывается в базу синонимом пункта и работает при следующем поиске; прямое
совпадение синонима второй строки не заводит. Само хранилище и слой доступа к
нему — блок `db` (T284); здесь живёт то, чего слой намеренно не знает:
**когда** карту спрашивать, **когда** в неё писать и что считать пригодным
синонимом.

**Слой отдаёт КОД пункта, а не пункт.** Методики в базе нет, а у каждой
проверки своё издание (D063, D064) — значит, действует ли код в издании ТОЙ
проверки, решается здесь. Синоним, оставшийся от снятого пункта, никуда не
приводит и разбор не роняет.

**Отказ карты проверку не останавливает.** Тот же довод, что у `roster`:
«отказ базы не мешает боту подняться, обход точки важнее». Невыученное слово —
досада, а сказанное аудитору «не сохранено» — неправда о его работе. Поэтому
любой отказ блока `db` здесь кончается строкой в журнале и ответом «не помню»,
а не исключением наружу. Ловится `DbError` целиком, а не один `SynonymError`:
ненастроенная база отказывает раньше, `ConfigError`, и он такой же законный
ответ «карты нет», как недоступная таблица.

**Звать слой может только ярус выше базы.** `src.recognize` и `src.db` — пиры в
слоевом контракте (`pyproject.toml`), и импорт карты в быстрый путь уронил бы
`lint-imports`. Поэтому карту спрашивает бот и передаёт разбору уже готовыми
данными — кодом пункта, а не связью с базой.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass

from src import domain
from src.db import synonyms
from src.db.errors import DbError
from src.domain.errors import DomainError
from src.recognize.shortlist import MANUAL_ONLY

logger = logging.getLogger(__name__)

#: Вид пункта, который разбор вправе поставить сам. Служебные строки (сводная
#: по процессу) записью не бывают вовсе.
VIOLATION = "violation"


@dataclass(frozen=True)
class Learned:
    """Пункт, поднятый картой синонимов, и формулировка, которой его уже называли.

    Формулировка нужна не для поиска, а для показа: аудитор обязан видеть,
    ПОЧЕМУ система поставила этот пункт, — иначе запись без подтверждения
    выглядит догадкой ниоткуда. Хранится она дословно, как сказал человек.
    """

    code: str
    phrase: str


def _applicable(code: str, *, chat_id: int) -> bool:
    """Годится ли код в синонимы — в издании ЭТОЙ проверки.

    Проверка стоит по обе стороны, на чтении и на записи, и это не дубль.
    Читая, мы не вправе поставить пункт, которого разбор не предлагает: правило
    «служебное ставит только аудитор» обошлось бы с чёрного хода. Записывая —
    не вправе засорять карту строками, которые никогда не сработают: карту
    читает человек, разбирая промахи, и мёртвая строка врёт ему о том, чему
    система научилась.
    """
    try:
        item = domain.get_item(code, chat_id=chat_id)
    except DomainError:
        # Предупреждением, а не молчанием: код в карте есть, а в издании
        # проверки его нет — это и есть тот разбор, ради которого карта ведётся.
        logger.warning("синоним ведёт к пункту «%s», которого в издании этой проверки нет", code)
        return False
    if item.kind != VIOLATION or code in MANUAL_ONLY:
        logger.info("пункт «%s» разбор не предлагает — синонимом он не работает", code)
        return False
    return True


def recall(note: str, *, lang: str, chat_id: int) -> Learned | None:
    """Пункт, которым эта формулировка уже кончалась. Не знаем — `None`.

    Зовётся ПОСЛЕ сверки со списком нарушений и только когда та промолчала:
    прямое совпадение карту не спрашивает и не пополняет (D119).

    `lang` — язык речи аудитора, не интерфейса и не отчёта: карта ключуется
    тем языком, на котором сказано (`inspections.speech_lang`).
    """
    сказанное = note.strip()
    if not сказанное:
        # Голый кадр без слов спрашивать не о чем. Поход в базу за пустой
        # строкой — это запрос на каждый кадр пачки впустую.
        return None
    try:
        alias = synonyms.lookup_phrase(сказанное, lang=lang)
    except DbError as exc:
        logger.warning("карта синонимов не ответила (%s): %s", type(exc).__name__, exc)
        return None
    if alias is None:
        return None
    if not _applicable(alias.item_code, chat_id=chat_id):
        return None
    return Learned(code=alias.item_code, phrase=alias.phrase)


def learn(note: str, *, item_code: str, lang: str, chat_id: int) -> str:
    """Запомнить формулировку синонимом пункта. Исход — кодом слоя или пусто.

    Пусто означает «в карту не легло и разбирать нечего»: слов не было, пункт
    в синонимы не годится или карта не ответила. Ни один из трёх случаев не
    отказ для вызывающего — запись аудитора к этому времени уже сделана, и
    рассказывать ему про память системы нечего.

    Разночтение (`CONFLICT`) называется в журнале и на этом кончается: строку
    карты не переписывает никто — прав UPDATE у роли приложения нет вовсе
    (T284), а снятие неверного синонима управляющей компанией заведено
    отдельной задачей (#255).
    """
    сказанное = note.strip()
    if not сказанное:
        return ""
    if not _applicable(item_code, chat_id=chat_id):
        return ""
    try:
        память = synonyms.remember_phrase(
            сказанное, item_code=item_code, lang=lang, origin=synonyms.LEARNED
        )
    except DbError as exc:
        logger.warning(
            "синоним пункта «%s» не записан (%s): %s", item_code, type(exc).__name__, exc
        )
        return ""
    if память.outcome == synonyms.CONFLICT:
        logger.warning(
            "формулировка «%s» уже ведёт к пункту «%s», а запись легла на «%s» — "
            "строка карты не тронута",
            сказанное,
            память.alias.item_code,
            item_code,
        )
    return память.outcome
