"""Вопрос о повторе: такой же пункт уже был нарушением в предыдущей проверке точки.

Правило владельца D191 говорит про цену: повтор нарушения предыдущей проверки
стоит вдвое. D255 уточняет, кто его находит: **система сама** замечает, что в
этой пиццерии этот пункт уже был нарушением, и спрашивает проверяющего, считать
ли запись ×2, — а решение остаётся за ним («давай сейчас сделаем через
подтверждение, чтобы конечное решение принимал проверяющий»).

Отсюда разделение, на котором держится весь этот модуль: **система приносит
наблюдение, цену назначает человек**. Наблюдение — «такой же пункт был в
прошлый раз» — проверяемый факт из базы. Вывод «значит это повтор» фактом не
является: тот же код мог относиться к другой единице оборудования, а
исправленное и снова сломавшееся — не то же самое, что не исправленное вовсе.
Поэтому само наблюдение ничего не меняет в записи: пометка повтора ставится
только ответом «да» на вопрос (`routers/edit.py`, `routers/correct.py`).

Вопрос не задаётся для `D3`: этот класс сжигает долю зоны целиком, и удваивать
там нечего — ставки за запись у него нет. Не задаётся и для `D0`: замер не
нарушение, вычета у него нет. Вопрос о цене, которая не изменится, хуже его
отсутствия.

Недоступная база вопрос снимает, а не роняет запись: аудитор стоит на точке,
запись уже сделана, и обход не должен зависеть от того, доехал ли до базы
справочный запрос.
"""

from __future__ import annotations

import logging
from datetime import date

from src.db import queries
from src.db.errors import DbError
from src.domain.models import Inspection

logger = logging.getLogger(__name__)

#: Классы, у которых нет ставки за запись, — удваивать нечего (D191): `D3`
#: сжигает долю зоны целиком, `D0` — информационная запись без вычета, `R` —
#: рекомендация (D201).
NOTHING_TO_DOUBLE = frozenset({"D0", "D3", "R"})


def seen_before(inspection: Inspection | None, *, code: str, level: str) -> date | None:
    """Когда этот пункт был нарушением в предыдущей проверке этой точки.

    Отдаётся ровно наблюдение — дата прошлого обхода, — без вывода о повторе:
    решение остаётся за проверяющим (D191, D255). `None` означает «спрашивать
    не о чем» и объединяет все случаи, в которых вопрос неуместен или
    недоступен: неизвестная точка, класс без ставки, прошлых проверок нет,
    пункта в прошлой не было, база не ответила. Для показа они неразличимы —
    во всех аудитор видит запись без вопроса.
    """
    if inspection is None or level in NOTHING_TO_DOUBLE:
        return None
    tenant = (inspection.tenant or "").strip()
    unit = (inspection.unit or "").strip()
    if not tenant or not unit:
        # Поход в базу за пустым названием точки всё равно кончился бы отказом.
        return None
    try:
        прошлая = queries.previous_inspection(tenant=tenant, unit=unit)
    except DbError as exc:
        # Предупреждением, а не молчанием: вопрос пропал, и разбирающий
        # «почему бот молчал про повтор» должен найти причину в журнале.
        logger.warning("предыдущая проверка не пришла (%s): %s", type(exc).__name__, exc)
        return None
    if прошлая is None or code not in прошлая.codes:
        return None
    return прошлая.date
