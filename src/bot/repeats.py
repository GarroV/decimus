"""Подсказка о повторе: такой же пункт уже был в предыдущей проверке точки (#359).

Правило владельца D191 говорит про цену: повтор нарушения предыдущей проверки
стоит вдвое. Но пометить запись повтором может только человек — движок считает
одну проверку и истории точки не видит, а система, решившая это за аудитора,
удвоила бы вычет там, где нарушение другое.

Отсюда разделение, на котором держится весь этот модуль: **система приносит
наблюдение, цену назначает аудитор**. Наблюдение — «такой же пункт был в
прошлый раз» — проверяемый факт из базы. Вывод «значит это повтор» фактом не
является: тот же код мог относиться к другой единице оборудования, а
исправленное и снова сломавшееся — не то же самое, что не исправленное вовсе.
Поэтому подсказка ничего не меняет в записи и ни на что не влияет, кроме того,
что аудитор теперь знает про прошлый раз и не должен помнить его наизусть.

Подсказка не показывается для `D3`: этот класс сжигает долю зоны целиком, и
удваивать там нечего — ставки за запись у него нет. Подсказка, зовущая нажать
кнопку, которая ничего не изменит, хуже её отсутствия.

Недоступная база подсказку снимает, а не роняет запись: аудитор стоит на точке,
запись уже сделана, и обход не должен зависеть от того, доехал ли до базы
справочный запрос.
"""

from __future__ import annotations

import logging

from src.db import queries
from src.db.errors import DbError
from src.domain.models import Inspection

logger = logging.getLogger(__name__)

#: Класс, который сжигает долю зоны целиком. Ставки за запись у него нет,
#: значит и удваивать нечего (D191).
BURNS_ZONE = "D3"


def seen_before(inspection: Inspection | None, *, code: str, level: str) -> bool:
    """Был ли этот пункт записан в предыдущей проверке этой точки.

    Отдаётся ровно наблюдение, без вывода о повторе — решение остаётся за
    аудитором (D191). `False` означает «подсказывать нечем» и объединяет все
    случаи, в которых подсказка неуместна или недоступна: неизвестная точка,
    класс без ставки, прошлых проверок нет, база не ответила. Для показа они
    неразличимы — во всех аудитор видит запись без подсказки.
    """
    if inspection is None or level == BURNS_ZONE:
        return False
    tenant = (inspection.tenant or "").strip()
    unit = (inspection.unit or "").strip()
    if not tenant or not unit:
        # Поход в базу за пустым названием точки всё равно кончился бы отказом.
        return False
    try:
        прошлые = queries.previous_codes(tenant=tenant, unit=unit)
    except DbError as exc:
        # Предупреждением, а не молчанием: подсказка пропала, и разбирающий
        # «почему бот молчал про повтор» должен найти причину в журнале.
        logger.warning("коды предыдущей проверки не пришли (%s): %s", type(exc).__name__, exc)
        return False
    return code in прошлые
