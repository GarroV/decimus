"""Память бота о проверке и чужой старт: сверка личности проверки (D392).

`PendingStore` и `MaterialStore` живут в памяти бота и забываются на старте
проверки, который делает сам бот (`routers/start.py`). Проверку может начать и
мини-апп — это другой процесс (сервис обхода), до памяти бота он не дотянуться.
Без сверки предложение, показанное кнопками по кадру старой проверки, или слово,
придержанное в ней, легло бы в новую — в другую пиццерию, партнёру в отчёт.

Поэтому у каждой проверки есть личность (`Inspection.run_id`, её ставит старт),
а хранилища помнят, при какой личности наполнялись. Сменилась — память чата
сбрасывается целиком, до того как к ней обратились. Проверка при обращении, а
не очистка по событию: события из другого процесса бот не получает.

Личность читается с диска на каждое обращение к памяти чата — это один маленький
файл, а ошибка здесь молчалива, и дешевле прочитать, чем промахнуться.
"""

from __future__ import annotations

from collections.abc import Callable

#: Откуда берётся личность проверки чата. `None` у хранилища — сверки нет
#: (юнит-тесты без диска).
RunOf = Callable[[int], str]


class RunGuard:
    """Помнит, какую личность проверки видела память каждого чата."""

    def __init__(self, current: RunOf | None = None) -> None:
        self._current = current
        self._seen: dict[int, str] = {}

    def is_stale(self, chat_id: int) -> bool:
        """Сменилась ли проверка чата с прошлого обращения. Первое обращение — нет.

        Первое обращение ничего не сбрасывает: до него память чата пуста, ведь
        наполняется она только через это же обращение.
        """
        if self._current is None:
            return False
        now = self._current(chat_id)
        before = self._seen.get(chat_id)
        self._seen[chat_id] = now
        return before is not None and before != now

    def forget(self, chat_id: int) -> None:
        self._seen.pop(chat_id, None)
