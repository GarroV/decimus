"""Строка настройки Claude Desktop: свой мост, штатный `plutil`, никакого Node (#222, D103).

**Что человек получает.** Один блок, вставляемый в терминал: он кладёт на
машину мост stdio↔HTTP и дописывает одну запись в файл настроек приложения.
После перезапуска приложения наш сервер у него есть.

**Почему не `mcp-remote`.** Прежняя редакция присылала `npx -y mcp-remote`:
Node как обязательное условие подключения и постоянный процесс-посредник между
приложением и нашим сервером. Владелец отверг это прямо (D103), указав на уже
работающий мост соседнего продукта, и мост действительно лучше по существу:
токен уходит в файл конфигурации curl с правами 600, а не в `argv`, где его
видно любому через `ps`. Отозванный токен у посредника к тому же оборачивался
молчаливым потоком `401` — на площадке их набралось больше 170 за час.

**Почему `plutil`, а не `node -e` / `python3 -c`.** `/usr/bin/plutil` есть на
любом маке, и проверено (macOS 26.6.2), что он делает ровно то, что здесь
требуется: сохраняет чужие серверы и посторонние ключи, а на неразбираемом
файле возвращает 1 и файл НЕ ТРОГАЕТ. Последнее и есть главное требование:
тихо заменить непонятый конфиг человека на наш единственный сервер — худший из
возможных исходов, хуже отказа.

**Почему тело моста берётся из файла, а не написано здесь строкой.** Мост
живёт в `tools/mcp_bridge.sh` и оттуда же попадает в команду. Копия текста
внутри каталога сообщений разъехалась бы с оригиналом на первой правке, и
разъехалась бы молча: у человека на машине работала бы вчерашняя редакция.
Комментарии при сборке снимаются — сообщение телеграма ограничено 4096
знаками, а в них сплошь «почему», нужное читателю репозитория, не терминалу.
"""

from __future__ import annotations

import shlex
from pathlib import Path

#: Имя нашего сервера в файле настроек приложения. Оно же — ключ, который
#: команда заменяет при повторной настройке, поэтому вторая настройка не
#: плодит записей, а обновляет одну.
SERVER_NAME = "dodo-audit"

#: Куда кладётся мост на машине человека — путь ОТНОСИТЕЛЬНО его дома. Свой
#: каталог, а не общий `~/bin`: приём соседнего продукта (`~/.swarm-brain/bin`),
#: и по нему сразу видно, чьё это и что сносить, если продукт больше не нужен.
BRIDGE_PATH = ".dodo-audit/bin/mcp_bridge.sh"

#: Файл настроек Claude Desktop — тоже относительно дома. Путь macOS-only, и
#: человеку это сказано ДО команды (`mcp.desktop_note`).
CONFIG_PATH = "Library/Application Support/Claude/claude_desktop_config.json"

#: Мост в репозитории — единственный источник его текста (D055).
_BRIDGE_SOURCE = Path(__file__).resolve().parents[2] / "tools" / "mcp_bridge.sh"


class McpSetupError(RuntimeError):
    """Команду настройки собрать не из чего или не из того."""


def bridge_body() -> str:
    """Тело моста в том виде, в каком оно уедет на машину человека.

    Снимаются комментарии и пустые строки, остаётся строка запуска и код.
    Отказ вместо пустой строки, если файла нет: команда без моста выглядела бы
    выполненной, а подключение не работало бы — молчаливый промах ровно того
    сорта, из-за которого задача и заведена.
    """
    if not _BRIDGE_SOURCE.exists():
        raise McpSetupError(
            f"мост {_BRIDGE_SOURCE} не найден — команду настройки собрать не из чего"
        )
    строки = _BRIDGE_SOURCE.read_text(encoding="utf-8").splitlines()
    код = [s for s in строки if s.strip() and not s.lstrip().startswith("#")]
    if not код:
        raise McpSetupError(f"в мосте {_BRIDGE_SOURCE} не осталось ни одной строки кода")
    return "\n".join(["#!/bin/bash", *код])


def _проверить(значение: str, что: str) -> str:
    """Ни кавычек, ни обратных косых: они уедут внутрь JSON для `plutil`.

    Отказ, а не экранирование: такие адреса и токены у нас не заводятся вовсе
    (токен — `secrets.token_urlsafe`, адрес — настройка стенда), поэтому их
    появление означает не редкий случай, а поломку, и чинить её надо там, где
    она возникла, а не здесь молчаливой заменой символов.
    """
    if not значение:
        raise McpSetupError(f"{что} пуст — команда настройки была бы нерабочей")
    if any(символ in значение for символ in ('"', "\\", "\n")):
        raise McpSetupError(f"{что} содержит кавычку или обратную косую: {значение!r}")
    return значение


def code_command(*, url: str, token: str) -> str:
    """Одна строка для Claude Code: прямой HTTP-транспорт, без моста и установки.

    **Моста здесь нет, и он не нужен** — проверено живым подключением
    15.09.2026: клиент ходит к нашему серверу по HTTP сам, `claude mcp add
    --transport http` дописывает запись в `~/.claude.json`, сервер отвечает
    `initialize` нашим `serverInfo`. Тело моста пересылалось в чат только
    ради Claude Desktop, который удалённый сервер так не умеет.

    **Почему это главный путь пункта.** Владелец на живом прогоне 15.09.2026
    потребовал короткую команду вместо прежней простыни, указав на соседний
    продукт: там установка — одна строка, которая просто прописывает сервер в
    настройки клиента. Сорок строк с телом моста внутри человек не читает,
    копирует из телеграма с потерями и справедливо боится запускать
    (решение D111).

    Токен уезжает в `--header` и оседает в `~/.claude.json` — там же, где его
    держит клиент для любого другого удалённого сервера. В `argv` он при этом
    виден через `ps` ровно на время одной команды, а не на каждую строку
    сессии, как это было бы у моста без файла конфигурации curl.
    """
    адрес = _проверить(url, "адрес MCP-сервера")
    секрет = _проверить(token, "токен доступа")
    заголовок = f"Authorization: Bearer {секрет}"
    return (
        f"claude mcp add --transport http {SERVER_NAME} "
        f"{shlex.quote(адрес)} --header {shlex.quote(заголовок)}"
    )


def desktop_command(*, url: str, token: str, done: str) -> str:
    """Готовый блок для терминала: мост на машину, запись в настройки приложения.

    Всё тело идёт в ОТДЕЛЬНУЮ оболочку (`bash <<'DODO_SETUP'`), а не строками в
    текущую, и это не косметика. Внутри нужны `set -eu` и `trap` — в
    интерактивном zsh человека они остались бы висеть после команды, а ошибка
    посреди блока при `errexit` способна закрыть ему окно терминала. Отдельная
    оболочка забирает и то и другое с собой, а заодно не оставляет в его
    сессии наших переменных с токеном внутри.

    Порядок шагов выбран так, чтобы настоящий файл настроек трогался ровно
    один раз и в самом конце: сначала правится КОПИЯ, и только удавшаяся копия
    переименовывается на место. Обрыв посреди записи оставил бы иначе
    обрезанный JSON, то есть сломал бы все серверы разом, включая чужие.

    Отсутствующий конфиг заводится как `{"mcpServers":{}}`, а не как `{}`, и
    это не украшательство: пустой `{}` `plutil` разбирает как OpenStep-plist и
    писать в него отказывается («Conversion to OpenStep format is not
    supported») — то есть у человека, не настраивавшего до нас ни одного
    сервера, команда падала бы, а у остальных работала. Проверено запуском.
    """
    адрес = _проверить(url, "адрес MCP-сервера")
    секрет = _проверить(token, "токен доступа")
    сообщение = shlex.quote(done)
    запись = (
        '{\\"command\\":\\"/bin/bash\\",\\"args\\":[\\"$BIN\\"],\\"env\\":'
        f'{{\\"DODO_MCP_URL\\":\\"{адрес}\\",\\"DODO_MCP_TOKEN\\":\\"{секрет}\\"}}}}'
    )
    шаги = [
        "bash <<'DODO_SETUP'",
        "set -eu",
        f'BIN="$HOME/{BRIDGE_PATH}"',
        f'CFG="$HOME/{CONFIG_PATH}"',
        'mkdir -p "$(dirname "$BIN")" "$(dirname "$CFG")"',
        "cat > \"$BIN\" <<'DODO_BRIDGE'",
        bridge_body(),
        "DODO_BRIDGE",
        'chmod 700 "$BIN"',
        'TMP="$CFG.dodo-tmp"',
        "trap 'rm -f \"$TMP\"' EXIT",
        'if [ -f "$CFG" ]; then cp "$CFG" "$TMP"; else printf \'{"mcpServers":{}}\' > "$TMP"; fi',
        'plutil -extract mcpServers json -o /dev/null "$TMP" 2>/dev/null \\',
        "  || plutil -insert mcpServers -json '{}' \"$TMP\"",
        f'plutil -replace mcpServers.{SERVER_NAME} -json "{запись}" "$TMP"',
        'plutil -convert json -r -o "$TMP" "$TMP"',
        'mv "$TMP" "$CFG"',
        f"printf '%s\\n' {сообщение}",
        "DODO_SETUP",
    ]
    return "\n".join(шаги)
