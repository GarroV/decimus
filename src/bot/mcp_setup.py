"""Команда установки MCP — одна строка с личным токеном (#222, D103, D112).

Собирает её веб: «Настройки» и «Claude (MCP)» (`src/web/users_mcp.py`,
`src/web/walk_settings.py`). Бот команду не присылает (D626): пункт «Установка
MCP» из него снят, рабочая платформа — веб. Модуль остался в `src/bot` лишь
потому, что оттуда его и берёт веб (там же живёт каталог текстов `t`); перенос
в другое место — отдельное решение.

**Что человек получает.** Одну строку для терминала: она скачивает установщик
за адресом `/setup` (`src/mcp/install.py`), сверяет его отпечаток и запускает
с токеном в окружении. Настройку Claude на машине человека делает
установщик (`src/mcp/install.py`), а не эта строка.
"""

from __future__ import annotations

import hashlib
import shlex

from src.mcp.install import install_script

#: Адрес сервера MCP, каким его видит человек со своей машины (`BOT_MCP_URL`).
MCP_URL_VAR = "BOT_MCP_URL"


class McpSetupError(RuntimeError):
    """Команду настройки собрать не из чего или не из того."""


def _проверить(значение: str, что: str) -> str:
    """Ни кавычек, ни обратных косых: они уедут внутрь JSON для `plutil`.

    Отказ, а не экранирование: такие адреса и токены у нас не заводятся вовсе
    (токен — `secrets.token_urlsafe`, адрес — настройка стенда), поэтому их
    появление означает не редкий случай, а поломку, и чинить её надо там, где
    она возникла, а не здесь молчаливой заменой символов.
    """
    if not значение:
        raise McpSetupError(f"{что} пуст — команда настройки была бы нерабочей")
    if any(символ in значение for символ in ('"', "\\", "\n")):
        raise McpSetupError(f"{что} содержит кавычку или обратную косую: {значение!r}")
    return значение


def installer_sha256() -> str:
    """SHA-256 установщика ровно в том виде, в каком его отдаёт сервер (F-103).

    Отпечаток едет в строке запуска, то есть другим путём, чем сам скрипт: тот,
    кто подменил ответ `/setup` (или оборвал его по дороге), отпечаток в
    переписке подделать не может, и `shasum -c` не даст запустить чужое.
    Считается от `install_script()` — той же сборки, что отдаёт сервер, а не от
    файла на диске: в файле стоит маркер моста, а отдаётся уже слитое.
    """
    return hashlib.sha256(install_script().encode("utf-8")).hexdigest()


def setup_command(*, url: str, token: str) -> str:
    """Одна строка для терминала: скачать установщик и запустить его с токеном.

    **Форма взята у соседнего продукта, а не придумана** (swarm-brain,
    `functions/v1/swarm-setup`): публичный GET отдаёт bash-скрипт, человек
    запускает его одной строкой, токен приезжает ОКРУЖЕНИЕМ. Владелец
    потребовал ровно этого, указав на свой работающий продукт (D112).

    **Почему токен в окружении, а не в аргументах.** Аргументы процесса видны
    на машине всем через `ps`; переменные окружения чужого процесса на маке —
    нет. Тот же довод, по которому мост кладёт заголовок в файл конфигурации
    curl (D055).

    **Почему тело установщика здесь не собирается.** Раньше пункт слал сорок
    строк с мостом внутри: сообщение телеграма копируется целиком, обрывается
    на 4096 знаках и уезжает в терминал с потерями. Теперь скрипт лежит за
    адресом (`src/mcp/install.py`), а в переписке — только строка запуска.
    """
    адрес = _проверить(url, "адрес MCP-сервера")
    секрет = _проверить(token, "токен доступа")
    установщик = f"{адрес.rstrip('/')}/setup"
    отпечаток = installer_sha256()
    return (
        f'f=$(mktemp) && curl -fsSL {shlex.quote(установщик)} -o "$f" && '
        f'echo "{отпечаток}  $f" | shasum -a 256 -c - && '
        f'DECIMUS_MCP_URL={shlex.quote(адрес)} DECIMUS_MCP_TOKEN={shlex.quote(секрет)} bash "$f"; '
        'rm -f "$f"'
    )
