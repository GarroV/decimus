"""Пространство, от имени которого идёт обращение к базе (аудит 12.10, F-037, F-005).

Охват в тексте запроса (`src/db/reach.py`) — первая линия: каждый запрос сам
говорит, чьё читает. Вторая линия — сама база. Построчные политики роли
приложения (миграция `0061_space_isolation`) сверяют строку с настройкой
`decimus.space` соединения, и запрос, в котором условия охвата нет, всё равно
не отдаёт чужого.

Кто ставит пространство — двери, а не запросы: веб по вошедшему
(`src/web/auth.py`), бот и мини-апп — по привязке человека, MCP — по учётке
токена. Служебная работа без человека (сбор рейтингов, досылка кадров, сверка
хранилища, API для сервисов) ставит его явно — `acting_space(SYSTEM_SPACE)`,
и каждое такое место видно поиском по имени.

**Не поставлено — не видно ничего.** Политика при пустой настройке не отдаёт ни
строки и не принимает записи: забытая дверь проявляется пустым экраном на первом
же прогоне, а не утечкой. Значения:

- код пространства (`HQ`, партнёр) — чтение по охвату этого пространства (УК —
  вся сеть, D283; партнёр — свои проверки и проверки пиццерий своих стран,
  D289), запись — только своё (D283);
- `SYSTEM_SPACE` (`*`) — служебное обращение: всё. Только для работы без
  человека.

Чем это НЕ является: защитой от захваченного процесса. Роль приложения сама
может поставить себе любую настройку; граница здесь — от ошибки в коде (запрос
без охвата, помощник по одному идентификатору), а не от того, кто уже исполняет
код в контейнере.

Настройка ставится на всё время, пока соединение у вызывающего (`set_config(...,
false)` вне транзакции), и снимается сбросом пула на возврате (`RESET ALL`,
`src/db/pool.py`): откат транзакции внутри блока её не теряет, а до следующего
человека она не доходит.
"""

from __future__ import annotations

from collections.abc import Iterator
from contextlib import contextmanager
from contextvars import ContextVar
from typing import Any

import psycopg

from src.domain.tenants import canonical_tenant

from .errors import DbError

#: Имя настройки соединения, которую читают политики (`decimus_space()` в `0061`).
SPACE_SETTING = "decimus.space"

#: Служебное обращение без человека: читает и пишет всё. Ставится только явно.
SYSTEM_SPACE = "*"

_SPACE: ContextVar[str | None] = ContextVar("decimus_space", default=None)

#: Пространство, когда дверь его не поставила. В продукте — всегда `None`: забытая
#: дверь обязана упасть ошибкой базы. Подменяет его только оснастка тестов
#: (`tests/conftest.py: db_env`), где функции базы зовут напрямую, мимо дверей;
#: двери в тех же тестах ставят своё пространство поверх него. Код продукта это
#: имя не трогает — держит `tests/test_db_space_isolation.py`.
_FALLBACK: str | None = None

_SET_SQL = "select set_config('decimus.space', %s, false)"


def _checked(space: str) -> str:
    """Код пространства или `SYSTEM_SPACE`; пустое — ошибка вызывающего, а не «ничего»."""
    if space == SYSTEM_SPACE:
        return space
    код = canonical_tenant(space or "")
    if not код:
        raise DbError(
            "Не задано пространство, от имени которого идёт обращение к базе: без него "
            "база не отдаст ни строки, и пустой ответ выдал бы себя за «ничего нет»"
        )
    return код


def current_space() -> str | None:
    """Пространство этого обращения или `None`, если дверь его не поставила."""
    space = _SPACE.get()
    return space if space is not None else _FALLBACK


@contextmanager
def acting_space(space: str) -> Iterator[str]:
    """Всё, что внутри блока, идёт в базу от имени `space`.

    Вложенный блок с ДРУГИМ пространством — ошибка кода: дверь уже сказала, чей
    это запрос, и молча подменить её значит ровно то, от чего защищает политика.
    Служебное (`SYSTEM_SPACE`) внутри человеческого тоже запрещено по той же
    причине. То же самое пространство повторно — можно (двери вкладываются).
    """
    код = _checked(space)
    было = _SPACE.get()
    if было is not None and было != код:
        raise DbError(
            f"Обращение уже идёт от имени пространства {было!r}; подменить его на "
            f"{код!r} внутри того же обращения нельзя"
        )
    метка = _SPACE.set(код)
    try:
        yield код
    finally:
        _SPACE.reset(метка)


def enter_space(space: str) -> object:
    """Поставить пространство без блока `with` — для хуков «до/после» запроса.

    Возвращает метку для `leave_space`. Хук «после» обязан её вернуть, иначе
    пространство осталось бы на потоке до следующего запроса.
    """
    return _SPACE.set(_checked(space))


def leave_space(метка: object) -> None:
    """Снять пространство, поставленное `enter_space`."""
    _SPACE.reset(метка)  # type: ignore[arg-type]


def apply_space(conn: psycopg.Connection[Any]) -> None:
    """Передать пространство обращения соединению — до первой транзакции.

    Ставится в автокоммите, чтобы откат транзакции внутри блока не снял
    настройку. Пространства нет — настройка не трогается: у свежего или
    сброшенного пулом соединения она пустая, и политики не отдадут ничего.
    """
    space = current_space()
    if space is None:
        return
    autocommit = conn.autocommit
    if conn.info.transaction_status != psycopg.pq.TransactionStatus.IDLE:
        raise DbError("Пространство передаётся соединению до начала транзакции")
    conn.autocommit = True
    try:
        conn.execute(_SET_SQL, (space,))
    finally:
        conn.autocommit = autocommit
