"""Отказы блока `db`.

Один базовый класс, чтобы вызывающий (бот, T093/T068) мог перехватить любой
отказ этого блока одним `except DbError` и не уронить проверку на точке:
падение базы задерживает аналитику, но не сам обход (D027, DoD блока).
"""

from __future__ import annotations


class DbError(Exception):
    """Базовый отказ блока `db`."""


class EmailTakenError(DbError):
    """Почта уже привязана к другой учётке этого арендатора (T332).

    Отдельным классом, а не общим «не удалось»: занятая почта — обычный ответ
    экрану («такая почта уже у другого человека»), а не сбой базы. Свалив их в
    одно, админка сказала бы про опечатку то же, что про упавшую связь.
    """


class ConfigError(DbError):
    """Окружение непригодно: не задан `DATABASE_URL` или база недоступна на старте."""


class PushError(DbError):
    """Слив завершённой проверки не удался: нет состояния, оценки или базы нет на связи.

    Текст отказа безопасен для лога: путей вне проверки и содержимого записей
    в нём нет (конституция, раздел «Правила безопасности»).
    """


class VersionMismatchError(PushError):
    """Проверку считают не по той методике, которой она помечена (T148, T178).

    Наследник `PushError`, а не сосед: слив действительно не состоялся, и
    вызывающий, который ловит блок целиком (`except DbError`), не должен
    падать от того, что у отказа появился более точный тип. Но разбирать этот
    случай ему придётся отдельно — база здесь в полном порядке, и сообщение
    «историю сохранить не удалось» отправило бы человека чинить не то.

    Обе версии лежат полями, а не только в тексте: текст пишется человеку и
    правится, а ветка кода, которая его показывает, обязана выбираться типом и
    заполняться значениями, а не разбором строки.
    """

    def __init__(self, message: str, *, recorded: str, current: str) -> None:
        super().__init__(message)
        self.recorded = recorded
        self.current = current


class UnitRefusedError(PushError):
    """Точку проверки пространство принять не может (#482, D234, ревью #340 п.10).

    Две причины — точки нет в справочнике УК или она не из стран пространства —
    отказывают ОДНИМ типом и одним текстом: различие подсказало бы партнёру, что
    пиццерия с таким названием в сети есть, только не в его странах.

    Наследник `PushError` по той же причине, что `VersionMismatchError`: слив не
    состоялся, и ловящий блок целиком не должен падать от более точного типа. Но
    база здесь в порядке, и повтор не поможет никогда — поэтому вызывающий
    разбирает этот случай отдельно, а не текстом «база не ответила».
    """

    def __init__(self, message: str, *, unit: str) -> None:
        super().__init__(message)
        self.unit = unit


class UnitExistsError(DbError):
    """Пиццерия с таким именем или синонимом в справочнике уже есть (#437).

    Несёт найденную точку: экран показывает её и ведёт в её карточку, а не
    отвечает загадкой «не получилось».
    """

    def __init__(
        self, message: str, *, unit_id: str, name: str, country: str | None = None
    ) -> None:
        super().__init__(message)
        self.unit_id = unit_id
        self.name = name
        #: Страна найденной точки: ссылку на её карточку экран даёт, только
        #: если точка в охвате вошедшего.
        self.country = country


class StorageError(DbError):
    """Хранилище кадров не приняло или не отдало объект.

    Заведён отдельным типом, чтобы драйвер хранилища переводил свои исключения
    (у boto3 они свои, у следующего поставщика будут другие) на границе самого
    драйвера. Иначе перевод пришлось бы делать в месте вызова широким
    `except Exception`, а он заодно подменял бы собой ошибки в коде
    вызывающего — и настоящая поломка выглядела бы отказом хранилища.
    """


class AccessError(DbError):
    """Личный доступ к MCP не выдан, не отозван или не сверен (T253, D098/D099).

    Отдельный тип, а не `PushError`: слив проверки и выдача доступа отказывают
    по разным причинам и чинятся по-разному, а вызывающему, который ловит блок
    целиком (`except DbError`), от появления более точного типа ничего
    не делается.

    **Текст отказа безопасен и для журнала, и для чата.** Ни значения токена,
    ни его отпечатка, ни строки подключения в нём нет: этот отказ единственный
    в блоке, который показывается человеку в переписке, — а переписка то самое
    место, откуда секрет уже не убрать.
    """


class RetractionError(DbError):
    """Проверку не сняли из истории (T210, T233).

    Отдельный тип, а не `PushError`: слив и снятие отказывают по разным
    причинам и чинятся по-разному, а вызывающему, который ловит блок целиком
    (`except DbError`), от появления более точного типа ничего не делается.

    Текст отказа безопасен для лога: ни строки подключения, ни содержимого
    записей в нём нет (конституция, раздел «Правила безопасности»).
    """


class MoveError(DbError):
    """Проверку не перенесли по дате или пиццерии (D195).

    Текст безопасен для показа на карточке: ни строки подключения, ни текста
    драйвера в нём нет — только что не так и что с этим делать.
    """


class SynonymError(DbError):
    """Карта синонимов формулировок не приняла запись или не ответила (T284, D119).

    Отдельный тип, а не `PushError`: учение и слив отказывают по разным
    причинам и стоят разного. Не запомнить синоним — досадно, проверка при
    этом цела и уходит партнёру; не слить проверку — потеря истории. Слитые
    в один тип, они заставили бы вызывающего либо ронять обход из-за
    невыученного слова, либо глотать вместе с ним настоящую потерю.

    Текст отказа безопасен для лога: ни строки подключения, ни методики в нём
    нет — только то, что сказал человек, и код пункта.
    """


class AcceptError(DbError):
    """Проверку не подтвердили на приёмке (D199).

    Текст безопасен для показа на карточке: ни строки подключения, ни текста
    драйвера в нём нет — только что не так и что с этим делать.
    """


class ReviseError(DbError):
    """Запись проверки на приёмке не исправлена (D200).

    Текст безопасен для показа на карточке: ни строки подключения, ни текста
    драйвера в нём нет — только что не так и что с этим делать.
    """


class ActionPlanError(DbError):
    """Действие с экшн-планом не выполнено (D272, D274): запрос, срок, загрузка, вердикт.

    Текст безопасен для показа на экране: ни строки подключения, ни текста
    драйвера в нём нет — только что не так и что с этим делать.
    """


class PrescriptionError(DbError):
    """Действие с предписанием не выполнено (D266, D270): черновик, отправка, ответ, закрытие.

    Текст безопасен для показа на экране: ни строки подключения, ни текста
    драйвера в нём нет — только что не так и что с этим делать.
    """


class IssuedDraftLostError(PrescriptionError):
    """Черновик в Gmail уже лёг, а отметка «действует» в базе — нет.

    Отдельный класс, потому что исход для человека другой: в его почте лежит
    черновик предписания, которого система не считает отправленным, и его надо
    удалить, а не отправлять.
    """
