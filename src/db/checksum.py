"""Отпечаток миграции: что в нём участвует, а что нет (#258).

Сторож истории схемы сравнивает применённый файл с лежащим на диске, и до этой
задачи сравнивал **байты**. Комментарий в SQL байтами от схемы не отличается,
поэтому правка слов о миграции ломала накат так же, как правка самой миграции:
17.09.2026 накат на площадке встал целиком из-за того, что в `0007` убрали
дословную цитату владельца ради публичного репозитория (D073), — схема не
менялась ни на символ, а не доехали вместе с ней две следующие миграции.

Поэтому отпечаток снимается с **нормализованного** SQL: без комментариев, без
краевых пробелов, с одиночным пробелом вместо любой цепочки пропусков. Всё
остальное входит: правка тела по-прежнему отказ, и это главное свойство, ради
которого сторож существует.

**Нормализация уважает литералы.** `--` внутри строки и внутри `$$…$$` — это
данные, а не начало комментария: тела правил `0004` и `0010` написаны на
PL/pgSQL и живут в долларовых кавычках целиком. Разбирай их наивно — и две
разные миграции получили бы один отпечаток, то есть сторож пропустил бы ровно
ту подмену, от которой поставлен.

**Формат отпечатка назван в нём самом** (`sql1:<sha256>`). Голый sha256 без
префикса — прежний формат, снятый с полного текста; по нему раннер отличает
базу, накатанную до перехода, и переводит её печати сам, когда файл с тех пор
не тронут (`migrate.apply_migrations`).
"""

from __future__ import annotations

import hashlib

#: Префикс нового формата. Он же признак: запись без префикса снята прежним
#: раннером с полного текста файла.
ALGO_PREFIX = "sql1:"


def normalize_sql(sql: str) -> str:
    """SQL без комментариев и лишних пропусков — то, что и есть схема.

    Разбор посимвольный, а не регулярным выражением: состояний четыре
    (обычный текст, строка в кавычках, долларовая строка, комментарий), и
    регулярка, которая их различает, читается хуже, чем этот цикл.
    """
    out: list[str] = []
    i, n = 0, len(sql)
    while i < n:
        ch = sql[i]

        # Строковый или кавычечный литерал: до закрывающей кавычки всё данные.
        # Удвоенная кавычка внутри ('' или "") литерал не закрывает.
        if ch in "'\"":
            out.append(ch)
            i += 1
            while i < n:
                if sql[i] == ch and i + 1 < n and sql[i + 1] == ch:
                    out.append(sql[i : i + 2])
                    i += 2
                    continue
                out.append(sql[i])
                i += 1
                if sql[i - 1] == ch:
                    break
            continue

        # Долларовые кавычки: $$…$$ или $tag$…$tag$ — тело функции целиком.
        if ch == "$":
            tag = _dollar_tag(sql, i)
            if tag is not None:
                end = sql.find(tag, i + len(tag))
                if end == -1:
                    # Незакрытый тег — не наше дело чинить: остаток уходит в
                    # отпечаток как есть, а падать будет сам Postgres.
                    out.append(sql[i:])
                    break
                out.append(sql[i : end + len(tag)])
                i = end + len(tag)
                continue

        # Строчный комментарий: до конца строки, сам перевод строки остаётся
        # разделителем — иначе соседние слова склеились бы в одно.
        if ch == "-" and sql.startswith("--", i):
            end = sql.find("\n", i)
            i = n if end == -1 else end
            continue

        # Блочный комментарий, в Postgres вложенный: считаем глубину.
        if ch == "/" and sql.startswith("/*", i):
            depth, i = 1, i + 2
            while i < n and depth:
                if sql.startswith("/*", i):
                    depth, i = depth + 1, i + 2
                elif sql.startswith("*/", i):
                    depth, i = depth - 1, i + 2
                else:
                    i += 1
            out.append(" ")
            continue

        out.append(ch)
        i += 1

    return " ".join("".join(out).split())


def _dollar_tag(sql: str, start: int) -> str | None:
    """`$$` или `$tag$` в этом месте — или ничего, если это просто доллар."""
    end = sql.find("$", start + 1)
    if end == -1:
        return None
    tag = sql[start + 1 : end]
    if tag and not (tag[0].isalpha() or tag[0] == "_"):
        return None
    if not all(c.isalnum() or c == "_" for c in tag):
        return None
    return sql[start : end + 1]


def checksum(sql: str) -> str:
    """Отпечаток миграции — по схеме, а не по словам о ней."""
    digest = hashlib.sha256(normalize_sql(sql).encode("utf-8")).hexdigest()
    return f"{ALGO_PREFIX}{digest}"


def legacy_checksum(sql: str) -> str:
    """Прежний отпечаток: полный текст файла байт в байт.

    Нужен не ради совместимости вообще, а ради одного разговора с базой,
    накатанной до перехода: по нему видно, тронут ли файл с тех пор, — и если
    не тронут, печать можно перевести молча.
    """
    return hashlib.sha256(sql.encode("utf-8")).hexdigest()


def is_legacy(stored: str) -> bool:
    """Печать снята прежним раннером — с полного текста."""
    return not stored.startswith(ALGO_PREFIX)
