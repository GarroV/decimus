-- 0012_phrase_aliases.sql
--
-- T284: карта синонимов формулировок. Решение D119: если аудитор сказал иначе
-- или с ошибками и ПРЯМОГО совпадения с методикой не нашлось, разобранная
-- формулировка складывается сюда как синоним пункта и работает при следующем
-- поиске. Прямое совпадение синонима второй строки не заводит.
--
-- ЧТО ЭТО ЗА ТАБЛИЦА И ЧЕМ ОНА НЕ ЯВЛЯЕТСЯ. Здесь не методика: сами пункты,
-- процессы и вопросы в базу не переносятся (DoD блока — это справочник домена,
-- `data/checklist.csv`). Здесь то, КАК пункт называет живой человек: строка,
-- которую произнёс аудитор, и код пункта, к которому она привела. Поэтому
-- ссылки на таблицу пунктов нет и быть не может — есть код, тот самый, которым
-- связываются сущности во всём проекте (конституция, принцип 5).
--
-- Обратная сторона отсутствия ссылки названа вслух, чтобы её не приняли за
-- недосмотр: база не знает, действует ли код в издании методики, по которому
-- идёт проверка. Издание принадлежит домену и у каждой проверки своё (D063,
-- D064), поэтому проверять принадлежность кода обязан потребитель карты
-- (T285), а не эта таблица. Синоним, оставшийся от снятого пункта, просто
-- никуда не приведёт — и это правильный исход, а не тихая ошибка.
--
-- ПОЧЕМУ НЕ `translations`. Соблазн очевиден: там тоже формулировки строками
-- с языком (D025). Но `translations` отвечает на вопрос «как ЭТА сущность
-- называется на языке X» — один текст на сущность, поле и язык, и слив
-- перезаписывает его (`on conflict do update set text`). Здесь всё наоборот:
-- у одного пункта синонимов сколько угодно, ключ поиска — сама формулировка,
-- а перезапись запрещена. Общее у таблиц только слово «формулировка».
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

create table phrase_aliases (
    tenant_code text not null references tenants (code),
    lang text not null,
    phrase_normalized text not null,
    item_code text not null,
    phrase text not null,
    origin text not null default 'learned',
    created_at timestamptz not null default now(),
    -- Ключ поиска составной и начинается с арендатора: карта одного партнёра
    -- не отвечает на вопросы другого. Язык в ключе, а не рядом: «жёлтый зонт»
    -- по-русски и та же строка по-английски — два разных синонима, и
    -- совпадение написания между языками сети не должно их сливать.
    primary key (tenant_code, lang, phrase_normalized),
    -- Список источников закрыт: по нему управляющая компания однажды отберёт
    -- накопленное машиной отдельно от заведённого человеком, и неизвестный код
    -- сделал бы такой отбор неполным молча. Добавление источника — строка в
    -- этом ограничении, то есть миграция, а не случайное значение из кода.
    constraint phrase_aliases_origin_is_a_code
        check (origin in ('learned', 'manual')),
    -- Язык пишется одним написанием. Иначе «RU» и «ru» окажутся разными
    -- ключами, и карта раздвоится ровно там, где её нельзя раздваивать.
    constraint phrase_aliases_lang_is_one_spelling
        check (lang <> '' and lang = lower(btrim(lang))),
    -- Пустой ключ совпал бы с любой пустой строкой и увёл бы к случайному
    -- пункту; синоним без кода — строка, которая никуда не ведёт.
    constraint phrase_aliases_key_not_blank
        check (phrase_normalized <> ''),
    constraint phrase_aliases_item_code_not_blank
        check (btrim(item_code) <> '')
);

comment on table phrase_aliases is
    'Карта синонимов формулировок: как аудитор сказал → код пункта методики '
    '(T284, D119). Пополняется только на непрямом совпадении: прямое '
    'совпадение синонима второй строки не заводит. Методики здесь нет — '
    'только чужие слова о ней и код, к которому они привели.';
comment on column phrase_aliases.phrase_normalized is
    'Ключ поиска: обрезанные края, схлопнутые пробелы, снятая крайняя '
    'пунктуация, нижний регистр (`db.synonyms.normalize_phrase`). Правило '
    'одно на запись и на поиск — разойдись они на один знак, карта перестала '
    'бы работать молча и только на части написаний.';
comment on column phrase_aliases.phrase is
    'Как сказал человек. Для показа управляющей компании и для разбора '
    'промахов; сопоставление идёт по ключу, а связь — по item_code.';
comment on column phrase_aliases.origin is
    'Происхождение записи кодом: learned — накоплено машиной на непрямом '
    'совпадении (D119), manual — заведено человеком. Код, а не формулировка: '
    'перевод и правка слов не должны ломать отбор по источнику.';
comment on column phrase_aliases.item_code is
    'Код пункта методики. Ссылки на таблицу пунктов нет намеренно: методика '
    'живёт в домене и у каждой проверки своё издание — действует ли код, '
    'решает потребитель карты, а не база.';

-- Вопрос «как ещё называют этот пункт» задаёт управляющая компания, и он
-- обратный ключу поиска: тот начинается с формулировки, этот — с кода.
create index phrase_aliases_item_idx on phrase_aliases (tenant_code, item_code);

-- Права роли приложения: только чтение и запись новых строк.
--
-- UPDATE и DELETE не выданы намеренно, и это не забытая строка. Синоним,
-- который уже работает, не переписывается ошибкой одного аудитора и не
-- пропадает от промаха в коде: разночтение слой доступа обязан НАЗВАТЬ
-- (`synonyms.CONFLICT`), а не разрешить втихую. Свойство держит база, а не
-- дисциплина вызовов — то же правило, по которому запечатанная проверка
-- заморожена политикой, а не проверкой в коде (0004).
--
-- Обратная сторона названа вслух: убрать неверный синоним ролью приложения
-- нечем. Правка и снятие синонимов — работа управляющей компании, у неё своя
-- задача и свои права; до неё неверная строка чинится накатом, а не продуктом.
grant select, insert on phrase_aliases to dodo_audit_app;

alter table phrase_aliases enable row level security;
alter table phrase_aliases force row level security;
create policy phrase_aliases_app_access on phrase_aliases
    for all to dodo_audit_app using (true) with check (true);
