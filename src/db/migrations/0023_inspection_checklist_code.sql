-- 0023_inspection_checklist_code.sql
--
-- T345 (#262): продукт работает не с одним чек-листом, а с несколькими (D177),
-- и проверка обязана помнить, ПО КАКОМУ из них её считали.
--
-- ЗАПОЛНЕНИЕ СУЩЕСТВУЮЩИХ СТРОК — НЕ ПЕРЕПИСЫВАНИЕ ЗАДНИМ ЧИСЛОМ. До сегодня
-- чек-лист был ровно один — методика бизнес-девелопера (D181), — поэтому
-- `bizdev` у старых строк это запись того, что и так было правдой (D033), а не
-- назначение им нового смысла.
--
-- КОЛОНКА NOT NULL С УМОЛЧАНИЕМ, А НЕ NULLABLE. Проверка без кода чек-листа
-- бессмысленна: по ней нельзя ни собрать письмо, ни сравнить оценки. Пустое
-- значение здесь означало бы «не знаем, по чему проверяли», а такого состояния
-- у записанной проверки не бывает — оно бывает только у недописанного кода.
--
-- ПРО ПОРЯДОК КОЛОНОК. Разбор строки в `src/db/queries.py` позиционный, и
-- колонка дописывается В КОНЕЦ списка выборки. Вставленная в середину, она
-- сдвинула бы всё, что правее, и письмо партнёру молча напечатало бы одно
-- вместо другого — с верным на вид результатом.

alter table inspections
    add column if not exists checklist_code text not null default 'bizdev';

comment on column inspections.checklist_code is
    'Код чек-листа, по которому считали проверку (T345, D177). Пара «пространство + код» опознаёт чек-лист (D183); пространство появится вместе с ним.';
