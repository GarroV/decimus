-- 0017_unit_geography.sql
--
-- T335: у точки появляется география. До сих пор `units` знал только название
-- и код внешнего источника, поэтому вопрос «сколько у нас точек в Грузии»
-- база ответить не могла вовсе — а раздел «Страна» именно на нём и стоит.
--
-- Страна — КОДОМ, а не названием (конституция, принцип 5: формулировки
-- переводятся и правятся, коды нет). «Georgia», «Грузия» и «საქართველო» —
-- одна и та же страна, и сложить их в один срез можно только по коду.
-- Название страны словами живёт в словаре интерфейса, как и названия зон.
--
-- Город — строкой и намеренно без своего справочника: городов у сети сотни,
-- отдельная таблица под них сегодня не окупается, а срез строится по стране.
-- Когда города понадобятся как сущность, эта колонка станет ссылкой — но
-- заводить справочник заранее значило бы угадывать (YAGNI).
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

alter table units add column country text;
alter table units add column city text;

comment on column units.country is
    'Код страны ISO 3166-1 alpha-2 в ВЕРХНЕМ регистре: GE, RS, NG. Название '
    'страны словами здесь не хранится — оно переводится, а код нет. NULL для '
    'точек, заведённых по факту первой проверки: у них географии нет, пока её '
    'не проставит загрузка справочника или человек.';
comment on column units.city is
    'Город точки как он называется в источнике. Без справочника и без '
    'нормализации: сегодня это подпись рядом с точкой, а срез строится по '
    'стране.';

-- Ограничение формы, а не списка стран. Проверять принадлежность к ISO-списку
-- в базе нельзя: список меняется, а проверка молча запретила бы новую страну
-- ровно в тот день, когда сеть в неё придёт. Форма же не меняется никогда, и
-- она ловит настоящую ошибку загрузчика — положенное название вместо кода.
alter table units add constraint units_country_is_code
    check (country is null or country ~ '^[A-Z]{2}$');

-- Срез по стране — главный запрос этой колонки, и он обязан идти по индексу:
-- реестр точек сети читается с каждой страницы раздела «Страна».
create index units_country_idx on units (tenant_code, country);
