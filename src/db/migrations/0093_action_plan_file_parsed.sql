-- Файл «туда и обратно» электронного плана, шаг 3 эпика #1168 (спека
-- 2026-10-22-electronic-action-plan-design, «Файл туда и обратно»).
--
-- Версия файла помнит, разобрана ли она в строки плана: наш шаблон разбирается и его
-- строки ложатся в план, чужой файл остаётся вложением («не разобран — заполните на
-- экране»). До этой колонки метку «не разобран» ставили на каждый файл электронного плана.
-- Колонку пишет только вставка версии (таблица для приложения — только вставка), поэтому
-- значение известно до записи: разбор идёт раньше неё.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

alter table action_plan_files add column parsed boolean not null default false;

comment on column action_plan_files.parsed is
    'Файл разобран как наш шаблон электронного плана: его строки сверены с планом. Ложь — вложение, не разобранное (чужой файл, файловый план).';
