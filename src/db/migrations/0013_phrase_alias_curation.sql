-- 0013_phrase_alias_curation.sql
--
-- T292: неверный синоним снимается и переправляется — правом, а не накатом.
--
-- ЧТО ЗДЕСЬ ЧИНИТСЯ. Миграция `0012` дала роли приложения на `phrase_aliases`
-- только `select` и `insert`, и это был осознанный выбор: выученное не
-- переписывается ошибкой одного аудитора. Цена выбора была названа там же —
-- убрать неверную строку стало нечем, и она продолжала уводить поиск к чужому
-- пункту. Цена закрывается не расширением прав приложения (тогда возвращается
-- ровно то, от чего уходили), а ВТОРОЙ РОЛЬЮ: правка карты — работа
-- управляющей компании, и приходит она тем же разделением, каким приходит
-- снятие проверки из истории (`0010`, D086/D089).
--
-- ПОЧЕМУ НЕ ТРЕТЬЯ РОЛЬ, А УЖЕ ЗАВЕДЁННЫЙ `dodo_audit_admin`. Отдельная роль
-- описывала бы различие, которого у продукта нет: снимает проверки и правит
-- карту один и тот же человек управляющей компании, и приходит он одним и тем
-- же путём — инструментом MCP под кругом администраторов (`0011`). Третья
-- роль стоила бы ещё одной переменной окружения, ещё одного пароля и ещё
-- одной ветки в накате и в оснастке — ради разделения, которого никто не
-- просил. Обратная сторона названа вслух: у кого есть доступ администратора
-- истории, тот теперь правит и карту синонимов. Понадобится разделить
-- (например, куратор карты без права снимать проверки) — это миграция и
-- переменная, а не переделка слоя: подключение он берёт в одном месте.
--
-- СНЯТИЕ — ПОМЕТКА, А НЕ УДАЛЕНИЕ, и это не аккуратность ради аккуратности.
-- Удалённая строка освобождает ключ, а свободный ключ означает, что машина
-- выучит ту же формулировку заново на следующем же непрямом совпадении — с
-- тем же неверным кодом, потому что модель ошибётся так же. Снятие было бы
-- обратимо СИСТЕМОЙ, а не человеком, то есть не значило бы ничего. Оставшаяся
-- строка держит ключ первичным ключом — самым примитивным заслоном из
-- имеющихся, не политикой и не дисциплиной вызовов.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

-- --- пометка снятия -----------------------------------------------------------
--
-- Обязательность причины выражена связью двух колонок, а не `not null`: у
-- живого синонима причины нет и быть не должно. Тот же приём и то же
-- объяснение, что у снятия проверки (`0010`).

alter table phrase_aliases add column retracted_at timestamptz;
alter table phrase_aliases add column retraction_reason text;

alter table phrase_aliases add constraint phrase_aliases_retraction_has_reason
    check ((retracted_at is null) = (retraction_reason is null));

alter table phrase_aliases add constraint phrase_aliases_retraction_reason_is_not_empty
    check (retraction_reason is null or btrim(retraction_reason) <> '');

comment on column phrase_aliases.retracted_at is
    'Когда синоним сняли с работы (T292). NULL — синоним живой. Строка не '
    'удаляется: она держит свой ключ, и поэтому машина не выучит ту же '
    'формулировку заново — иначе следующий обход вернул бы ровно ту ошибку, '
    'ради которой синоним снимали.';
comment on column phrase_aliases.retraction_reason is
    'Почему синоним сняли. Обязательна ровно тогда, когда он снят: '
    'ограничение phrase_aliases_retraction_has_reason не даёт ни снятия без '
    'причины, ни причины у живого синонима. Пустая строка запрещена отдельно — '
    'она выглядела бы названной причиной, которой не прочитать.';

-- --- след правки пункта -------------------------------------------------------
--
-- Переправленный синоним обязан помнить, куда вёл раньше. Иначе разбор «что
-- машина навыучивала неверно» упирается в карту, где все строки выглядят
-- правильными: исправленные ничем не отличаются от изначально верных, а
-- `origin` по-прежнему говорит «накоплено машиной» — и говорит правду, потому
-- что строку завела именно она.
--
-- Полной истории правок тут нет намеренно: видно последнее состояние и откуда
-- в него пришли. Вторая правка перепишет след первой. Понадобится настоящая
-- история — это отдельная таблица и отдельное решение, а не ещё три колонки
-- здесь.

alter table phrase_aliases add column corrected_at timestamptz;
alter table phrase_aliases add column correction_reason text;
alter table phrase_aliases add column previous_item_code text;

-- Три колонки правки заполняются вместе или не заполняются вовсе: «исправлено,
-- но неизвестно когда» и «исправлено, но неизвестно откуда» — не состояния, а
-- следы недописанного запроса.
alter table phrase_aliases add constraint phrase_aliases_correction_is_whole
    check (
        (corrected_at is null) = (correction_reason is null)
        and (corrected_at is null) = (previous_item_code is null)
    );

alter table phrase_aliases add constraint phrase_aliases_correction_reason_is_not_empty
    check (correction_reason is null or btrim(correction_reason) <> '');

-- Правка на тот же самый код — не правка. Записанная как правка, она сделала
-- бы строку «исправленной», не исправив ничего, а `previous_item_code`
-- указывал бы сам на себя.
alter table phrase_aliases add constraint phrase_aliases_correction_changed_something
    check (previous_item_code is null or previous_item_code <> item_code);

comment on column phrase_aliases.corrected_at is
    'Когда человек переправил синоним на другой пункт (T292). NULL — пункт '
    'ставился один раз, тем, кто завёл строку.';
comment on column phrase_aliases.correction_reason is
    'Зачем переправили. Обязательна вместе с остальным следом правки: '
    'ограничение phrase_aliases_correction_is_whole не даёт заполнить след '
    'наполовину.';
comment on column phrase_aliases.previous_item_code is
    'Код пункта ДО правки — чтобы промах модели остался виден после '
    'исправления. Ссылки на таблицу пунктов здесь нет по той же причине, что '
    'у item_code: методики в базе нет вовсе.';

-- --- права администратора -----------------------------------------------------
--
-- Читает администратор карту целиком — вместе со снятыми строками, которых в
-- продуктовой выдаче нет.
grant select on phrase_aliases to dodo_audit_admin;

-- А ПИШЕТ РОВНО ШЕСТЬ КОЛОНОК, и это здесь главный заслон — тот же приём, что
-- у снятия проверки (`0010`): привилегия на КОЛОНКИ говорит именно то, что
-- нужно, и проверяется одним взглядом в `\dp`, а политика такого сказать не
-- может вовсе (`with check` видит только новую строку и не видит старой).
--
-- Неприкосновенны при этом ровно те колонки, ради которых всё затевалось:
-- арендатор, язык и ключ поиска (ключ карты не переезжает: переехав, он увёл
-- бы к другой строке всё, что на неё ссылалось), сказанное человеком дословно
-- (показание не правится — по нему управляющая компания разбирает промахи),
-- происхождение (кто завёл строку, правкой не меняется) и время заведения.
grant update (
    item_code, retracted_at, retraction_reason,
    corrected_at, correction_reason, previous_item_code
) on phrase_aliases to dodo_audit_admin;

-- Ни INSERT, ни DELETE администратору не выдано. Заводит синонимы приложение
-- (машина на непрямом совпадении, D119), а удалять строки в этой базе не
-- умеет никто: снятие — пометка.

-- Разрешающая политика `0012` выдана `to dodo_audit_app`, то есть на вторую
-- роль не действует, а с включённым RLS и без единой разрешающей политики не
-- проходит НИЧЕГО. Поэтому администратору нужны свои — и они уже, чем у
-- приложения: чтение плюс правка, без заведения строк.
create policy phrase_aliases_admin_reads on phrase_aliases
    for select to dodo_audit_admin using (true);
create policy phrase_aliases_admin_curates on phrase_aliases
    for update to dodo_audit_admin using (true) with check (true);

-- ПОЧЕМУ СНЯТЫЕ СТРОКИ НЕ СПРЯТАНЫ ОТ РОЛИ ПРИЛОЖЕНИЯ политикой, как спрятана
-- снятая проверка (`inspections_retracted_are_admin_only`). Спрятанная строка
-- всё равно держала бы ключ — уникальность проверяется независимо от
-- видимости, — и запись машины упиралась бы в неё молча: `on conflict do
-- nothing` не вставил бы ничего, а следующий за ним `select` не увидел бы
-- причины. Слой не смог бы отличить «формулировка снята» от «строка пропала
-- между двумя запросами» и ответил бы вызывающему ошибкой целостности на
-- совершенно законном исходе. Поэтому снятую строку роль приложения ВИДИТ, а
-- из поиска и из карты её убирает запрос слоя (`synonyms.py`), и это названо
-- здесь, чтобы отсутствие политики не приняли за недосмотр. Заслон, ради
-- которого всё делалось, держится не видимостью, а тем, что у роли
-- приложения нет ни UPDATE, ни DELETE: снять пометку и переписать код она не
-- может ни при какой видимости.
