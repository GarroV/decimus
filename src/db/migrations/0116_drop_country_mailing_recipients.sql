-- 0116_drop_country_mailing_recipients.sql
--
-- Особый список «Кому» страны (`0112`) снят: адресаты предписаний и экшн-планов
-- берутся из общего списка рассылки страны (`country_contacts`, вид `mailing`),
-- который правят по одному адресу. Письмо по-прежнему отправляет человек, список
-- лишь подставляет «Кому». На проде таблица пуста (сверено), данных не теряем.
drop table if exists country_mailing_recipients;
