-- 0021_web_user_email.sql
--
-- T332 (#308): вход через учётку Google опознаёт человека по почте.
--
-- Google не знает наших логинов. После согласия он возвращает почту — и это
-- единственное, по чему можно найти, кого пустили. Поэтому почта появляется
-- у учётки раньше самого входа: пока её негде хранить, кнопка «Войти через
-- Google» опознавать некого.
--
-- ПОЧТА НЕ ЗАМЕНЯЕТ ЛОГИН, А ЛОЖИТСЯ РЯДОМ. Пароль остаётся запасным входом
-- (D163): у партнёра почта может оказаться не гугловой, и отнимать у него
-- единственную дверь ради красоты схемы нельзя. Поэтому колонка nullable —
-- учётка без почты законна и входит паролем, как входила.
--
-- НЕЗНАКОМАЯ ПОЧТА — ОТКАЗ, А НЕ ЗАВЕДЕНИЕ УЧЁТКИ. Схема этого не решает, но
-- она делает решение возможным: раз почта хранится у существующей строки,
-- вход обязан сперва найти строку. Автозавод по факту входа означал бы, что
-- круг допущенных задаёт Google, а не владелец.
--
-- ХРАНИМ НОРМАЛИЗОВАННОЕ. Google отдаёт почту в том виде, в каком её завели,
-- и `Ivan@Dodobrands.io` с `ivan@dodobrands.io` — один человек. Если пустить
-- в базу обе формы, один и тот же человек заведётся дважды, а войдёт как
-- кто-то один — и какой именно, будет зависеть от порядка строк. Поэтому
-- ограничение требует уже приведённую строку: приводит вызывающий код, а
-- база не даёт ему забыть.
--
-- УНИКАЛЬНОСТЬ — В ПРЕДЕЛАХ АРЕНДАТОРА, как и всё остальное здесь. Один
-- человек может быть заведён у двух арендаторов законно; чего быть не может,
-- так это двух строк с одной почтой у одного арендатора — тогда опознание
-- стало бы выбором из двух, а выбирать не из чего.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

alter table web_users
    add column email text
        check (email is null or (email = lower(btrim(email)) and email <> ''));

comment on column web_users.email is
    'Почта для входа через учётку Google (T332). Хранится нормализованной '
    '(lower + btrim). NULL — учётка входит только паролем, это законно. '
    'Круг допущенных задаёт владелец: незнакомая почта получает отказ, '
    'а не заводит учётку.';

create unique index web_users_email_uq
    on web_users (tenant_code, email) where email is not null;

-- Читает приложение: `grant select on web_users` из 0014 дан на таблицу
-- целиком и новую колонку покрывает сам. Роли обслуживания права выданы
-- поколоночно (0020), поэтому почту ей нужно назвать отдельно — иначе экран
-- «Люди» не увидит колонки и не сможет её проставить.
grant select (email) on web_users to dodo_audit_admin;
grant insert (email) on web_users to dodo_audit_admin;
grant update (email) on web_users to dodo_audit_admin;
