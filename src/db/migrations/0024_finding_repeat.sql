-- 0024_finding_repeat.sql
--
-- #359 (D191): повтор нарушения стоит вдвое, и проверка обязана помнить, какая
-- запись была засчитана как повтор.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ВЫЧИСЛЕНИЕ ПО ИСТОРИИ. Совпадение кода с предыдущей
-- проверкой — это НАБЛЮДЕНИЕ, а удвоение цены — РЕШЕНИЕ АУДИТОРА, принятое на
-- точке. Считать второе из первого значит назначать цену догадкой: тот же код
-- мог относиться к другому объекту, а исправленное и снова сломавшееся
-- нарушение отличается от неисправленного. Поэтому пометка хранится как факт
-- проверки, рядом с самой записью.
--
-- NOT NULL С УМОЛЧАНИЕМ `false`. Пустое значение означало бы «не знаем, был ли
-- это повтор», а такого состояния у записанной проверки не бывает: аудитор
-- либо отметил повтор, либо нет. Строки, слитые до этой миграции, читаются как
-- «не отмечено» — это запись того, что и так было правдой: отметить их было
-- нечем.
--
-- ПРО ПОРЯДОК КОЛОНОК. Разбор строки в `src/db/queries.py` позиционный, и
-- колонка дописывается В КОНЕЦ списков выборки. Вставленная в середину, она
-- сдвинула бы всё, что правее, и отчёт партнёру напечатал бы одно вместо
-- другого — с верным на вид результатом (см. 0023).
--
-- Права на таблицу выданы целиком (0004, `grant … on findings`), поэтому
-- отдельного гранта колонке не требуется.

alter table findings
    add column if not exists repeat boolean not null default false;

comment on column findings.repeat is
    'Аудитор отметил запись как повтор нарушения предыдущей проверки: вычет удвоен (D191, #359). Умолчание false — «не отмечено», а не «неизвестно».';
