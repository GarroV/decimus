-- 0015_web_login_attempts.sql
--
-- T325, решения D154 и D155: перебор пароля на форме входа перестаёт быть
-- бесплатным.
--
-- ЧТО БЫЛО. Вход появился (`0014`), а ограничителя попыток не было: форма
-- принимала пароли подряд с одного адреса столько раз, сколько их успевали
-- прислать. Пока админка слушает петлю, перебирать её может только тот, кто
-- уже на машине; владелец решил открыть её другим людям (D154), и до
-- публикации между посторонним и историей проверок сети стоит ровно один
-- пароль.
--
-- ЧТО ПОЯВЛЯЕТСЯ. Одна таблица счётчиков: сколько неудач подряд пришло с
-- этого адреса и сколько — на этот логин. Запрет из неё не хранится, а
-- СЧИТАЕТСЯ (`src/db/web_throttle.py`): срок запрета — это функция от числа
-- неудач и времени последней, и второй записи того же факта в схеме не
-- заводится. Разошедшиеся «счётчик говорит одно, а колонка запрета другое» —
-- это ровно тот вид расхождения, который не виден до разбора инцидента.
--
-- ПОЧЕМУ В БАЗЕ, А НЕ В ПАМЯТИ ПРОЦЕССА. Счётчик в памяти обнуляется при
-- перезапуске, а перезапуск здесь случается сам: выкладка, перезагрузка
-- домашнего сервера, падение контейнера. Ограничитель, которого нет ровно в
-- эти минуты, выглядит работающим всё остальное время. Тот же довод и то же
-- решение, что у сессий в `0014`: держать в браузере (или в процессе) можно
-- то, чью потерю мы согласны не заметить.
--
-- ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО.
--
--   * Ни логина, ни адреса в открытом виде — только отпечаток SHA-256. Это не
--     тайна (и логин, и адрес перебираются по отпечатку за секунды), а две
--     вещи попроще: длина строки перестаёт зависеть от того, что прислал
--     посторонний, и в базу не попадает дословно то, что человек ввёл в поле
--     «логин», — а туда регулярно вводят пароль от соседней системы.
--   * Внешнего ключа на `tenants` нет. Неудачная попытка бывает и на стенде,
--     где тенанта в справочнике ещё нет вовсе, и ключ превратил бы её в отказ
--     базы, то есть в пятисотую страницу вместо «логин или пароль не подошли».
--   * RLS нет: сказать ею здесь нечего. В `0014` она держала односторонность
--     закрытия сессии, а у счётчика односторонних переходов нет — успешный
--     вход обязан его обнулять. Разрешающая политика поверх привилегий не
--     добавила бы ни одного запрета, зато добавила бы строчку, над смыслом
--     которой ломал бы голову следующий читатель.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

create table web_login_attempts (
    -- Чей стенд. Границу арендаторов счётчик не ослабляет и не усиливает:
    -- она уже стоит на учётке, — но запирать вход соседнему тенанту из-за
    -- перебора в этом было бы ошибкой формы данных (принцип 6 конституции).
    tenant_code text not null,
    -- Что именно считается: адрес, с которого пришли, или логин, в который
    -- целятся. Два счётчика нужны оба и по разным причинам: по логину ловится
    -- перебор с меняющихся адресов, по адресу — перебор по разным логинам.
    scope text not null check (scope in ('address', 'login')),
    -- ОТПЕЧАТОК ключа, а не ключ. Та же колонка и то же ограничение, что у
    -- `web_sessions.fingerprint` в `0014`: 64 знака шестнадцатеричной записи
    -- даёт только SHA-256, поэтому «записали то, что ввёл человек» — отказ
    -- записи, а не строка в базе.
    key_fingerprint text not null check (key_fingerprint ~ '^[0-9a-f]{64}$'),
    -- Неудач подряд. Ноль не хранится: обнулить счётчик — значит удалить
    -- строку, и «нет строки» с «ноль неудач» не разъезжаются.
    failures integer not null check (failures > 0),
    -- Когда пришла последняя неудача. Отсюда считается и запрет (последняя
    -- неудача + срок по числу неудач), и забвение счётчика.
    updated_at timestamptz not null default now(),
    -- Ключ естественный: одна строка на «тенант + что считаем + чей отпечаток».
    -- Суррогатный `id` здесь был бы вторым способом назвать ту же строку.
    primary key (tenant_code, scope, key_fingerprint)
);

-- Строки выбрасываются по возрасту, а не по расписанию: чистка идёт тем же
-- запросом, что и запись неудачи (`src/db/web_throttle.py`). Без индекса эта
-- чистка читала бы таблицу целиком на каждой неудачной попытке — то есть
-- ровно на том потоке запросов, ради которого таблица и заведена.
create index web_login_attempts_stale_idx on web_login_attempts (updated_at);

comment on table web_login_attempts is
    'Счётчик неудачных входов в админку (T325): по адресу и по логину. '
    'Хранятся ОТПЕЧАТКИ ключей, срок запрета не хранится, а считается по '
    'числу неудач (src/db/web_throttle.py). Строки старше срока забвения '
    'удаляются попутно, при следующей неудачной попытке.';
comment on column web_login_attempts.failures is
    'Неудач подряд. Успешный вход строку удаляет; ноль в ней не хранится.';

-- --- права -------------------------------------------------------------------
--
-- Здесь роль приложения обязана уметь больше, чем на учётках: счётчик — это
-- её рабочая запись, а не чужая тайна. Опасного в этих правах нет: вся
-- таблица целиком восстанавливается следующей неудачной попыткой, а сведений
-- о том, кто здесь заведён, в ней не лежит.

grant select, insert, delete on web_login_attempts to dodo_audit_app;

-- ПРАВИТЬ МОЖНО ДВЕ КОЛОНКИ — счётчик и время. Тот же приём, что у
-- `web_sessions` в `0014`. Чем закрыто по существу: переписать `scope` или
-- `key_fingerprint` у живой строки нельзя, то есть накопленные неудачи
-- нельзя переставить с чужого ключа на свой (или наоборот — повесить свои на
-- чужой логин и тем запереть вход человеку).
grant update (failures, updated_at) on web_login_attempts to dodo_audit_app;
