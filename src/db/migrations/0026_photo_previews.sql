-- 0026_photo_previews.sql
--
-- D218: у записи в карточке проверки видны прикреплённые кадры — сжатой
-- копией, «не в максимальном качестве, а в достаточном, чтоб было видно».
-- Сжатая копия хранится НАВСЕГДА; удаление по D202/D213 касается оригиналов.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ТАБЛИЦА. У кадра одна копия для показа, и живёт она
-- ровно столько, сколько строка кадра. Ссылка пишется той же командой, что и
-- ссылка на оригинал (`upload_photos`), пока `uploaded_at` пуст: политика
-- `photos_uploaded_only_once` после этого замораживает строку целиком, и
-- подменить копию задним числом нельзя тем же заслоном, что и оригинал.
--
-- Форма ссылки та же, что у оригинала: `s3://корзина/ключ`, без адреса сервера
-- — хранилище переедет с MUSPELHEIM (D213), и переезд обязан стоить правки
-- переменных окружения, а не каждой строки.

alter table photos add column preview_path text;

comment on column photos.preview_path is
    'Сжатая копия кадра для показа в админке (D218), s3://корзина/ключ. '
    'Хранится навсегда; оригинал удаляется по D202/D213. Пусто — кадр выгружен '
    'до D218 или ещё не выгружен.';
