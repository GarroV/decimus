-- 0089_inspection_edits_delete.sql
--
-- Журнал правок на приёмке (0081) принимает и снятие записи (#1164): владелец
-- 21.10.2026 — «добавь в проверки, которые на вычитке, возможность удаления
-- каких-то пунктов, потому что могли нечаянно занести не то». Снятие пишется
-- тем же журналом и той же транзакцией, что исправление и добавление: кто, когда,
-- какая запись была (`changes` — прежние значения полей, новые пусты) и оценка
-- до и после.
--
-- Меняется только список допустимых видов правки. Прав роли приложения это не
-- трогает: журнал по-прежнему только дописывается, а `delete` на `findings` ей
-- выдан в 0004 и закрыт для принятой проверки политиками заморозки.
--
-- Раннер оборачивает файл в одну транзакцию сам.

alter table inspection_edits drop constraint inspection_edits_kind_check;
alter table inspection_edits
    add constraint inspection_edits_kind_check check (kind in ('revise', 'add', 'delete'));
