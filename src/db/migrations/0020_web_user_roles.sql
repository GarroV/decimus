-- 0020_web_user_roles.sql
--
-- T338 (#322): учётками управляют из админки, а не из командной строки.
--
-- Сегодня завести человека можно только командой на машине, где лежит
-- репозиторий (`tools/web_user.py`). Владелец попросил делать это с экрана —
-- и как только заведение переезжает в веб, немедленно встаёт вопрос, которого
-- в командной строке не было: КТО ИМЕННО может заводить. В терминал ходит
-- команда проекта, а в админку — все, кому её открыли.
--
-- Без роли ответ был бы «любой вошедший», то есть аудитор, открывший админку
-- посмотреть свою проверку, мог бы завести себе вторую учётку или отключить
-- чужую. Поэтому роль появляется ВМЕСТЕ с экраном, а не «потом, когда
-- понадобится»: потом — это уже после того, как кто-то воспользовался.
--
-- ЧТО РОЛЬ НЕ ЗНАЧИТ. Она не про то, чью историю видно: за это отвечает
-- арендатор (`tenant_code`), и роль его не расширяет. Админ чужого арендатора
-- остаётся без доступа к чужой истории ровно так же, как аудитор.
--
-- ПОЧЕМУ ПО УМОЛЧАНИЮ `auditor`, А НЕ `admin`, И ПОЧЕМУ НИКОМУ НЕ РАЗДАЁТСЯ
-- ЗАДНИМ ЧИСЛОМ. Кто заведён в бою — у каждого стенда своё, и миграция этого
-- не знает. Раздать всем `admin` значило бы тихо выдать права людям, которых
-- никто на это не смотрел; раздать «по имени `director`» — угадать. Поэтому
-- накат НЕ даёт прав никому, а первый админ назначается явной командой
-- (`make web-user ARGS="role <логин> admin"`). Экран до этого никому не
-- откроется — и это верное поведение: пустой доступ чинится одной командой,
-- лишний доступ не чинится ничем.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

alter table web_users
    add column role text not null default 'auditor'
        check (role in ('auditor', 'admin'));

comment on column web_users.role is
    'Что человеку можно В АДМИНКЕ: auditor — работать со своей историей, '
    'admin — вдобавок заводить и отключать учётки. Чью историю видно, '
    'решает не роль, а арендатор (tenant_code).';

-- Приложение роль ЧИТАЕТ (она приезжает вместе с опознанием), но не пишет:
-- `grant select` на таблицу у него уже есть с 0014, и расширять его нельзя —
-- заслон D155 держится именно тем, что приложение физически не может тронуть
-- строку учётки. Заведение и отключение идут под ролью администратора, как
-- снятие проверки (0010): повышенное действие требует отдельного
-- подключения, которого у обычного процесса просто нет.
-- ПРАВА ВЫДАНЫ КОЛОНКАМИ, А НЕ ТАБЛИЦЕЙ. У администратора истории с `0016`
-- есть чтение ровно трёх колонок учётки, и `password_hash` в их число не
-- входит намеренно. Табличный `grant select` добавил бы ему свёртки паролей
-- заодно — расширение доступа, за которым никто бы не следил, потому что
-- выглядит оно как обычная строка гранта.
grant select (login, tenant_code, disabled_at, role, created_at) on web_users
    to dodo_audit_admin;

-- Вставка — тоже колонками: перечислено ровно то, что заполняет заведение
-- учётки. Табличный insert разрешил бы писать и `id`, и `created_at`, то есть
-- заводить строку задним числом.
grant insert (tenant_code, login, password_hash, role) on web_users
    to dodo_audit_admin;

-- Пишет администратор ровно две колонки: отключение и роль. Пароля здесь нет
-- и не будет — смена чужого пароля это вход под чужим именем. Забыл пароль —
-- учётка отключается и заводится заново, след остаётся в обеих строках.
grant update (disabled_at, role) on web_users to dodo_audit_admin;

