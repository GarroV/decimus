-- 0055_maps_ratings_index.sql
--
-- Индекс под выборки «последняя оценка филиала на карте» (`maps_store.latest`)
-- и «оценка пиццерии на карте на дату» (`maps_store.unit_scores`).
--
-- `maps.ratings` копит снимок дня на пару (филиал, карта): 107 тыс. строк на
-- 12.10.2026 и растёт на ~400 в сутки. Обе выборки брали `distinct on` по всей
-- таблице: полный проход ради ~380 ответных строк, 135–147 мс каждая, а
-- страница «Рейтинги» зовёт `latest` дважды. Теперь запросы идут «пара за
-- парой»: по одной последней записи на (филиал, карта) через `lateral ...
-- limit 1`. Для филиал-карта хватает первичного ключа, а вот перечень карт
-- (`select provider_id ... > prev`) — прыжки по значениям `provider_id` — без
-- индекса с `provider_id` впереди снова читает таблицу целиком.
--
-- Замер на данных по форме прода (115 тыс. строк, 394 пары): `latest` 130–170 →
-- 4–6 мс, `unit_scores` 135–155 → 1,5 мс.
--
-- Обычный `create index`, не `concurrently`: раннер оборачивает файл в одну
-- транзакцию, а `concurrently` в ней нельзя. Таблица ~14 МБ, сборка занимает
-- доли секунды; загрузка оценок ждёт суточную, и запись на это время не нужна.

create index if not exists ratings_provider_company_date_idx
    on maps.ratings (provider_id, company_uuid, on_date desc);
