-- 0019_partner_letters.sql
--
-- T333 (#310): правленое письмо партнёру перестаёт исчезать.
--
-- Сегодня письмо пересобирается движком при каждом открытии экрана, и правка
-- человека живёт ровно до ухода со страницы. Экран при этом ведёт себя как
-- редактор — и это худший вид молчаливой потери: человек правит текст, не
-- понимая, что правка никуда не денется. Владелец увидел это первым же
-- взглядом на живой стенд: «сейчас я не понимаю как сохранить».
--
-- D035 говорит, что история писем живёт в системе. Без этой таблицы ответить
-- «что именно мы отправили партнёру» нечем, а партнёр считает отправленное
-- фактом и будет прав.
--
-- ПОЧЕМУ ТЕКСТ В БАЗЕ, А НЕ ФАЙЛ В ХРАНИЛИЩЕ, как отчёт (0018). Отчёт —
-- готовый документ, он не правится и весит мегабайты. Письмо — несколько
-- килобайт текста, который человек правит, перечитывает и ищет; ради него
-- ходить в хранилище значит платить сетевым запросом за то, что лежит в
-- соседней строке. Форма разная, потому что разная и вещь.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

create table partner_letters (
    id uuid primary key default gen_random_uuid(),
    inspection_id uuid not null references inspections(id) on delete cascade,

    -- Текст письма ТАК, КАК ЕГО ЗАФИКСИРОВАЛ ЧЕЛОВЕК. Не заготовка движка и не
    -- её пересказ: смысл записи в том, что она совпадает с ушедшим партнёру.
    body text not null check (length(btrim(body)) > 0),

    -- Язык письма — третий язык продукта, свой у каждого партнёра и не равный
    -- языку интерфейса того, кто письмо готовил (`CLAUDE.md`: язык — параметр,
    -- никогда не константа).
    lang text not null,

    -- Кто зафиксировал. Учётка админки, а не имя строкой: имена меняются, а
    -- вопрос «кто это отправил» задают через год.
    saved_by text not null,

    created_at timestamptz not null default now()
);

create index partner_letters_by_inspection on partner_letters (inspection_id, created_at desc);

comment on table partner_letters is
    'Письмо партнёру, зафиксированное человеком (T333, D035). Заготовку '
    'по-прежнему собирает движок; сюда попадает только то, что человек '
    'подтвердил как отправляемое — «модель предлагает, фиксирует человек».';
comment on column partner_letters.body is
    'Текст в том виде, в каком его зафиксировал человек. Показывается вместо '
    'пересборки: пересобранное письмо могло бы разойтись с тем, что у '
    'партнёра на руках, и разошлось бы молча.';

alter table partner_letters enable row level security;
alter table partner_letters force row level security;
create policy partner_letters_app_access on partner_letters
    for all to dodo_audit_app using (true) with check (true);

-- Зафиксированное письмо заморожено — как кадр (0004) и как отчёт (0018).
-- Передумал — фиксируется НОВОЕ письмо, и обе записи видно: история на то и
-- история, что из неё нельзя вынуть отправленное.
create policy partner_letters_frozen_once_written on partner_letters
    as restrictive for update
    using (false);

grant select, insert on partner_letters to dodo_audit_app;
grant select on partner_letters to dodo_audit_admin;
