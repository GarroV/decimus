-- 0022_web_password_change.sql
--
-- T340 (#323): паролю учётки нужна смена.
--
-- До этой миграции пароль не менялся ничем: `tools/web_user.py` умеет завести,
-- отключить, перечислить и назначить роль, а сменить пароль — нет. Ротация
-- была возможна только заведением второй учётки с отключением первой, то есть
-- человек менял заодно и логин, а в перечне копились отключённые строки.
--
-- Цена этого пробела названа прямо: временный пароль стенда остаётся
-- временным навсегда, потому что заменить его нечем.
--
-- ПОЧЕМУ ПРАВО ДАЁТСЯ РОЛИ ОБСЛУЖИВАНИЯ, А НЕ ПРИЛОЖЕНИЮ. Пароль здесь меняет
-- команда с машины, а не страница: у роли приложения (`dodo_audit_app`) на
-- `web_users` по-прежнему только чтение, и пробитое приложение переписать
-- пароль не может. Смена пароля С ЭКРАНА — отдельная задача (#324), и там
-- право не выдаётся тем же движением: вопрос «кому можно писать хеш» решается
-- под неё отдельно.
--
-- ЗАКРЫТИЕ СЕССИЙ — ЧАСТЬ СМЕНЫ, А НЕ ДОБАВКА. Пароль меняют в ответ на «его
-- кто-то узнал»; если открытые по старому паролю сессии продолжают работать,
-- смена не выгоняет того, ради кого её делали. Роли обслуживания нужно право
-- закрывать их, поэтому оно выдаётся здесь же.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

grant update (password_hash) on web_users to dodo_audit_admin;

grant select (id, user_id, closed_at, expires_at) on web_sessions to dodo_audit_admin;
grant update (closed_at) on web_sessions to dodo_audit_admin;
