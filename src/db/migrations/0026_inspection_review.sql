-- 0026_inspection_review.sql
--
-- Этап приёмки (D199). До сих пор проверка знала два состояния: `draft` —
-- собирается внутри транзакции слива, `finalized` — запечатана. Слив бота
-- проходил оба за одну транзакцию, то есть проверка попадала в историю сети в
-- ту же секунду, когда аудитор дошёл до последнего пункта.
--
-- Решение владельца: между обходом и историей стоит человек. Проверка после
-- слива ждёт вычитки, её записи до подтверждения правятся (ошибка «грязный пол
-- в горячем цехе вместо зала» чинится здесь, а не снятием проверки), и лишь
-- подтверждение делает её частью истории.
--
-- Поэтому вводится третье значение — `review`. Запретов под него писать не
-- нужно: заслоны миграции 0004 сформулированы как `status <> 'finalized'`,
-- значит `review` правится ровно так же, как `draft`, а запечатанной остаётся
-- только принятая проверка. Это и было причиной писать заслон через «что
-- нельзя трогать», а не перечислением того, что можно.

alter table inspections drop constraint inspections_status_known;

alter table inspections add constraint inspections_status_known
    check (status in ('draft', 'review', 'finalized'));

comment on column inspections.status is
    'draft — проверка собирается в базе (внутри транзакции слива); '
    'review — слита и ждёт вычитки: записи правятся, в историю сети она ещё '
    'не входит; '
    'finalized — принята человеком и запечатана, дальше её нельзя ни '
    'переписать, ни удалить, ни дополнить. Дорога одна: '
    'draft → review → finalized; выход из finalized закрыт политиками '
    'миграции 0004, а не соглашением.';

-- Кто и когда принял. Это не украшение журнала: подтверждение — действие
-- человека, и через месяц вопрос «кто пустил эту проверку в историю» задаётся
-- партнёром, а не разработчиком. Отдельная таблица не заводится: у принятия
-- нет истории правок, оно случается один раз и навсегда.
alter table inspections add column accepted_at timestamptz;
alter table inspections add column accepted_by text;

comment on column inspections.accepted_at is
    'Когда проверку приняли после вычитки. NULL — ещё не принята.';
comment on column inspections.accepted_by is
    'Кто принял: логин учётки админки. NULL — ещё не принята.';
