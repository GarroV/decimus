-- 0016_web_unlock.sql
--
-- T328, решение D158: запертый вход открывается не только временем.
--
-- ЧТО БЫЛО. Ограничитель перебора (`0015`) запирает вход после серии неудач, и
-- снять запрет было нечем: он проходил сам, по времени. Разбор безопасности на
-- приёмке T325 показал цену такого устройства. Логины здесь короткие и
-- предсказуемые, круг узкий; посторонний, знающий логин администратора, держит
-- его запертым сколь угодно долго — достаточно одной неудачной попытки раз в
-- ~70 минут, чтобы счётчик не успевал забыться. ПАРОЛЬ ДЛЯ ЭТОГО НЕ НУЖЕН
-- ВОВСЕ. Пока админка слушает петлю, это внутреннее дело; после публикации
-- наружу (D154, D156) цена атаки падает до «знать логин».
--
-- ЧТО ПОЯВЛЯЕТСЯ. Права, которыми снимает запрет РОЛЬ АДМИНИСТРАТОРА ИСТОРИИ —
-- та же, что снимает проверку (`0010`). Новых таблиц и колонок нет: снятие
-- запрета — это удаление строки счётчика, и второго способа записать тот же
-- факт здесь не заводится.
--
-- ПОЧЕМУ ЭТА РОЛЬ, А НЕ РОЛЬ ПРИЛОЖЕНИЯ (D158). Снятие запрета по смыслу того
-- же рода, что снятие проверки: это действие человека из команды, а не шаг
-- продуктового сценария. У роли администратора уже есть своё подключение
-- (`DATABASE_RETRACTION_URL`), которое живёт отдельно от подключения
-- приложения, и команда снятия берёт его, а не строку приложения.
--
-- ЧЕГО ЭТИ ПРАВА НЕ ДЕЛАЮТ И НЕ МОГУТ СДЕЛАТЬ. Они не отбирают у роли
-- приложения её собственный `delete` на счётчике (`0015`): он ей нужен, чтобы
-- обнулять счётчик при удачном входе и выбрасывать старые строки. То есть
-- «роль приложения не снимает запреты» — это утверждение о КОДЕ (в админке нет
-- такого пути), а не запрет базы, и выдавать его за запрет базы нельзя.
-- Заслон базы здесь другой и стоит на `0015`: переставить накопленные неудачи
-- с чужого ключа на свой нельзя ни одной роли, потому что права на правку
-- `key_fingerprint` нет ни у кого.

-- Читать счётчик — чтобы показать человеку, кто заперт и насколько. Удалять —
-- это и есть снятие запрета: срок в базе не хранится, он считается по числу
-- неудач и времени последней (`src/db/web_throttle.py`), поэтому «снять
-- запрет» и «забыть неудачи» — одно и то же действие, а не два.
--
-- INSERT и UPDATE не выдаются намеренно: роль, которая может ДОБАВИТЬ неудачи
-- чужому логину, умеет запирать вход человеку — а это ровно та беда, от
-- которой заведена эта миграция, только изнутри.
grant select, delete on web_login_attempts to dodo_audit_admin;

-- Учётки читаются ТОЛЬКО ТРЕМЯ КОЛОНКАМИ, и `password_hash` в их число не
-- входит. Зачем вообще: в счётчике лежат отпечатки, а не логины, и без списка
-- заведённых учёток команда «показать, кто заперт» печатала бы столбец
-- шестнадцатеричных строк, по которому нельзя понять, заперт ли директор.
-- Инструмент считает отпечаток каждого известного логина и сопоставляет — то
-- есть узнаёт СВОИХ, а чужой отпечаток так и остаётся нерасшифрованным.
--
-- Табличного `select` здесь нет намеренно: он выдал бы вместе с логинами и
-- свёртки паролей, а роли администратора истории они не нужны ни для чего.
grant select (login, tenant_code, disabled_at) on web_users to dodo_audit_admin;
