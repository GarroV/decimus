-- 0093_ratings_rko_service_marks.sql
--
-- «Дисквалифицировать пиццу» в фото-проверке РКО — не нарушение, а служебная
-- пометка контроля: отчёт ресторана не идёт в пул баллов по продукту. С этой
-- миграции загрузка её не пишет (`src/ratings/model.py: RKO_SERVICE_MARKS`);
-- здесь убирается то, что уже легло раньше, и стартовое хард-правило из 0039,
-- которое выводило пометку в блок «Хард-нарушения».
--
-- Сравнение — как у загрузки: без учёта регистра, лишних пробелов и хвостовой
-- пометки автодетекции (ML)/(ИИ)/(AI). Проверки РКО остаются: уходит только
-- строка пометки.
--
-- Раннер оборачивает файл в одну транзакцию сам.

-- lower() по кириллице зависит от локали базы, поэтому формулировка Dodo IS
-- сверяется ещё и как есть.
delete from ratings.violations
 where rating_type = 'rko'
   and btrim(regexp_replace(
           regexp_replace(text, '\s+', ' ', 'g'),
           '\s*\((ML|ИИ|AI)\)\s*$', ''
       )) in ('Дисквалифицировать пиццу', 'дисквалифицировать пиццу')
    or rating_type = 'rko'
   and lower(btrim(regexp_replace(
           regexp_replace(text, '\s+', ' ', 'g'),
           '\s*\((ML|ИИ|AI)\)\s*$', ''
       ))) = 'дисквалифицировать пиццу';

delete from ratings.hard_rules
 where rating_type = 'rko'
   and (btrim(pattern) in ('Дисквалифицировать пиццу', 'дисквалифицировать пиццу')
        or lower(btrim(pattern)) = 'дисквалифицировать пиццу');
