-- 0102_ratings_layout_d658_order.sql
--
-- D658: порядок блоков «Рейтингов» по ярусам — верхний «Средний», «Нарушения»,
-- «Top-10»; средний «Оценки клиентов», «Карты», «Агрегаторы», «Стабильно ниже»;
-- нижний «Хард», «Сравнение». 0101 вставил `clients` перед самым ранним блоком
-- среднего яруса, и на свежей базе (демо собирается из миграций каждый час)
-- остался прежний порядок «агрегаторы, риск, карты». Видимость не меняется.
--
-- Раннер оборачивает файл в одну транзакцию сам.

update ratings.layout l
   set position = v.p, updated_by = 'migration 0102'
  from (values ('scores', 0), ('violations', 1), ('top', 2), ('clients', 3), ('maps', 4),
               ('aggregators', 5), ('risk', 6), ('hard', 7), ('compare', 8)) v(b, p)
 where l.block = v.b;
