-- 0014_web_accounts.sql
--
-- T323, решения D154 и D155: у веб-админки появляется вход.
--
-- ЧТО БЫЛО. Входа не было вовсе. Админка слушала петлю и наружу не выходила
-- (`src/web/config.py` отказывается подниматься на непетлевом адресе) — то
-- есть единственной защитой истории проверок сети была недоступность адреса.
-- Владелец решил открыть админку другим людям (D154), и до публикации
-- обязано появиться опознание человека (D155).
--
-- ЧТО ПОЯВЛЯЕТСЯ. Две таблицы: учётки и открытые по ним сессии.
--
-- ГЛАВНОЕ СВОЙСТВО ПЕРВОЕ: РОЛЬ ПРИЛОЖЕНИЯ УЧЁТКИ НЕ ТРОГАЕТ. Она их только
-- ЧИТАЕТ — ровно настолько, чтобы сверить пароль. Завести учётку, сменить
-- чужой пароль, отключить или удалить её она не может: у неё нет таких прав,
-- и это не «в коде не предусмотрено», а отказ базы. Учётки заводит роль
-- владельца — та же, что накатывает схему (`DATABASE_ADMIN_URL`), и тем же
-- способом, что разовые работы обслуживания у соседнего продукта сети.
-- Разделение то же, что у снятия проверок в `0010`: продукт работает одной
-- ролью, а необратимое делается другой.
--
-- ГЛАВНОЕ СВОЙСТВО ВТОРОЕ: НИ ПАРОЛЯ, НИ СЕССИОННОГО ТОКЕНА В БАЗЕ НЕТ. От
-- пароля остаётся хеш с солью (scrypt), от токена — отпечаток SHA-256, и обе
-- колонки держат форму ограничением, а не договорённостью в коде. Приём взят
-- у токенов MCP (`0011`) целиком: попытка записать значение вместо свёртки
-- падает отказом на первой же записи, а не живёт до чужого взгляда в базу.
--
-- Новой роли здесь не заводится. Четвёртая копия приёма «своя роль под своё
-- необратимое действие» не нужна: владелец схемы уже существует, и заведение
-- учётки — работа ровно его класса.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

-- --- учётки ------------------------------------------------------------------
--
-- Круг узкий и плоский: сотрудники управляющей компании, которых заводит
-- команда проекта. Регистрации снаружи нет, приглашений нет, ролей нет —
-- система прав это отдельная задача, а не то, что тихо появляется вместе с
-- первой таблицей (та же оговорка, что в `0011`).

create table web_users (
    id uuid primary key default gen_random_uuid(),
    -- Чью историю видит этот человек. Арендатор у учётки обязателен: вход не
    -- даёт доступа к чужому тенанту, и держится это тем, что опознание ищет
    -- строку по паре «арендатор + логин», а не по одному логину.
    tenant_code text not null references tenants (code),
    login text not null,
    -- ХЕШ, а не пароль. Форма проверяется ограничением: `scrypt$n$r$p$соль$хеш`
    -- (`src/db/web_access.py`). Пароль человека в такую строку не попадёт
    -- случайно — он не начинается с метки алгоритма, — поэтому ошибка
    -- «сохранили пароль» становится отказом записи.
    password_hash text not null check (password_hash ~ '^scrypt\$'),
    created_at timestamptz not null default now(),
    -- Отключение — пометка, как снятие проверки в `0010` и отзыв доступа в
    -- `0011`. Строка остаётся: «у кого был доступ» по пустому месту не
    -- восстановить, а именно этот вопрос задают после инцидента.
    disabled_at timestamptz
);

-- Логин уникален ВНУТРИ арендатора, а не глобально. Один и тот же `director`
-- в двух странах — это два разных человека с разными паролями, и глобальная
-- уникальность заставила бы придумывать им разные логины, то есть уводила бы
-- границу арендаторов из схемы в договорённость об именовании.
create unique index web_users_tenant_login_idx on web_users (tenant_code, login);

comment on table web_users is
    'Учётки веб-админки (T323, D155). Заводит их роль владельца схемы, '
    'регистрации снаружи нет. Роль приложения эту таблицу только читает.';
comment on column web_users.password_hash is
    'scrypt с солью, вид scrypt$n$r$p$соль$хеш. Обратимого хранения нет: '
    'ограничение не пропустит в колонку ничего, что не начинается с метки '
    'алгоритма, поэтому «записали пароль» — отказ записи, а не утечка.';
comment on column web_users.disabled_at is
    'Когда учётка отключена. NULL — учётка живая. Отключение действует сразу '
    'и на уже открытые сессии: опознание сверяет учётку на каждом запросе.';

-- --- сессии ------------------------------------------------------------------
--
-- Сессия живёт В БАЗЕ, а не только в куке, и это не запас на будущее. Выход
-- обязан ПРЕКРАЩАТЬ доступ, а подписанная кука без записи на сервере
-- прекращается только в том браузере, где нажали кнопку: снятая копия куки
-- продолжала бы работать до конца срока, и отозвать её было бы нечем.

create table web_sessions (
    id uuid primary key default gen_random_uuid(),
    -- Внешний ключ есть, каскада нет: учётки не удаляются вовсе (см. выше),
    -- поэтому осиротевшей строке взяться неоткуда, а `on delete cascade`
    -- обещал бы удаление, которого в этой схеме не бывает.
    user_id uuid not null references web_users (id),
    -- ОТПЕЧАТОК токена из куки, а не сам токен. Та же колонка и то же
    -- ограничение, что у `mcp_tokens.fingerprint` в `0011`, по той же причине:
    -- 64 знака шестнадцатеричной записи даёт только SHA-256, и сырой токен
    -- (`secrets.token_urlsafe`) в неё физически не запишется.
    fingerprint text not null unique
        check (fingerprint ~ '^[0-9a-f]{64}$'),
    issued_at timestamptz not null default now(),
    -- Срок обязателен и без умолчания: бессрочная сессия — это вечный доступ
    -- по одной украденной куке. Величину называет продукт (`SESSION_TTL`), а
    -- не схема, — чтобы «сколько живёт сессия» правилось в одном месте.
    expires_at timestamptz not null,
    closed_at timestamptz
);

comment on table web_sessions is
    'Открытые сессии веб-админки (T323). Хранится ОТПЕЧАТОК токена из куки; '
    'значение живёт только в браузере. Выход помечает строку закрытой, и '
    'предъявленная снова кука перестаёт работать у всех её копий сразу.';

-- --- права -------------------------------------------------------------------
--
-- Роль приложения: прочитать учётку (сверить пароль), открыть сессию, закрыть
-- свою. Всё остальное — нет.

grant usage on schema public to dodo_audit_app;

-- ТОЛЬКО SELECT. Ни INSERT, ни UPDATE, ни DELETE: подмена `password_hash` у
-- живой строки — это вход под чужим именем, причём след остался бы нетронутым,
-- а отключение учётки чужой рукой — отъём доступа без записи о том, кто его
-- отнял. Права на это нет ни в каком виде, поэтому такая правка невозможна,
-- а не «не предусмотрена кодом».
grant select on web_users to dodo_audit_app;

grant select, insert on web_sessions to dodo_audit_app;

-- А ПРАВИТЬ МОЖНО РОВНО ОДНУ КОЛОНКУ — пометку закрытия. Тот же приём и та же
-- причина, что у `mcp_tokens` в `0011`: политика такого сказать не умеет
-- (`with check` видит только новую строку), а привилегия на колонки выражает
-- это дословно и проверяется одним взглядом в `\dp`. Чем закрыто по существу:
-- продлить чужую сессию правкой `expires_at` нельзя, переписать отпечаток на
-- свой — тоже, а именно это превратило бы чужую живую сессию в свою.
grant update (closed_at) on web_sessions to dodo_audit_app;

-- RLS включается только на сессиях, и это не забывчивость. На учётках
-- разграничение уже сказано привилегиями выше, целиком и без остатка:
-- разрешающая политика поверх них не добавила бы ни одного запрета, а
-- добавила бы строчку, над которой следующий читатель ломал бы голову, что
-- именно она защищает. На сессиях RLS нужен ради ОДНОГО правила ниже —
-- односторонности закрытия, — и без включённого RLS сказать его нечем.
--
-- `force` — по той же причине, что в `0004` и `0011`: владелец таблицы иначе
-- не подчиняется собственным политикам, а односторонность закрытия обязана
-- держать при любой роли. Разрешающая политика нужна отдельно: с включённым
-- RLS и без единой политики не проходит ничего, включая обычный вход.
alter table web_sessions enable row level security;
alter table web_sessions force row level security;

-- Без `to <роль>` намеренно: сессии живут одинаково для всех, кто до них
-- вообще допущен привилегиями, и вторая политика ниже обязана действовать и
-- на роль, о которой мы сегодня не подумали.
create policy web_sessions_access on web_sessions
    for all using (true) with check (true);

-- ЗАКРЫТИЕ ОДНОСТОРОННЕЕ — так же, как отзыв токена в `0011` и снятие
-- проверки в `0010`. Сужающая политика пропускает ровно один переход: живая
-- строка → закрытая.
--
-- `using (closed_at is null)` не пускает правку уже закрытой строки, то есть
-- воскресить сессию нечем; `with check (closed_at is not null)` не даёт
-- правке оставить строку живой. Вместе это и есть обещание «выход
-- действительно прекращает сессию»: снять пометку не может никто, включая
-- владельца схемы.
create policy web_sessions_are_closed_not_reopened on web_sessions
    as restrictive for update
    using (closed_at is null)
    with check (closed_at is not null);
