-- 0018_inspection_reports.sql
--
-- T336 (#317): готовый отчёт проверки перестаёт жить только в телеграме.
--
-- Сегодня PDF собирается при завершении, уходит аудитору в чат — и всё.
-- Показать его в админке нечем, ответить «что именно получил партнёр» нечем,
-- а через год не будет и самого чата. Кадры эту дорогу уже прошли (T094):
-- файл уезжает в хранилище, в базе остаётся ссылка. Отчёт идёт той же.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА В `inspections`. Завершённая проверка
-- заморожена политикой (0004), и это заслон, ради которого всё затевалось:
-- переписать оценку задним числом нельзя. Колонка под ссылку внутри той же
-- строки означала бы дырку в этом заслоне — update по запечатанной проверке
-- пришлось бы разрешить, а RLS не различает колонки в `with check`, поэтому
-- «разрешить только ссылку» на деле стало бы «разрешить строку».
--
-- Отдельная таблица закрывает это без компромисса и заодно отвечает на
-- вопрос, который всё равно пришёл бы следом: отчётов у проверки может быть
-- больше одного — пересобранный без потерянного кадра, присланный повторно
-- (#310 просит того же для письма). Один отчёт в строке, а не колонка,
-- которую однажды начнут перетирать.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

create table reports (
    id uuid primary key default gen_random_uuid(),
    inspection_id uuid not null references inspections(id) on delete cascade,

    -- Ссылка в хранилище — та же форма, что у кадра: `s3://корзина/ключ`, без
    -- адреса сервера и без имени поставщика. Хранилище на этом проекте заведомо
    -- переедет (D054, D061, D166), и ссылка, знающая сегодняшний адрес, сделала
    -- бы переезд правкой каждой строки вместо правки переменных окружения.
    storage_path text not null,

    -- Тип содержимого записан, а не подразумевается: отдавая файл в браузер,
    -- админка обязана назвать тип, а угаданный по расширению тип — это ровно
    -- тот случай, когда документ партнёру открывается как текст.
    content_type text not null default 'application/pdf',

    -- Размер в байтах: по нему видно, что доехало, без обращения к хранилищу.
    size_bytes bigint not null check (size_bytes > 0),

    created_at timestamptz not null default now()
);

create index reports_by_inspection on reports (inspection_id, created_at desc);

comment on table reports is
    'Готовый отчёт проверки, уехавший в хранилище (T336). Файла здесь нет — '
    'только ссылка на него: база хранит историю, файлы лежат в хранилище.';
comment on column reports.storage_path is
    'Ссылка вида s3://корзина/ключ — без адреса сервера и имени поставщика, '
    'чтобы переезд хранилища стоил правки переменных окружения, а не правки '
    'каждой строки.';

alter table reports enable row level security;

alter table reports force row level security;
create policy reports_app_access on reports
    for all to dodo_audit_app using (true) with check (true);

-- Записанный отчёт заморожен — тот же приём, что у кадра
-- (`photos_uploaded_only_once`, 0004). Выгрузка идёт ПОСЛЕ завершения
-- проверки, отдельной транзакцией, поэтому запрет стоит не на статусе
-- проверки, а на самой строке: подменить ссылку на уже записанный отчёт
-- задним числом нельзя ничем. Нужен другой отчёт — появляется НОВАЯ строка,
-- и обе видно.
create policy reports_frozen_once_written on reports
    as restrictive for update
    using (false);

grant select, insert on reports to dodo_audit_app;

grant select on reports to dodo_audit_admin;
