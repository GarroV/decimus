"""Типы, которыми блок `db` разговаривает наружу.

`InspectionRow` — сводка одной проверки для списка (контракт
`list_inspections` в `docs/furca/blocks/db.md`). `FindingRow` — одна
записанная находка, `InspectionDetail` — проверка целиком вместе с находками
(контракт `get_inspection` и `findings_by_unit`, T114).

Ни один из этих типов ничего не считает: числа приходят из базы такими, какими
их положил движок при завершении проверки (конституция, принцип 2).
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from typing import Any

#: Происхождение проверки (`inspections.origin`, миграции 0038 и 0042, D334).
#:
#: `field` — обход из бота, умолчание колонки.
#: `import` — ТЕКУЩАЯ проверка, заведённая задним числом через MCP по действующей
#: версии эталона УК: записи проверяет и оценку считает движок, как у обхода.
#: `legacy` — ИСТОРИЧЕСКАЯ из старого отчёта: оценка перенесена как есть и
#: движком не пересчитывается никогда (D332) — ни при загрузке, ни на приёмке,
#: ни при сверке письма.
#:
#: Обе загруженные читаются рядом с обходами (D306), их подтверждение не
#: открывает запрос экшн-плана и письма партнёру по ним нет (D310, `accept.py`).
ORIGIN_FIELD = "field"
ORIGIN_IMPORT = "import"
ORIGIN_LEGACY = "legacy"
#: Происхождения, которые заводят инструменты загрузки.
UPLOADED_ORIGINS = frozenset({ORIGIN_IMPORT, ORIGIN_LEGACY})

#: Маркеры записи исторической проверки там, где старый отчёт значения не дал
#: (D332, 0042). Явные значения, а не пустота: колонки `not null`, а пустой код
#: пункта читатели приняли бы за поломку. Показ — «без класса», «пункт не
#: назван». `LEGACY_CODE` не совпадает ни с одним кодом чек-листа. Эти же
#: строки литералами стоят в запросах `queries.py` (системные нарушения).
LEGACY_CODE = "LEGACY"
#: «Без класса»: в старом отчёте класса D1–D3 не было (старые чек-листы на
#: 253/217/150 вопросов). Не D0 и не R — у тех свой смысл.
NO_CLASS = "NC"
#: Зона не названа. Пустая строка, а не выдуманная зона: разбивки по зонам у
#: исторической нет, а выдуманный код читатели искали бы в справочнике зон.
NO_ZONE = ""

#: Версия методики исторической проверки — НЕ настоящая версия хранилища:
#: `legacy:<метка>`. Ни один путь не загружает её из хранилища (пересчёта у
#: исторической нет), а по префиксу её видно сразу.
LEGACY_VERSION_PREFIX = "legacy:"


@dataclass(frozen=True)
class InspectionRow:
    """Одна строка списка проверок этого блока."""

    id: str
    tenant_code: str
    unit_name: str
    chat_id: int
    #: Вид проверки КОДОМ (`planned`/`repeat`/`unscheduled`), а не словом
    #: (T152, D025): формулировки переводятся и правятся, коды нет. Показывать
    #: вид человеком обязан тот, кто показывает, — через `domain.kind_title`
    #: и на языке того документа, который печатает.
    kind: str
    inspection_date: date
    report_lang: str
    checklist_version: str
    pct: float
    grade: str
    findings_count: int
    pushed_at: str
    #: Шапка проверки — то, чем письмо партнёру подписано и кому адресовано
    #: (T176). Слив пишет эти поля с самого T091, но чтение их не возвращало, и
    #: письмо, пересобранное по записанной проверке (`src/mcp/letters.py`),
    #: подписывалось прочерком вместо имени аудитора — молча, с нулевым кодом
    #: возврата у движка.
    #:
    #: Пустая строка означает «поле не заполнено», а не «поля нет»: колонки
    #: объявлены `not null default ''`, мастер бота даёт их пропустить, а `None`
    #: вместо пустой строки превратился бы у потребителя в слово «None» в
    #: подписи документа партнёру.
    auditor: str = ""
    city: str = ""
    partner: str = ""
    contact: str = ""
    #: Код чек-листа, по которому считали проверку (T345, D177). Пара
    #: «пространство + код» опознаёт чек-лист целиком (D183) — пространство
    #: появится здесь же, когда будет построено.
    #:
    #: Умолчание `bizdev`, а не пустая строка: до множественности чек-лист был
    #: один — методика бизнес-девелопера (D181), — и у строк, залитых до
    #: миграции, это запись того, что и так было правдой (D033).
    checklist_code: str = "bizdev"
    #: Снята ли проверка из истории (T210, D086, D089) и почему. Пустая
    #: причина при `retracted=False` — не «причину забыли», а «проверка живая»:
    #: схема не даёт ни снятия без причины, ни причины у живой проверки.
    #:
    #: У обычного чтения оба поля всегда пусты, и это не значит «снятых нет»:
    #: снятую проверку прячет построчная политика, и обычная роль её не видит
    #: вовсе. Заполненными они приходят только администратору истории — тому,
    #: кто читает с `include_retracted=True`.
    retracted: bool = False
    retraction_reason: str = ""
    #: Этап приёмки (D199). `on_review` — проверка обойдена, но ещё не вычитана
    #: и не подтверждена человеком; в историю сети она не входит. Кто и когда
    #: подтвердил — пусто у ждущих и у принятых до появления этапа (0034).
    on_review: bool = False
    accepted_at: str = ""
    accepted_by: str = ""
    #: Происхождение (`ORIGIN_*` выше, D334). По нему читатели решают две вещи:
    #: пересчитывать ли оценку движком (у `legacy` — никогда, D332) и есть ли
    #: письмо партнёру (у загруженных — нет, D310).
    origin: str = ORIGIN_FIELD

    @property
    def is_legacy(self) -> bool:
        """Историческая: оценка как в старом отчёте, движок её не трогает (D332)."""
        return self.origin == ORIGIN_LEGACY

    @property
    def is_uploaded(self) -> bool:
        """Заведена задним числом через MCP (текущая или историческая, D334)."""
        return self.origin in UPLOADED_ORIGINS


@dataclass(frozen=True)
class FindingRow:
    """Одна записанная находка вместе с проверкой, из которой она взята.

    Проверка названа прямо в строке (`inspection_id`, `unit_name`,
    `inspection_date`): находка без даты и точки не отвечает ни на один
    вопрос, ради которого её читают («что повторяется у этой пиццерии»), а
    добирать это отдельным запросом на каждую строку — тот самый N+1.
    """

    id: str
    inspection_id: str
    unit_name: str
    inspection_date: date
    n: int
    code: str
    level: str
    zone: str
    zone_unusual: bool
    #: Со слов аудитора или распознано по кадру (D044). Пусто — источник не
    #: записан: так выглядят проверки, заведённые до D044. Пустая строка и NULL
    #: в базе означают здесь одно и то же и склеены намеренно: «не записан» не
    #: бывает двух разных видов.
    source: str
    #: Язык, на котором находка записана (речь аудитора). Формулировки хранятся
    #: строками `(entity_id, lang, text)` (D025), и это поле говорит, какую
    #: строку вернули, — вместо того чтобы выдавать её за единственную.
    lang: str
    #: Формулировка и комментарий на языке `lang`. `None` — строки перевода нет
    #: вовсе; подменять её пустой строкой нельзя, иначе «перевода нет»
    #: становится неотличимо от «аудитор ничего не написал».
    text: str | None
    comment: str | None
    #: Сырые слова аудитора, из которых выросла запись (T183, T185): подпись к
    #: кадру, отдельное сообщение, расшифровка голоса — дословно, на языке
    #: `lang`. Формулировкой записи они не являются: партнёру уходит `text` по
    #: правилам фиксации, а сказанное на точке ему не предназначено.
    #:
    #: Пустая строка — слов не записано: их не было вовсе (разбор голого кадра)
    #: либо запись начата до T183. Двух разных видов у этого нет, поэтому `NULL`
    #: и пустая строка склеены, как у `source`; отличает эти два случая сам
    #: `source` (у первого он `photo`) — так же, как это делает домен.
    words: str = ""
    #: Что предложила модель до того, как аудитор зафиксировал запись (T164,
    #: D077). `None` — модель не предлагала ничего: запись заведена вручную или
    #: до T164. Это не то же самое, что `NONE`/`UNKNOWN` — так модель отвечает
    #: «ничего из перечня не подходит» и «места из слов не видно», то есть это
    #: её ответ, а не отсутствие ответа.
    suggested_code: str | None = None
    suggested_level: str | None = None
    suggested_zone: str | None = None
    #: Доля от 0 до 1. Диапазон стережёт схема: по этой величине управляющая
    #: компания ставит порог отбора, и чужая шкала обесценила бы выборку целиком.
    suggested_confidence: float | None = None
    #: Аудитор отметил запись как повтор нарушения предыдущей проверки: вычет
    #: за неё удвоен (D191, #359).
    repeat: bool = False

    def corrections(self) -> tuple[str, ...]:
        """Что из предложенного моделью аудитор поправил: `code`, `level`, `zone`.

        Считается сравнением двух троек ЭТОЙ ЖЕ строки, а не читается из базы:
        записанный отдельно, такой список стал бы третьей копией факта, который
        уже есть, — и разъехался бы с парой, из которой считается, молча.

        Пустой кортеж означает две разные вещи, и различает их само
        предложение: модель попала (предложение есть и совпало) или модели не
        было вовсе (`suggested_code is None`). Слить их в «правок нет» здесь
        можно, потому что ни то, ни другое не идёт в предложения для
        управляющей компании; разделяет их тот, кто спрашивает, — по наличию
        предложения.
        """
        if self.suggested_code is None:
            return ()
        пары = (
            ("code", self.suggested_code, self.code),
            ("level", self.suggested_level, self.level),
            ("zone", self.suggested_zone, self.zone),
        )
        return tuple(поле for поле, предложено, записано in пары if предложено != записано)


@dataclass(frozen=True)
class PreviousInspection:
    """Предыдущая проверка точки глазами подсказки о повторе (#359, D255).

    Ровно два факта: когда был прошлый обход и какие пункты тогда оказались
    нарушениями. Дата нужна вопросу аудитору («в прошлый раз, такого-то
    числа…»): без неё он не отличит прошлую неделю от прошлого года.
    """

    date: date
    codes: frozenset[str]


@dataclass(frozen=True)
class PreviousFinding:
    """Одно нарушение прошлой проверки — то, на что аудитору смотреть сегодня.

    `text` — формулировка той записи на языке речи той проверки, а не вопрос
    методики: «пятно на столе у окна» подсказывает, куда смотреть, а «столы
    чистые» — нет. `None` — строки перевода нет; экран тогда берёт вопрос
    методики по коду.
    """

    code: str
    level: str
    zone: str
    text: str | None


@dataclass(frozen=True)
class PreviousFindings:
    """Прошлая проверка точки с её нарушениями — для мини-аппа обхода (#418).

    Та же прошлая проверка, что у вопроса о повторе (`PreviousInspection`):
    подсказка «здесь было» и вопрос «считать ×2?» обязаны говорить об одном
    обходе, иначе аудитор увидит в них два разных прошлых.
    """

    date: date
    findings: tuple[PreviousFinding, ...]


@dataclass(frozen=True)
class ItemUsage:
    """Как часто пункт методики нарушают — по сданным неотклонённым проверкам (D197).

    Сводка для панели пункта: по ней видно, какой пункт работает, а какой
    мёртвый (не нарушен ни разу) или бьёт по одним и тем же точкам. Это счёт
    записей, а не оценка: процент и буква остаются делом движка.
    """

    code: str
    records: int
    units: int
    inspections: int
    last_date: date | None
    #: `(класс, записей)` по классам, от D1 к D3.
    by_level: tuple[tuple[str, int], ...]
    #: `(точка, id точки, записей)` — самые частые, не больше пяти.
    top_units: tuple[tuple[str, str, int], ...]


@dataclass(frozen=True)
class InfoRow:
    """Одно поле информационной части записанной проверки (T200).

    Не находка и не замер: на оценку эти поля не влияют вовсе, но печатаются
    партнёру приложением отчёта, а срок плана действий читает из них письмо.
    Пункт назван КОДОМ методики (`INF01`, `INF07`, …) — формулировку вопроса
    подставляет тот, кто печатает, и на языке того документа, который печатает.

    Ответ отдаётся дословно и без языка. Языка у информационной части нет
    одного: свободный текст записан на языке речи аудитора, «да/нет» — на языке
    отчёта, дата не на языке вовсе. Переводить ответ при этом не полагается
    никому — движок печатает его как записан на любом языке отчёта, — и подпись
    «это по-сербски» была бы у двух полей из трёх неверной.

    Кадров здесь нет по той же причине, по какой их нет у `FindingRow`: они
    лежат в хранилище за ссылками, а потребителя, который печатал бы отчёт по
    записанной проверке, сегодня нет — письмо кадров не носит. В базе кадр поля
    при этом хранится и выгружается (`photos.info_id`), то есть не теряется.
    """

    code: str
    text: str


@dataclass(frozen=True)
class InspectionDetail:
    """Проверка целиком: сводка, разбивка оценки, находки и информационная часть.

    `counts`, `by_zone` и `deductions` отдаются в том виде, в каком их положил
    движок: это его `Score`, а не пересчёт. Форму этих полей блок `db` не
    разбирает и не проверяет — он их хранит и возвращает.
    """

    inspection: InspectionRow
    deductions: float
    counts: dict[str, Any]
    by_zone: dict[str, Any]
    findings: tuple[FindingRow, ...]
    #: Информационная часть в ЗАПИСАННОМ порядке, а не отсортированная по коду
    #: (T200): движок печатает поля в том порядке, в каком их записали, и это
    #: порядок разделов документа партнёру.
    #:
    #: Пустой кортеж означает две разные вещи, и различить их изнутри этого
    #: блока нечем: аудитор пропустил все поля (D070 разрешает пропустить любое)
    #: либо проверка слита до T200, когда информационной части в базе не было
    #: вовсе. Тот, кто собирает по этим полям документ, обязан считать пустоту
    #: невосстановленной частью, а не «аудитор ничего не сказал».
    info: tuple[InfoRow, ...] = ()
    #: Только у исторической (`legacy`, D332): статус из старого отчёта словами
    #: и метка прежней методики. Пусто у всех остальных.
    reported_status: str = ""
    legacy_method: str = ""
