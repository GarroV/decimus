"""Проверка: методика управляющей компании не цитируется в репозитории (#138, #854).

Без зависимостей, на одной стандартной библиотеке: боевая методика лежит там,
где нет pytest, — на сервере прода, — и проверка идёт шагом выкатки
(`scripts/prod-update.sh`), а не тестом, который в CI пропускается молча.
Тест `tests/test_methodology_leak.py` зовёт эти же функции.

    python3 tools/methodology_leak.py [<каталог методики>] [--tracked-only]

Нашла цитату — печатает находки и выходит с кодом 1; методики нет — кодом 2:
«не проверялось» не выдаётся за «чисто».

Почему проверка устроена именно так — история промахов в докстроке теста.
"""

from __future__ import annotations

import csv
import re
import subprocess
import sys
from collections.abc import Iterator
from pathlib import Path

#: Класс стоит в методике и в начале строки, и в конце — одного правила мало.
_КЛАСС = re.compile(r"^\s*\((?:D[123])(?:,\s*D[123])*\)\s*|\s*\((?:D[123])(?:,\s*D[123])*\)\s*$")

#: Короче этого фрагмент ловит служебный шум, а не цитату. Порогов ДВА, и это
#: не придирка: единый порог в 12 знаков пропускал название зоны длиной 11
#: знаков — оно короче порога, но это полноценная цитата. Ровно та ошибка,
#: которую этот файл и заведён
#: ловить: порог собственного изготовления отсекает находку, и «ничего не
#: найдено» выглядит как чистота.
#:
#: Названия зон конкретны сами по себе, им хватает пяти знаков. Формулировкам
#: вопросов и ячейкам таблицы порог нужен выше: там короткий фрагмент — это
#: служебный обрывок вроде «см.» или «нет».
МИН_ДЛИНА = 12
МИН_ДЛИНА_ЗОНЫ = 5

#: Что цитатой НЕ считается, с причиной на каждую строку. Список короткий
#: намеренно: без него тест утонет в шуме и его заглушат целиком.
#:
#: * `Поломка` — заголовок колонки таблицы подсказок, от него зависит разбор
#:   в продукте (`recognize.cues`), убрать нельзя, не сломав быстрый путь;
#: * `Вид проверки` / `Inspection type` — собственная надпись мастера бота,
#:   совпадающая с формулировкой поля методики. Совпадение, а не копия;
#: * `# Критерии нарушений по вопросам` — заголовок файла критериев, который
#:   оснастка пишет для своего синтетического набора.
ИСКЛЮЧЕНИЯ = frozenset(
    {
        "Поломка",
        "Вид проверки",
        "Inspection type",
        "# Критерии нарушений по вопросам",
        # То же без решётки: нормализация снимает markdown-разметку, и
        # заголовок доходит сюда уже очищенным. Его пишет сам движок при
        # выгрузке критериев, то есть это имя формата, а не содержание.
        "Критерии нарушений по вопросам",
        # `Freezer` — название зоны длиной 7 знаков и одновременно обычное
        # английское слово. Первый же тест, упомянувший морозильник
        # по-английски, дал бы ложную находку, а ложная находка — самый
        # быстрый путь к тому, что тест заглушат целиком.
        "Freezer",
    }
)

#: Коды пунктов и зон цитатой не являются: это идентификаторы, которыми
#: продукт связывает сущности по жёсткому правилу проекта, и они были в
#: репозитории всегда. Ловим текст, а не коды — в том числе ячейку из
#: нескольких кодов через запятую: она тоже перечень идентификаторов.
_КОД = re.compile(r"^[A-Z]{2,4}\d{2}(?:\s*,\s*[A-Z]{2,4}\d{2})*$")


def _норма(s: str) -> str:
    return _КЛАСС.sub("", (s or "").strip()).rstrip(".").strip()


def needles(data: Path) -> tuple[set[str], set[str]]:
    """Всё, что не должно встречаться в репозитории, — прямо из методики.

    Второе значение — названия зон: они сверяются иначе, чем остальное."""
    иглы: set[str] = set()

    with (data / "checklist.csv").open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            for ключ in ("question_ru", "question_en"):
                иглы.add(_норма(row.get(ключ) or ""))

    зоны: set[str] = set()
    with (data / "zones.csv").open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            for ключ in ("name_ru", "name_en"):
                зоны.add(_норма(row.get(ключ) or ""))

    # Критерии — самое чувствительное, что есть в методике: дословные правила
    # «что считать каким классом» плюс ссылки на внутренние стандарты. Формулировку
    # вопроса можно угадать по смыслу, критерий — нет, это и есть ноу-хау
    # управляющей компании. До 04.09.2026 их тут не было вовсе: иглы строились
    # по вопросам, зонам и подсказкам, и строка критериев проходила насквозь.
    for строка in (data / "criteria.md").read_text(encoding="utf-8").splitlines():
        текст = _норма(строка.lstrip("#*-| ").strip())
        if len(текст) >= МИН_ДЛИНА:
            иглы.add(текст)

    # ВСЕ ячейки таблицы подсказок, а не первая: пороги классов живут в
    # остальных колонках, и именно поэтому их не находили два прохода подряд.
    for line in (data / "photo-cues.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("|") and line.count("|") >= 3:
            for ячейка in line.split("|"):
                иглы.add(_норма(ячейка))

    зоны_годные = {з for з in зоны if len(з) >= МИН_ДЛИНА_ЗОНЫ}
    годные = {и for и in иглы if len(и) >= МИН_ДЛИНА} | зоны_годные
    return {и for и in годные if и not in ИСКЛЮЧЕНИЯ and not _КОД.match(и)}, зоны_годные


#: Что выведено за скобки — и это НЕ «markdown», а именно документы. Разница
#: не словесная: `tests/methodology/*.md` — не дока, а данные, которыми идёт
#: весь набор, то есть первое место, куда следующий человек скопирует боевую
#: формулировку «чтобы было похоже на настоящее». Пока фильтр стоял по
#: расширению, фикстура не проверялась вовсе.
#:
#: Документы вне проверки по решению владельца о видимости репозитория (D073):
#: там названия зон стоят по построению, и красить ими сборку бессмысленно.
ВНЕ_ПРОВЕРКИ = ("docs/", "progress.md", "tasks.md", "CHANGELOG.md")


def outside_check(относительный: Path) -> bool:
    имя = относительный.as_posix()
    return any(имя.startswith(x) for x in ВНЕ_ПРОВЕРКИ)


#: Как читается файл перед поиском. Цитату, разорванную переносом строки,
#: простое вхождение НЕ находит — на этом детектор пропустил дословную строку
#: методики в докстроке модуля, разбитую по ширине строки (нашёл её человек,
#: а не эта проверка). Поэтому перед сравнением снимаются знаки комментариев
#: и схлопываются пробелы: цитата остаётся цитатой, как её ни переноси.
_РАЗМЕТКА = re.compile(r"^[ \t]*[#*>-]+[ \t]?", re.M)


def flat(текст: str) -> str:
    """Текст, приведённый к виду, в котором цитату не спрятать переносом."""
    return re.sub(r"\s+", " ", _РАЗМЕТКА.sub(" ", текст))


#: Как сравнивается игла с текстом, и почему по-разному.
#:
#: Формулировки вопросов и строки карты — цитаты в любом регистре: смена
#: заглавной буквы цитату цитатой быть не перестаёт. Блок нашёл свою докстроку
#: с дословной строкой карты, прошедшую мимо детектора ровно первой буквой.
#:
#: Названия зон — иначе. По правилу проекта в коде живут ПРОИЗНОСИМЫЕ формы
#: («зал», «горячий цех» строчными) — это не цитата, а то, как зону называют
#: вслух; без них не работает разбор слов аудитора. Цитатой название становится
#: в том виде, в каком стоит в методике, — с заглавной. Поэтому зоны сверяются
#: с учётом регистра, всё остальное — без.
def occurs(игла: str, текст: str, *, zones: set[str]) -> bool:
    return игла in текст if игла in zones else игла.lower() in текст.lower()


def published_files(корень: Path, *, untracked: bool = True) -> Iterator[Path]:
    """Файлы, которые уедут в публичный репозиторий: и отслеживаемые, и НОВЫЕ.

    Новые здесь не для полноты. Именно их и создаёт каждый блок стройки, и
    именно они уезжают следующим коммитом — а сторож, спрашивавший только
    `ls-files`, их не видел вовсе (задача #204). Проверено опытом: полное
    название зоны в новом файле проходило насквозь, и покраснел бы сторож
    впервые уже ПОСЛЕ того, как файл попал в историю, откуда его не убрать.

    Игнорируемое не берётся: `data/` и `examples/` лежат вне git намеренно
    (D002) и состоят из методики целиком — сторож на них покраснел бы всегда.
    Ровно поэтому спрашивается git, а не обход каталога: он один знает, что
    уедет наружу, а что нет.
    """
    вывод = subprocess.run(  # noqa: S603 — аргументы свои, не ввод
        # `--cached` — отслеживаемые, `--others` с `--exclude-standard` — новые
        # мимо .gitignore. Вместе это и есть «что уедет в публичный репозиторий».
        #
        # `-z` не украшение: без него git ЭКРАНИРУЕТ имена с кириллицей и
        # пробелами (`"src/\320\277..."`), такого пути на диске нет, `is_file`
        # отвечает «нет» — и файл пропускается молча. Проверено опытом: игла в
        # файле с русским именем проходила насквозь и на исправленном списке.
        [  # noqa: S607 — git из PATH, аргументы свои
            "git",
            "ls-files",
            "-z",
            "--cached",
            *(("--others", "--exclude-standard") if untracked else ()),
        ],
        cwd=корень,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    for имя in вывод.split("\0"):
        if not имя:
            continue
        путь = корень / имя
        if путь.is_file():
            yield путь


def scan(корень: Path, data: Path, *, untracked: bool = True) -> list[str]:
    """Находки «файл: игла» по всем файлам, что уедут в публичный репозиторий."""
    иглы, зоны = needles(data)
    if not иглы:
        raise RuntimeError("иглы не собрались — проверка перестала что-либо проверять")
    находки: list[str] = []
    for путь in published_files(корень, untracked=untracked):
        if outside_check(путь.relative_to(корень)):
            continue
        try:
            текст = flat(путь.read_text(encoding="utf-8"))
        except (UnicodeDecodeError, OSError):
            continue
        находки.extend(
            f"{путь.relative_to(корень)}: «{игла[:40]}»"
            for игла in иглы
            if occurs(игла, текст, zones=зоны)
        )
    return sorted(находки)


def main(argv: list[str]) -> int:
    корень = Path(__file__).resolve().parents[1]
    позиционные = [a for a in argv if not a.startswith("--")]
    data = Path(позиционные[0]) if позиционные else корень / "data"
    if not (data / "checklist.csv").is_file():
        print(f"методики нет в {data} — утечка НЕ проверялась", file=sys.stderr)
        return 2
    находки = scan(корень, data, untracked="--tracked-only" not in argv)
    if находки:
        print(
            f"УТЕЧКА МЕТОДИКИ: процитирована в репозитории ({len(находки)} шт.), а он публичный:",
            file=sys.stderr,
        )
        for строка in находки:
            print(f"  {строка}", file=sys.stderr)
        return 1
    print("методика в репозитории не цитируется")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
