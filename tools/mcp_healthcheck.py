"""Проба здоровья MCP-сервера — изнутри его контейнера (задача T255, #210).

Отвечает ровно на один вопрос: **на петле контейнера отвечает НАШ сервер, и
дверь у него на месте**. На вопрос «доступен ли сервер с чужой машины» она не
отвечает и отвечать не может — на него отвечает `tools/mcp_outside.py`.
Путать эти два ответа нельзя: поломка, ради которой заведена задача, состояла
ровно в том, что изнутри всё выглядело поднятым, а добраться снаружи было
некуда.

**Почему проба стучится, а не смотрит на процесс.** Образ один на бот и на
сервер, и запечённая в него проверка ищет процесс бота (`pgrep -f "python -m
src.bot"`, см. `Dockerfile`) — для сервера она была бы красной всегда. Но
причина глубже: процесс, живой и переставший отвечать на сокете, — обычный
исход, а здоровьем сервера считается ответ, а не строка в `ps`.

**Почему запрос БЕЗ токена, и почему здоровьем считается отказ 401.** Токена у
пробы нет и быть не должно: она живёт в описании стенда, которое лежит в
публичном репозитории, а секреты живут в `.env`. Отказ 401 при этом — лучшее
доказательство здоровья, какое достижимо без секрета: до него запрос проходит
и приём соединения, и разбор тела заголовков, и разбор заголовка авторизации,
то есть дверь на месте и заперта. Ответ 200 без токена был бы поводом гасить
сервер, а не признаком здоровья, — и проба честно назовёт его провалом.

**Почему сверяется заголовок `Server`.** Площадка общая: рядом живут чужие
проекты, и на том же порту петли мог оказаться чужой процесс. Проба, которая
радуется любому 401, однажды порадуется чужому.

**Почему адресов ДВА, а не один (T279, #243).** 17.09.2026 снаружи сервер
отдавал 502, а контейнер стоял `healthy`: проба стучалась на порт сервера
(8265) и честно получала 401. Сломано было следующее звено — socat из сервиса
`link`, который слушает 8266 в том же сетевом пространстве и шлёт на 8265.
Контейнер `mcp` пересоздали, `link` остался в сетевом пространстве, которого
больше нет; порт 8266 в новом пространстве не слушал никто, и весь путь
снаружи обрывался там. Проба этого не видела, потому что мерила не тот отрезок,
по которому идёт пользователь.

Поэтому там, где звено объявлено (`COMPOSE_PROFILES` содержит `funnel`), проба
стучится ВТОРЫМ адресом — на порт звена, — и требует от него того же: отказа
401 от нашего сервера. Это единственный отрезок пути, который виден изнутри
стенда целиком: от порта, куда приходит трафик снаружи, до сервера. Дальше —
публикация на петлю хоста и общий вход площадки, и на них отвечает
`tools/mcp_outside.py` с чужой машины, а не проба контейнера: здоровье
контейнера не имеет права зависеть от чужого туннеля и от интернета.

**Красная проба не чинит, а показывает.** Docker не перезапускает контейнер по
`unhealthy`, и это не недосмотр: осиротевшее звено лечится пересозданием
`link`, а не перезапуском сервера. Ценность проверки здесь в том, что молчание
кончилось.

Запуск (в контейнере, из `docker-compose.yml`):

    python tools/mcp_healthcheck.py

Код возврата 0 — здоров, 1 — нет; причина печатается одной строкой в stderr.
"""

from __future__ import annotations

import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

# Корень репозитория в пути — тем же приёмом и по той же причине, что у сида
# демо (`tools/seed_demo.py`). Editable-установка кладёт в `sys.path` каталог
# `src`, а не корень рядом с ним, поэтому запущенный по имени файла скрипт
# пакет `src` не видит. Проверено запуском в контейнере: без этих двух строк
# проба падала на импорте, и контейнер считался НЕЗДОРОВЫМ по причине, к
# здоровью сервера отношения не имеющей.
REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from src.mcp.config import (  # noqa: E402 -- путь к репозиторию выставляется выше
    DEFAULT_HOST,
    DEFAULT_PORT,
    MCP_HOST_VAR,
    MCP_PORT_VAR,
)

#: Имя, которым представляется наш сервер в заголовке `Server`
#: (`src/mcp/server.py`, `_Handler.server_version`). Копия строки, и это
#: осознанно: проба обязана оставаться независимой от графа импортов продукта.
#: Расхождение копий ловит тест живым ответом, а не площадка.
SERVER_HEADER = "dodo-audit-mcp"

#: Сколько ждём ответа. Меньше, чем `timeout` у проверки в `docker-compose.yml`:
#: проба обязана успеть сказать «нет» сама, а не быть убитой снаружи — убитая
#: снаружи, она не печатает причину.
TIMEOUT_SEC = 3.0

#: Здоровьем считается ровно этот код: запрос без токена отвергнут.
EXPECTED_STATUS = 401

#: Переменная, которой compose сообщает контейнеру, какие профили стенда
#: включены. Она же решает, поднимается ли звено, — поэтому она же и решает,
#: обязано ли оно отвечать. Второго признака «звено ожидается» заводить нельзя:
#: он разошёлся бы с первым, и проба требовала бы звена там, где его нет, либо
#: молчала бы там, где оно должно быть.
COMPOSE_PROFILES_VAR = "COMPOSE_PROFILES"

#: Профиль, с которым поднимается звено (`docker-compose.yml`, сервис `link`).
FUNNEL_PROFILE = "funnel"

#: Порт звена ВНУТРИ сетевого пространства контейнера: на нём слушает socat
#: (`TCP-LISTEN:8266` в описании стенда) и на него же смотрит публикация порта
#: наружу. Копия числа, и её расхождение с описанием стенда ловит тест, а не
#: площадка, — тем же приёмом и по той же причине, что `SERVER_HEADER` выше.
DEFAULT_LINK_PORT = 8266

#: Чем номер звена можно переназначить. Нужна ровно в двух случаях: стенд, где
#: socat слушает другой порт, и проверки — им нужен свободный номер, а не
#: занятый на машине.
MCP_LINK_PORT_VAR = "MCP_LINK_PORT"


def probe_url(env: dict[str, str] | None = None) -> str:
    """Адрес, по которому стучимся, — тот же, на котором слушает сервер.

    Берётся из тех же переменных и с теми же умолчаниями, что у самого сервера
    (`src/mcp/config.py`), а не задаётся своей парой: второе описание одного и
    того же адреса разошлось бы с первым молча, и проба стучалась бы не туда,
    показывая при этом здоровье.
    """
    src = os.environ if env is None else env
    host = (src.get(MCP_HOST_VAR) or "").strip() or DEFAULT_HOST
    port = (src.get(MCP_PORT_VAR) or "").strip() or str(DEFAULT_PORT)
    return f"http://{host}:{port}/"


def verdict(url: str) -> str | None:
    """`None` — здоров. Строка — причина, по которой нет.

    Пустое тело и `POST`: сервер отвечает только на `POST`, а разбирать тело он
    начинает уже после проверки токена — то есть до неё дело не дойдёт, и
    посылать что-то осмысленное незачем.
    """
    request = urllib.request.Request(  # noqa: S310 — схема http на свою же петлю
        url, data=b"", headers={"Content-Type": "application/json"}, method="POST"
    )
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT_SEC) as ответ:  # noqa: S310
            return (
                f"сервер ответил {ответ.status} на запрос БЕЗ токена — "
                f"ожидался отказ {EXPECTED_STATUS}: дверь открыта настежь"
            )
    except urllib.error.HTTPError as отказ:
        код, заголовки = int(отказ.code), отказ.headers
    except OSError as беда:
        # Сюда попадает и «соединение отвергнуто», и таймаут: сервер не поднят,
        # ещё не начал слушать или замолчал.
        return f"нет ответа по {url}: {беда}"

    if код != EXPECTED_STATUS:
        return f"сервер ответил {код} на запрос без токена — ожидался {EXPECTED_STATUS}"
    представился = (заголовки.get("Server") or "").strip()
    if представился != SERVER_HEADER:
        return (
            f"на {url} отвечает не наш сервер: заголовок Server = {представился!r}, "
            f"ожидался {SERVER_HEADER!r}"
        )
    return None


def link_url(env: dict[str, str] | None = None) -> str | None:
    """Адрес звена, если оно на этом стенде объявлено. `None` — не объявлено.

    Возврат `None` вместо тихой подстановки умолчания: решение «спрашивать ли
    со звена» принимает вызывающий и принимает его по одному признаку —
    включённому профилю. На стенде разработчика звена нет вовсе, и требовать с
    него ответа означало бы красный контейнер при исправном сервере.
    """
    src = os.environ if env is None else env
    профили = (src.get(COMPOSE_PROFILES_VAR) or "").split(",")
    if FUNNEL_PROFILE not in {профиль.strip() for профиль in профили}:
        return None
    host = (src.get(MCP_HOST_VAR) or "").strip() or DEFAULT_HOST
    port = (src.get(MCP_LINK_PORT_VAR) or "").strip() or str(DEFAULT_LINK_PORT)
    return f"http://{host}:{port}/"


def probes(env: dict[str, str] | None = None) -> list[tuple[str, str]]:
    """Что проба обязана опросить на этом стенде: пары «чей отрезок, адрес».

    Первым — сам сервер: без него остальное бессмысленно. Вторым — звено, если
    оно объявлено. Имя отрезка идёт в сообщение: «нет ответа» без указания, чей
    порт молчит, отправляет читателя перезапускать сервер, который работает.
    """
    адреса = [("сервер", probe_url(env))]
    звено = link_url(env)
    if звено is not None:
        адреса.append(("звено (socat, сервис link)", звено))
    return адреса


def main() -> int:
    for чей, url in probes():
        причина = verdict(url)
        if причина is not None:
            print(f"[mcp-healthcheck] {чей}: {причина}", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
